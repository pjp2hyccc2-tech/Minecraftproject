package com.huntcraft.village.world;

import com.huntcraft.HuntCraft;
import com.huntcraft.village.VillageRegistry;
import com.huntcraft.village.npc.NpcRole;
import com.huntcraft.village.npc.TrainingDummy;
import com.huntcraft.village.npc.VillageNpc;
import net.minecraft.core.BlockPos;
import net.minecraft.core.Vec3i;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.entity.Entity;
import net.minecraft.world.entity.EntityType;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructurePlaceSettings;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplate;
import net.minecraft.world.level.levelgen.structure.templatesystem.StructureTemplateManager;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

/**
 * Places Kazami village (structure tiles village_I_J.nbt generated by tools/village/gen_village.py) and its NPCs.
 * Built once per world on the first visit (flag in {@link VillageSavedData}; a newer layout version rebuilds it).
 */
public final class VillageBuilder {
    private VillageBuilder() {
    }

    public static BlockPos origin() {
        return new BlockPos(VillageLayout.ORIGIN_X, VillageLayout.ORIGIN_Y, VillageLayout.ORIGIN_Z);
    }

    /** World position of a layout coordinate when the village is placed at {@code origin}. */
    public static double[] at(BlockPos origin, double x, double y, double z) {
        return new double[]{origin.getX() + (x - VillageLayout.ORIGIN_X), origin.getY() + (y - VillageLayout.ORIGIN_Y),
                origin.getZ() + (z - VillageLayout.ORIGIN_Z)};
    }

    public static boolean isBuilt(ServerLevel level) {
        return VillageSavedData.get(level).builtVersion >= VillageLayout.VERSION;
    }

    /** Builds the village in the village dimension if it has not been built yet. */
    public static boolean ensureBuilt(ServerLevel level) {
        VillageSavedData data = VillageSavedData.get(level);
        if (data.builtVersion >= VillageLayout.VERSION) return false;
        long t0 = System.currentTimeMillis();
        int tiles = placeTemplates(level, origin());
        spawnAll(level, origin(), data);
        data.builtVersion = VillageLayout.VERSION;
        data.setDirty();
        HuntCraft.LOGGER.info("Kazami village built ({} tiles) in {} ms", tiles, System.currentTimeMillis() - t0);
        return true;
    }

    /** Places every village tile at {@code origin}. Returns the number of tiles placed. */
    public static int placeTemplates(ServerLevel level, BlockPos origin) {
        StructureTemplateManager mgr = level.getStructureManager();
        StructurePlaceSettings settings = new StructurePlaceSettings().setIgnoreEntities(true);
        int placed = 0;
        for (int i = 0; i < VillageLayout.TILES_X; i++) {
            for (int j = 0; j < VillageLayout.TILES_Z; j++) {
                Optional<StructureTemplate> opt = mgr.get(HuntCraft.id("village_" + i + "_" + j));
                if (opt.isEmpty()) {
                    HuntCraft.LOGGER.warn("Missing village tile village_{}_{}", i, j);
                    continue;
                }
                StructureTemplate t = opt.get();
                BlockPos at = origin.offset(i * VillageLayout.TILE, 0, j * VillageLayout.TILE);
                Vec3i size = t.getSize();
                for (int cx = at.getX() >> 4; cx <= (at.getX() + size.getX()) >> 4; cx++) {
                    for (int cz = at.getZ() >> 4; cz <= (at.getZ() + size.getZ()) >> 4; cz++) level.getChunk(cx, cz);
                }
                t.placeInWorld(level, at, at, settings, level.random, Block.UPDATE_CLIENTS);
                placed++;
            }
        }
        return placed;
    }

    /** Spawns every NPC + dummy (recording their UUIDs when {@code data} is given). Returns the spawned entities. */
    public static List<Entity> spawnAll(ServerLevel level, BlockPos origin, @Nullable VillageSavedData data) {
        List<Entity> out = new ArrayList<>();
        for (int i = 0; i < VillageLayout.NPC_ROLES.length; i++) {
            Entity e = spawnNpc(level, origin, i);
            if (e != null) {
                out.add(e);
                if (data != null) data.setNpc(VillageLayout.NPC_ROLES[i], e.getUUID());
            }
        }
        if (data != null) data.dummies.clear();
        for (int i = 0; i < VillageLayout.DUMMY_POS.length; i++) {
            Entity e = spawnDummy(level, origin, i);
            if (e != null) {
                out.add(e);
                if (data != null) data.dummies.add(e.getUUID());
            }
        }
        if (data != null) data.setDirty();
        return out;
    }

    public static EntityType<VillageNpc> typeFor(NpcRole role) {
        return role.mofu ? VillageRegistry.MOFU_NPC.get() : VillageRegistry.HUMAN_NPC.get();
    }

    @Nullable
    public static VillageNpc spawnNpc(ServerLevel level, BlockPos origin, int idx) {
        NpcRole role = NpcRole.byName(VillageLayout.NPC_ROLES[idx]);
        double[] p = VillageLayout.NPC_POS[idx];
        double[] w = at(origin, p[0], p[1], p[2]);
        level.getChunk(BlockPos.containing(w[0], w[1], w[2]));
        VillageNpc npc = typeFor(role).create(level);
        if (npc == null) return null;
        npc.moveTo(w[0], w[1], w[2], (float) p[3], 0);
        npc.setRole(role);
        npc.setHome(BlockPos.containing(w[0], w[1], w[2]), (float) p[3]);
        level.addFreshEntity(npc);
        return npc;
    }

    @Nullable
    public static TrainingDummy spawnDummy(ServerLevel level, BlockPos origin, int idx) {
        double[] p = VillageLayout.DUMMY_POS[idx];
        double[] w = at(origin, p[0], p[1], p[2]);
        level.getChunk(BlockPos.containing(w[0], w[1], w[2]));
        TrainingDummy d = VillageRegistry.TRAINING_DUMMY.get().create(level);
        if (d == null) return null;
        d.moveTo(w[0], w[1], w[2], (float) p[3], 0);
        d.setYHeadRot((float) p[3]);
        d.setYBodyRot((float) p[3]);
        level.addFreshEntity(d);
        return d;
    }

    /** Respawns NPCs / dummies that went missing (only checks loaded, entity-ticking spots). */
    public static void maintain(ServerLevel level) {
        VillageSavedData data = VillageSavedData.get(level);
        if (data.builtVersion <= 0) return;
        BlockPos origin = origin();
        for (int i = 0; i < VillageLayout.NPC_ROLES.length; i++) {
            double[] p = VillageLayout.NPC_POS[i];
            BlockPos pos = BlockPos.containing(p[0], p[1], p[2]);
            if (!level.isPositionEntityTicking(pos)) continue;
            UUID id = data.npcUuid(VillageLayout.NPC_ROLES[i]);
            if (id != null && level.getEntity(id) != null) continue;
            VillageNpc npc = spawnNpc(level, origin, i);
            if (npc != null) data.setNpc(VillageLayout.NPC_ROLES[i], npc.getUUID());
        }
        for (int i = 0; i < VillageLayout.DUMMY_POS.length; i++) {
            double[] p = VillageLayout.DUMMY_POS[i];
            BlockPos pos = BlockPos.containing(p[0], p[1], p[2]);
            if (!level.isPositionEntityTicking(pos)) continue;
            UUID id = i < data.dummies.size() ? data.dummies.get(i) : null;
            if (id != null && level.getEntity(id) != null) continue;
            TrainingDummy d = spawnDummy(level, origin, i);
            if (d == null) continue;
            while (data.dummies.size() <= i) data.dummies.add(d.getUUID());
            data.dummies.set(i, d.getUUID());
            data.setDirty();
        }
    }

    /** Forces a full rebuild (admin command). */
    public static void rebuild(ServerLevel level) {
        VillageSavedData data = VillageSavedData.get(level);
        data.builtVersion = 0;
        ensureBuilt(level);
    }
}
