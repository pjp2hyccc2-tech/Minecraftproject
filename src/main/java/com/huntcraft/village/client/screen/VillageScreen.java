package com.huntcraft.village.client.screen;

import com.huntcraft.HuntCraft;
import com.huntcraft.data.HunterData;
import com.huntcraft.village.VillageRegistry;
import com.huntcraft.village.client.ClientVillage;
import net.minecraft.client.Minecraft;
import net.minecraft.client.gui.GuiGraphics;
import net.minecraft.client.gui.screens.Screen;
import net.minecraft.client.gui.screens.inventory.InventoryScreen;
import net.minecraft.client.resources.sounds.SimpleSoundInstance;
import net.minecraft.nbt.CompoundTag;
import net.minecraft.network.chat.Component;
import net.minecraft.network.chat.FormattedText;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.sounds.SoundEvents;
import net.minecraft.util.FormattedCharSequence;
import net.minecraft.util.Mth;
import net.minecraft.world.entity.LivingEntity;
import net.minecraft.world.entity.player.Player;
import net.minecraft.world.item.ItemStack;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.api.distmarker.OnlyIn;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;

/**
 * Base class of the village screens: draws panels / buttons / tabs / icons from textures/gui/village/widgets.png
 * (512x512, generated by tools/village/gen_gui.py) and handles simple clickable regions. Every screen must render with
 * an empty open tag (the dev autotest opens them that way).
 */
@OnlyIn(Dist.CLIENT)
public abstract class VillageScreen extends Screen {
    public static final ResourceLocation WIDGETS = HuntCraft.id("textures/gui/village/widgets.png");
    public static final int ATLAS = 512;
    public static final int ICON_V = 64, DISH_V = 96, FACE_U = 0, FACE_V = 160;
    // text colours
    public static final int INK = 0xFF3B2A1A;
    public static final int INK_SOFT = 0xFF6B5238;
    public static final int LIGHT = 0xFFF4E9D0;
    public static final int GOLD = 0xFFFFD46A;
    public static final int GOOD = 0xFF6FD06A;
    public static final int BAD = 0xFFFF6A5A;
    public static final int GREY = 0xFF9A9088;
    public static final int OK_DARK = 0xFF2E8B2E;
    public static final int BAD_DARK = 0xFFC0392B;
    // icon indices (16x16, 32 per row at v=64 and v=80)
    public static final int I_ZENNY = 0, I_HR = 1, I_CROWN_GOLD = 2, I_CROWN_SILVER = 3, I_STAR = 4, I_STAR_EMPTY = 5, I_HEART = 6,
            I_STAMINA = 7, I_SWORD = 8, I_SHIELD = 9, I_MEAT = 10, I_CLOCK = 11, I_MOFU = 12, I_CHECK = 13, I_CROSS = 14, I_HAMMER = 15,
            I_FIRE = 16, I_WATER = 17, I_THUNDER = 18, I_ICE = 19, I_DRAGON = 20, I_FIGHTER = 21, I_HEALER = 22, I_BOMBER = 23,
            I_BOOK = 24, I_MAP = 25, I_LOCK = 26, I_PAW = 27, I_LEFT = 28, I_RIGHT = 29, I_PLUS = 30, I_MINUS = 31,
            I_HELM = 32, I_VEST = 33, I_CLAW = 34, I_SCROLL = 35, I_GIFT = 36, I_EXCLAIM = 37, I_SPARKLE = 38, I_BAG = 39,
            I_SORT = 40, I_DEPOSIT = 41, I_SKULL = 42, I_FLAG = 43, I_POT = 44, I_TAG = 45, I_NEW = 46, I_COIN_STACK = 47,
            I_ING0 = 48;

    protected final CompoundTag openTag;
    protected int left, top, panelW, panelH;
    private final List<Hit> hits = new ArrayList<>();
    protected int mouseX, mouseY;

    protected VillageScreen(Component title, int w, int h, @Nullable CompoundTag openTag) {
        super(title);
        this.panelW = w;
        this.panelH = h;
        this.openTag = openTag == null ? new CompoundTag() : openTag;
    }

    @Override
    protected void init() {
        super.init();
        this.left = (this.width - panelW) / 2;
        this.top = Math.max(8, (this.height - panelH) / 2);
    }

    @Override
    public boolean isPauseScreen() {
        return false;
    }

    @Nullable
    protected Player player() {
        return Minecraft.getInstance().player;
    }

    protected HunterData data() {
        return ClientVillage.data();
    }

    protected CompoundTag village() {
        return ClientVillage.village();
    }

    // ------------------------------------------------------------------ frame
    @Override
    public void render(GuiGraphics g, int mx, int my, float pt) {
        this.mouseX = mx;
        this.mouseY = my;
        hits.clear();
        this.renderBackground(g);
        panel(g, left, top, panelW, panelH);
        drawContent(g, mx, my, pt);
        super.render(g, mx, my, pt);
        drawTooltips(g, mx, my);
    }

    protected abstract void drawContent(GuiGraphics g, int mx, int my, float pt);

    protected void drawTooltips(GuiGraphics g, int mx, int my) {
    }

    /** Title plate centred at the top of the panel. */
    protected void titlePlate(GuiGraphics g, Component title, int iconIdx) {
        int w = Math.max(90, this.font.width(title) + 34);
        int x = left + (panelW - w) / 2, y = top - 8;
        nine(g, x, y, w, 20, 200, 32, 64, 20, 6);
        if (iconIdx >= 0) icon(g, iconIdx, x + 6, y + 2);
        g.drawString(this.font, title, x + (iconIdx >= 0 ? 24 : (w - this.font.width(title)) / 2), y + 6, GOLD, true);
    }

    /** Zenny + HR in the top corners of the panel. */
    protected void walletBar(GuiGraphics g) {
        HunterData d = data();
        String z = String.format("%,d z", d.zenny);
        int x = left + panelW - 10 - this.font.width(z);
        icon(g, I_ZENNY, x - 18, top + 6);
        g.drawString(this.font, z, x, top + 10, GOLD, true);
        String hr = "HR " + d.hunterRank;
        int hx = left + 10;
        icon(g, I_HR, hx, top + 6);
        g.drawString(this.font, hr, hx + 18, top + 10, LIGHT, true);
    }

    /** NPC speech line in a paper strip. */
    protected void speech(GuiGraphics g, Component text, int x, int y, int w) {
        paper(g, x, y, w, 20);
        textClip(g, text, x + 6, y + 6, w - 12, INK, false);
    }

    // ------------------------------------------------------------------ atlas drawing
    public void blitAtlas(GuiGraphics g, int x, int y, int u, int v, int w, int h) {
        g.blit(WIDGETS, x, y, u, v, w, h, ATLAS, ATLAS);
    }

    /** Generic 9-slice from the widget atlas. */
    public void nine(GuiGraphics g, int x, int y, int w, int h, int u, int v, int tw, int th, int b) {
        if (w <= 0 || h <= 0) return;
        b = Math.min(b, Math.min(w / 2, h / 2));
        int cw = tw - 2 * b, ch = th - 2 * b;
        int iw = w - 2 * b, ih = h - 2 * b;
        g.blit(WIDGETS, x, y, u, v, b, b, ATLAS, ATLAS);
        g.blit(WIDGETS, x + w - b, y, u + tw - b, v, b, b, ATLAS, ATLAS);
        g.blit(WIDGETS, x, y + h - b, u, v + th - b, b, b, ATLAS, ATLAS);
        g.blit(WIDGETS, x + w - b, y + h - b, u + tw - b, v + th - b, b, b, ATLAS, ATLAS);
        if (iw > 0) {
            g.blit(WIDGETS, x + b, y, iw, b, u + b, v, cw, b, ATLAS, ATLAS);
            g.blit(WIDGETS, x + b, y + h - b, iw, b, u + b, v + th - b, cw, b, ATLAS, ATLAS);
        }
        if (ih > 0) {
            g.blit(WIDGETS, x, y + b, b, ih, u, v + b, b, ch, ATLAS, ATLAS);
            g.blit(WIDGETS, x + w - b, y + b, b, ih, u + tw - b, v + b, b, ch, ATLAS, ATLAS);
        }
        if (iw > 0 && ih > 0) g.blit(WIDGETS, x + b, y + b, iw, ih, u + b, v + b, cw, ch, ATLAS, ATLAS);
    }

    public void panel(GuiGraphics g, int x, int y, int w, int h) {
        nine(g, x, y, w, h, 0, 0, 32, 32, 8);
    }

    public void paper(GuiGraphics g, int x, int y, int w, int h) {
        nine(g, x, y, w, h, 32, 0, 32, 32, 6);
    }

    public void inset(GuiGraphics g, int x, int y, int w, int h) {
        nine(g, x, y, w, h, 64, 0, 16, 16, 4);
    }

    public void slot(GuiGraphics g, int x, int y) {
        blitAtlas(g, x, y, 80, 0, 18, 18);
    }

    public void icon(GuiGraphics g, int idx, int x, int y) {
        blitAtlas(g, x, y, (idx % 32) * 16, ICON_V + (idx / 32) * 16, 16, 16);
    }

    public void dishIcon(GuiGraphics g, int idx, int x, int y, int size) {
        g.blit(WIDGETS, x, y, size, size, (idx % 16) * 32, DISH_V + (idx / 16) * 32, 32, 32, ATLAS, ATLAS);
    }

    public void mofuFace(GuiGraphics g, int pattern, int x, int y, int size) {
        g.blit(WIDGETS, x, y, size, size, FACE_U + Math.floorMod(pattern, 6) * 24, FACE_V, 24, 24, ATLAS, ATLAS);
    }

    public void stars(GuiGraphics g, int filled, int max, int x, int y) {
        for (int i = 0; i < max; i++) icon(g, i < filled ? I_STAR : I_STAR_EMPTY, x + i * 10, y);
    }

    /** Draws a button and registers it as clickable. */
    public boolean button(GuiGraphics g, int x, int y, int w, int h, Component label, boolean enabled, Runnable onClick) {
        boolean hover = enabled && in(mouseX, mouseY, x, y, w, h);
        nine(g, x, y, w, h, 100, enabled ? (hover ? 20 : 0) : 40, 48, 20, 4);
        int tw = this.font.width(label);
        int col = enabled ? (hover ? 0xFFFFF4C0 : LIGHT) : GREY;
        if (tw > w - 6) textClip(g, label, x + 3, y + (h - 8) / 2, w - 6, col, enabled);
        else g.drawString(this.font, label, x + (w - tw) / 2, y + (h - 8) / 2, col, enabled);
        if (enabled) hits.add(new Hit(x, y, w, h, onClick, true));
        return hover;
    }

    /** Small square icon button. */
    public boolean iconButton(GuiGraphics g, int x, int y, int iconIdx, boolean enabled, Runnable onClick) {
        boolean hover = enabled && in(mouseX, mouseY, x, y, 20, 20);
        nine(g, x, y, 20, 20, 100, enabled ? (hover ? 20 : 0) : 40, 48, 20, 4);
        icon(g, iconIdx, x + 2, y + 2);
        if (enabled) hits.add(new Hit(x, y, 20, 20, onClick, true));
        return hover;
    }

    public void tab(GuiGraphics g, int x, int y, int w, Component label, boolean active, Runnable onClick) {
        nine(g, x, y, w, 20, 150, active ? 0 : 24, 48, 24, 6);
        textClip(g, label, x + Math.max(4, (w - this.font.width(label)) / 2), y + 6, w - 8, active ? GOLD : 0xFFD8C8A8, true);
        if (!active) hits.add(new Hit(x, y, w, 20, onClick, true));
    }

    public void rowHighlight(GuiGraphics g, int x, int y, int w, int h, boolean selected, boolean hover) {
        if (selected) nine(g, x, y, w, h, 200, 0, 64, 16, 3);
        else if (hover) nine(g, x, y, w, h, 200, 16, 64, 16, 3);
    }

    /** Registers a clickable region without drawing. */
    public void region(int x, int y, int w, int h, Runnable onClick) {
        hits.add(new Hit(x, y, w, h, onClick, false));
    }

    public static boolean in(double mx, double my, int x, int y, int w, int h) {
        return mx >= x && mx < x + w && my >= y && my < y + h;
    }

    public void scrollBar(GuiGraphics g, int x, int y, int h, float progress, float visibleFrac) {
        g.fill(x, y, x + 4, y + h, 0x60000000);
        if (visibleFrac >= 1) return;
        int th = Math.max(10, (int) (h * visibleFrac));
        int ty = y + (int) ((h - th) * Mth.clamp(progress, 0, 1));
        g.fill(x, ty, x + 4, ty + th, 0xFFC9A66B);
        g.fill(x, ty, x + 1, ty + th, 0xFFE9CC8E);
    }

    public int wrap(GuiGraphics g, Component text, int x, int y, int w, int color, int maxLines) {
        List<FormattedCharSequence> lines = this.font.split(text, w);
        int n = 0;
        for (FormattedCharSequence l : lines) {
            if (n >= maxLines) break;
            g.drawString(this.font, l, x, y + n * 10, color, false);
            n++;
        }
        return n * 10;
    }

    public int lineCount(Component text, int w) {
        return this.font.split(text, w).size();
    }

    public void text(GuiGraphics g, Component c, int x, int y, int color) {
        g.drawString(this.font, c, x, y, color, false);
    }

    public void text(GuiGraphics g, String s, int x, int y, int color) {
        g.drawString(this.font, s, x, y, color, false);
    }

    public void textShadow(GuiGraphics g, Component c, int x, int y, int color) {
        g.drawString(this.font, c, x, y, color, true);
    }

    public void textRight(GuiGraphics g, String s, int rightX, int y, int color, boolean shadow) {
        g.drawString(this.font, s, rightX - this.font.width(s), y, color, shadow);
    }

    /** Clipped single line (adds "…" when too long). */
    public void textClip(GuiGraphics g, Component c, int x, int y, int maxW, int color, boolean shadow) {
        if (this.font.width(c) <= maxW) {
            g.drawString(this.font, c, x, y, color, shadow);
            return;
        }
        FormattedText cut = this.font.substrByWidth(c, Math.max(0, maxW - this.font.width("…")));
        FormattedCharSequence seq = net.minecraft.locale.Language.getInstance().getVisualOrder(cut);
        g.drawString(this.font, seq, x, y, color, shadow);
        g.drawString(this.font, "…", x + this.font.width(cut), y, color, shadow);
    }

    public void item(GuiGraphics g, ItemStack st, int x, int y) {
        g.renderItem(st, x, y);
    }

    public void itemWithCount(GuiGraphics g, ItemStack st, int x, int y) {
        g.renderItem(st, x, y);
        g.renderItemDecorations(this.font, st, x, y);
    }

    public void bar(GuiGraphics g, int x, int y, int w, int h, float frac, int c1, int c2) {
        g.fill(x - 1, y - 1, x + w + 1, y + h + 1, 0xFF1A120A);
        g.fill(x, y, x + w, y + h, 0xFF3A2C1E);
        int fw = (int) (w * Mth.clamp(frac, 0, 1));
        if (fw > 0) g.fillGradient(x, y, x + fw, y + h, c1, c2);
    }

    /** Thin separator line on paper. */
    public void rule(GuiGraphics g, int x, int y, int w) {
        g.fill(x, y, x + w, y + 1, 0x60402A10);
    }

    /** Live 3D preview of an entity (NPC portrait, companion preview). */
    public void preview(GuiGraphics g, int x, int y, int scale, @Nullable LivingEntity e, float mx, float my) {
        if (e == null) return;
        try {
            InventoryScreen.renderEntityInInventoryFollowsMouse(g, x, y, scale, x - mx, y - scale * 1.2F - my, e);
        } catch (RuntimeException ex) {
            HuntCraft.LOGGER.debug("preview render failed", ex);
        }
    }

    public void click() {
        Minecraft.getInstance().getSoundManager().play(SimpleSoundInstance.forUI(SoundEvents.UI_BUTTON_CLICK, 1.0F));
    }

    public void pageSound() {
        Minecraft.getInstance().getSoundManager().play(SimpleSoundInstance.forUI(VillageRegistry.UI_PAGE.get(), 1.0F));
    }

    @Override
    public boolean mouseClicked(double mx, double my, int button) {
        if (button == 0) {
            for (int i = hits.size() - 1; i >= 0; i--) {
                Hit h = hits.get(i);
                if (in(mx, my, h.x, h.y, h.w, h.h)) {
                    if (h.sound) click();
                    h.action.run();
                    return true;
                }
            }
        }
        return super.mouseClicked(mx, my, button);
    }

    private record Hit(int x, int y, int w, int h, Runnable action, boolean sound) {
    }

    public static String fmt(float f) {
        return f == Math.round(f) ? String.valueOf(Math.round(f)) : String.format(java.util.Locale.ROOT, "%.1f", f);
    }
}
