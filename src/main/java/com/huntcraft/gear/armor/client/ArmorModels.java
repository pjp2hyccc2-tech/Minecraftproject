package com.huntcraft.gear.armor.client;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonParser;
import com.huntcraft.HuntCraft;
import net.minecraft.client.Minecraft;
import net.minecraft.client.model.HumanoidModel;
import net.minecraft.client.model.geom.ModelPart;
import net.minecraft.client.model.geom.PartPose;
import net.minecraft.client.model.geom.builders.CubeDeformation;
import net.minecraft.client.model.geom.builders.CubeListBuilder;
import net.minecraft.client.model.geom.builders.LayerDefinition;
import net.minecraft.client.model.geom.builders.MeshDefinition;
import net.minecraft.client.model.geom.builders.PartDefinition;
import net.minecraft.resources.ResourceLocation;
import net.minecraft.world.entity.LivingEntity;
import net.minecraftforge.api.distmarker.Dist;
import net.minecraftforge.api.distmarker.OnlyIn;
import org.jetbrains.annotations.Nullable;

import java.util.Map;
import java.util.Optional;
import java.util.concurrent.ConcurrentHashMap;

/**
 * Custom humanoid armor models (horns, crests, fur, crystals, spikes...) built from the geometry generated by
 * tools/art/armor.py ({@link ArmorGeometry}). Two models per series: "outer" (helm, mail, greaves - texture
 * layer_1) and "inner" (coil - texture layer_2).
 */
@OnlyIn(Dist.CLIENT)
public final class ArmorModels {
    private static final float DEG = (float) (Math.PI / 180.0);
    private static final Map<String, Optional<HumanoidModel<LivingEntity>>> MODELS = new ConcurrentHashMap<>();
    private static final Map<String, Optional<ResourceLocation>> GLOW = new ConcurrentHashMap<>();
    private static final String[][] REQUIRED = {
            {"head", "0", "0", "0"}, {"hat", "0", "0", "0"}, {"body", "0", "0", "0"},
            {"right_arm", "-5", "2", "0"}, {"left_arm", "5", "2", "0"},
            {"right_leg", "-1.9", "12", "0"}, {"left_leg", "1.9", "12", "0"}};

    private ArmorModels() {
    }

    @Nullable
    public static HumanoidModel<LivingEntity> get(String set, boolean inner) {
        return MODELS.computeIfAbsent(set + (inner ? "_inner" : "_outer"), ArmorModels::build).orElse(null);
    }

    /** Emissive texture of a layer (textures/models/armor/SET_layer_N_glow.png) or null if the set has none. */
    @Nullable
    public static ResourceLocation glowTexture(String set, boolean inner) {
        String key = set + (inner ? "_layer_2" : "_layer_1");
        return GLOW.computeIfAbsent(key, k -> {
            ResourceLocation rl = HuntCraft.id("textures/models/armor/" + k + "_glow.png");
            try {
                return Minecraft.getInstance().getResourceManager().getResource(rl).isPresent() ? Optional.of(rl) : Optional.empty();
            } catch (Exception e) {
                return Optional.empty();
            }
        }).orElse(null);
    }

    public static void clearCaches() {
        GLOW.clear();
    }

    private static Optional<HumanoidModel<LivingEntity>> build(String key) {
        String json = ArmorGeometry.get(key);
        if (json == null) return Optional.empty();
        try {
            JsonObject o = JsonParser.parseString(json).getAsJsonObject();
            int tw = o.get("texture_width").getAsInt();
            int th = o.get("texture_height").getAsInt();
            MeshDefinition mesh = new MeshDefinition();
            PartDefinition root = mesh.getRoot();
            for (JsonElement p : o.getAsJsonArray("parts")) addPart(root, p.getAsJsonObject());
            for (String[] req : REQUIRED) {
                if (root.getChild(req[0]) == null) {
                    root.addOrReplaceChild(req[0], CubeListBuilder.create(),
                            PartPose.offset(Float.parseFloat(req[1]), Float.parseFloat(req[2]), Float.parseFloat(req[3])));
                }
            }
            ModelPart baked = LayerDefinition.create(mesh, tw, th).bakeRoot();
            return Optional.of(new HumanoidModel<>(baked));
        } catch (Exception e) {
            HuntCraft.LOGGER.error("Failed to build armor model {}", key, e);
            return Optional.empty();
        }
    }

    private static float[] floats(JsonArray a) {
        float[] f = new float[a.size()];
        for (int i = 0; i < f.length; i++) f[i] = a.get(i).getAsFloat();
        return f;
    }

    private static void addPart(PartDefinition parent, JsonObject o) {
        String name = o.get("name").getAsString();
        float[] pivot = o.has("pivot") ? floats(o.getAsJsonArray("pivot")) : new float[3];
        float[] rot = o.has("rotation") ? floats(o.getAsJsonArray("rotation")) : new float[3];
        CubeListBuilder cb = CubeListBuilder.create();
        if (o.has("cubes")) {
            for (JsonElement ce : o.getAsJsonArray("cubes")) {
                JsonObject c = ce.getAsJsonObject();
                float[] uv = floats(c.getAsJsonArray("uv"));
                float[] origin = floats(c.getAsJsonArray("origin"));
                float[] size = floats(c.getAsJsonArray("size"));
                float inflate = c.has("inflate") ? c.get("inflate").getAsFloat() : 0F;
                boolean mirror = c.has("mirror") && c.get("mirror").getAsBoolean();
                cb.texOffs((int) uv[0], (int) uv[1]).mirror(mirror)
                        .addBox(origin[0], origin[1], origin[2], size[0], size[1], size[2], new CubeDeformation(inflate));
            }
        }
        PartDefinition pd = parent.addOrReplaceChild(name, cb,
                PartPose.offsetAndRotation(pivot[0], pivot[1], pivot[2], rot[0] * DEG, rot[1] * DEG, rot[2] * DEG));
        if (o.has("children")) {
            for (JsonElement ch : o.getAsJsonArray("children")) addPart(pd, ch.getAsJsonObject());
        }
    }
}
