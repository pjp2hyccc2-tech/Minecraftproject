    @Override
    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        // resetPose restores only positions and rotations: scales and visibility are reset here
        for (ModelPart p : this.all) {
            p.xScale = 1.0F;
            p.yScale = 1.0F;
            p.zScale = 1.0F;
            p.visible = true;
            p.skipDraw = false;
        }
        // hidden while the entity is invisible (the eyes layer draws this model too, so it hides as well)
        this.root.visible = !entity.isInvisible();
        if (!this.root.visible) {
            return;
        }
        float partial = ageInTicks - (float) Mth.floor(ageInTicks);
        int pose = entity.pose();
        float pt = Math.max(0.0F, entity.poseTime(partial));
        float glitch = Mth.clamp(entity.glitch(partial), 0.0F, 1.0F);
        final float poseTicks = pt;
        State mem = this.state(entity, pose, ageInTicks);
        int prev = mem.prev;
        float blend = 8.0F;
        float t = ageInTicks;
        if (glitch > 0.0F) {
            float held = stutter(ageInTicks, glitch);
            float lost = ageInTicks - held;
            pt = Math.max(0.0F, pt - lost);
            limbSwing = limbSwing - lost * limbSwingAmount;
            t = held;
        }
        float yaw = netHeadYaw * 0.017453292F;
        float pitch = headPitch * 0.017453292F;

        float breath = Mth.sin(t * 0.07F);
        float jit = glitch * noise(t * 2.1F);
        float jit2 = glitch * noise(t * 2.9F + 20.0F);
        float look = Mth.clamp(yaw, -1.2F, 1.2F);
        float lookP = Mth.clamp(pitch, -0.6F, 0.6F);
        this.mouth.visible = false;
        this.jaw.visible = false;
        this.glint.visible = false;
        // the brim droops a little all round
        this.brimF.xRot = 0.38F;
        this.brimB.xRot = -0.35F;
        this.brimR.zRot = 0.38F;
        this.brimL.zRot = -0.38F;
        boolean squat = pose == HIDE || pose == PEEK;
        if (squat) {
            // crouched small on her heels, hunched over her knees
            this.body.y = 20.6F;
            this.rightLeg.y = 20.6F;
            this.leftLeg.y = 20.6F;
            this.rightLeg.xRot = -2.05F;
            this.leftLeg.xRot = -2.05F;
            this.rightLeg.zRot = 0.16F;
            this.leftLeg.zRot = -0.16F;
            this.rightShin.xRot = 2.25F;
            this.leftShin.xRot = 2.25F;
            this.body.xRot = 0.55F + breath * 0.01F;
            this.smock.xRot = -0.35F;
            this.neck.xRot = 0.1F;
            this.head.xRot = 0.12F;
            this.rightArm.xRot = -2.007F;
            this.rightArm.zRot = 0.392F;
            this.rightArm.yRot = -0.240F;
            this.rightForearm.xRot = -0.282F;
            this.rightHand.xRot = -0.594F;
            this.leftArm.xRot = -2.007F;
            this.leftArm.zRot = -0.392F;
            this.leftArm.yRot = 0.240F;
            this.leftForearm.xRot = -0.282F;
            this.leftHand.xRot = -0.594F;
            if (pose == PEEK) {
                // the hands slide down from the eyes, slowly; then the head comes up and turns to you
                float slide = span(pt, 0.0F, 16.0F);
                float up = span(pt, 10.0F, 22.0F);
                this.rightArm.xRot = Mth.lerp(slide, -2.007F, 0.147F);
                this.rightArm.zRot = Mth.lerp(slide, 0.392F, 0.005F);
                this.rightArm.yRot = Mth.lerp(slide, -0.240F, -1.299F);
                this.rightForearm.xRot = Mth.lerp(slide, -0.282F, -2.152F);
                this.rightHand.xRot = Mth.lerp(slide, -0.594F, -0.555F);
                this.leftArm.xRot = Mth.lerp(slide, -2.007F, 0.147F);
                this.leftArm.zRot = Mth.lerp(slide, -0.392F, -0.005F);
                this.leftArm.yRot = Mth.lerp(slide, 0.240F, 1.299F);
                this.leftForearm.xRot = Mth.lerp(slide, -0.282F, -2.152F);
                this.leftHand.xRot = Mth.lerp(slide, -0.594F, -0.555F);
                this.neck.xRot = 0.1F - 0.35F * up;
                this.head.xRot = 0.12F - 0.4F * up + lookP * 0.5F * up;
                this.head.yRot = look * up;
                this.head.zRot = 0.18F * up;
                this.glint.visible = pt > 14.0F;
            }
        } else if (pose == RUN) {
            // skipping: step-hop, knees high, arms swinging wide, the head bobbing loosely
            float a = Math.min(1.0F, limbSwingAmount * 1.5F);
            float c = limbSwing * 0.95F;
            float s = Mth.sin(c);
            float hop = Math.abs(Mth.sin(c));
            this.body.y = 17.0F - hop * 1.2F * a;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.rightLeg.xRot = -Math.max(0.0F, s) * 1.25F * a + Math.max(0.0F, -s) * 0.35F * a;
            this.leftLeg.xRot = -Math.max(0.0F, -s) * 1.25F * a + Math.max(0.0F, s) * 0.35F * a;
            this.rightShin.xRot = Math.max(0.0F, s) * 1.4F * a;
            this.leftShin.xRot = Math.max(0.0F, -s) * 1.4F * a;
            this.rightArm.xRot = s * 0.95F * a;
            this.leftArm.xRot = -s * 0.95F * a;
            this.rightArm.zRot = 0.25F;
            this.leftArm.zRot = -0.25F;
            this.rightForearm.xRot = -0.5F;
            this.leftForearm.xRot = -0.5F;
            this.body.xRot = 0.1F;
            this.head.xRot = -0.05F + Mth.sin(c * 2.0F) * 0.08F * a;
            this.head.zRot = s * 0.15F * a;
            this.smock.xRot = -0.1F - hop * 0.15F * a;
        } else if (pose == COUNT) {
            // face to the pillar, forearms crossed over her eyes against it; a little bob with every number
            float num = (pt % 16.0F) / 16.0F;
            float bob = Mth.sin(num * 3.14159F) * (pt < 150.0F ? 1.0F : 0.4F);
            this.body.xRot = 0.24F + bob * 0.03F;
            this.neck.xRot = 0.25F;
            this.head.xRot = 0.28F + bob * 0.06F;
            this.head.zRot = Mth.sin(pt * 0.013F) * 0.06F;
            this.rightArm.xRot = -2.117F;
            this.rightArm.zRot = 1.346F;
            this.rightArm.yRot = 0.344F;
            this.rightForearm.xRot = -0.381F;
            this.rightHand.xRot = -0.146F;
            this.leftArm.xRot = -2.073F;
            this.leftArm.zRot = -1.374F;
            this.leftArm.yRot = -0.264F;
            this.leftForearm.xRot = -0.333F;
            this.leftHand.xRot = -0.132F;
            this.rightLeg.zRot = 0.03F;
            this.leftLeg.zRot = -0.03F;
        } else if (pose == FOUND) {
            // springs up and points straight at you, mouth wide: "mi-tsu-ke-ta"
            float pop = spring(pt, 1.1F, 0.4F);
            float aim = Math.min(1.0F, pt / 3.0F);
            this.body.xRot = -0.08F;
            this.body.y = 17.0F - 0.6F * Math.max(0.0F, 1.0F - pt / 4.0F);
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.rightArm.xRot = (-1.57F + lookP) * aim;
            this.rightArm.yRot = look * 0.8F * aim;
            this.rightArm.zRot = 0.05F;
            this.rightForearm.xRot = 0.0F;
            this.rightHand.xRot = 0.0F;
            this.leftArm.xRot = 0.2F;
            this.leftArm.zRot = -0.3F * pop;
            this.head.yRot = look;
            this.head.xRot = lookP * 0.8F - 0.1F;
            this.head.zRot = 0.3F * pop + Mth.sin(t * 0.6F) * 0.04F;
            float o = Math.min(1.0F, pt / 4.0F) * (0.95F + Mth.sin(t * 0.5F) * 0.05F);
            this.mouth.visible = true;
            this.jaw.visible = true;
            this.mouth.yScale = Math.max(0.02F, o);
            this.jaw.y = this.jaw.y + 1.5F * o;
            this.glint.visible = true;
            blend = 2.0F;
        } else if (pose == STAND) {
            // hands clasped behind her back, head tilted; the tilt flips to the other side now and then, too fast
            float flip = Mth.sin(t * 0.021F) > 0.0F ? 1.0F : -1.0F;
            this.head.zRot = 0.42F * flip;
            this.head.yRot = look * 0.6F;
            this.head.xRot = lookP * 0.4F + 0.08F;
            this.body.zRot = -0.03F * flip;
            this.rightArm.xRot = 0.926F;
            this.rightArm.zRot = -0.900F;
            this.rightArm.yRot = -0.559F;
            this.rightForearm.xRot = -0.636F;
            this.leftArm.xRot = 0.926F;
            this.leftArm.zRot = 0.900F;
            this.leftArm.yRot = 0.559F;
            this.leftForearm.xRot = -0.636F;
        } else {
            // GIGGLE: a hand over her mouth, the shoulders shaking in little bursts
            float burst = Math.max(0.0F, Mth.sin(t * 0.17F));
            float shake = Mth.sin(t * 2.6F) * burst;
            this.body.y = 17.0F + shake * 0.25F;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.body.xRot = 0.16F + burst * 0.06F;
            this.body.zRot = shake * 0.03F;
            this.head.xRot = 0.2F + shake * 0.06F;
            this.head.zRot = 0.2F + shake * 0.05F;
            this.head.yRot = look * 0.4F;
            this.rightArm.xRot = -1.986F;
            this.rightArm.zRot = 0.976F;
            this.rightArm.yRot = -0.188F;
            this.rightForearm.xRot = -0.521F;
            this.rightHand.xRot = -0.453F;
            this.leftArm.xRot = 0.05F + shake * 0.05F;
            this.leftArm.zRot = -0.120F;
            this.leftForearm.xRot = -0.400F;
        }
        this.head.zRot = this.head.zRot + jit * 0.4F;
        this.head.yRot = this.head.yRot + jit2 * 0.25F;
        this.blend(mem, poseTicks, blend, ageInTicks);
    }

    /** Smoothstep 0..1. */
    private static float ease(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * (3.0F - 2.0F * c);
    }

    /** Fast in, slow out (0..1). */
    private static float easeOut(float x) {
        float c = 1.0F - Mth.clamp(x, 0.0F, 1.0F);
        return 1.0F - c * c * c;
    }

    /** Slow in, fast out (0..1). */
    private static float easeIn(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * c;
    }

    /** 0 before a, rises to 1 at b (smooth). */
    private static float span(float x, float a, float b) {
        return ease((x - a) / (b - a));
    }

    /** Pseudo random 0..1 for an integer-valued x (bounded argument: Mth.sin is a lookup table). */
    private static float hash(float x) {
        float k = x - 1024.0F * (float) Mth.floor(x / 1024.0F);
        float s = Mth.sin(k * 12.9898F + 4.1414F) * 43758.547F;
        return s - (float) Mth.floor(s);
    }

    /** Smooth value noise -1..1. */
    private static float noise(float x) {
        float i = (float) Mth.floor(x);
        float f = x - i;
        float u = f * f * (3.0F - 2.0F * f);
        return Mth.lerp(u, hash(i), hash(i + 1.0F)) * 2.0F - 1.0F;
    }

    /** Missing frames: time holds still for most of every 3-tick window, then jumps to catch up (g = 0..1). */
    private static float stutter(float x, float g) {
        float p = 3.0F;
        float i = (float) Mth.floor(x / p);
        float f = x / p - i;
        float hold = Mth.clamp(g, 0.0F, 1.0F) * (0.55F + 0.4F * hash(i + 17.0F));
        float s = f < hold ? 0.0F : (f - hold) / (1.0F - hold);
        return (i + s) * p;
    }

    /** 1 -> 0 over 3 ticks once every period ticks (phase shifted): sudden twitches. t must be >= 0. */
    private static float twitch(float t, float period, float phase) {
        float m = (t + phase) % period;
        return m < 3.0F ? 1.0F - m / 3.0F : 0.0F;
    }

    /** Stepped progress: holds still, then lurches to the next step (jerky motion), x in 0..1. */
    private static float jerky(float x, float steps) {
        float c = Mth.clamp(x, 0.0F, 1.0F) * steps;
        float i = (float) Mth.floor(c);
        float f = c - i;
        float s = f < 0.55F ? 0.0F : ease((f - 0.55F) / 0.45F);
        return Math.min(1.0F, (i + s) / steps);
    }

    /** Damped spring response 0..1 with overshoot (x in ticks since the step). */
    private static float spring(float x, float freq, float damp) {
        if (x <= 0.0F) {
            return 0.0F;
        }
        return 1.0F - (float) Math.exp(-damp * x) * Mth.cos(freq * x);
    }
    /** Per-entity animation memory: the previous pose, the values to blend from, smoothed values. */
    private static final class State {
        int pose = -1;
        int prev = -1;
        boolean blending;
        float lastAge = -1000.0F;
        float[] from;
        float[] last;
        final float[] fv = new float[8];
        final float[] ft = new float[] {-1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F};
    }

    private State state(Entity entity, int pose, float age) {
        State s = this.states.get(entity);
        if (s == null) {
            s = new State();
            s.from = new float[this.all.length * 9];
            s.last = new float[this.all.length * 9];
            s.pose = pose;
            this.states.put(entity, s);
        } else if (s.pose != pose) {
            System.arraycopy(s.last, 0, s.from, 0, s.last.length);
            // blend only from a frame that was actually seen a moment ago
            s.blending = age - s.lastAge < 10.0F;
            s.prev = s.pose;
            s.pose = pose;
        }
        return s;
    }

    /** Eases every part from the values shown when the pose changed to the new pose over `ticks`. */
    private void blend(State s, float pt, float ticks, float age) {
        boolean on = s.blending && ticks > 0.0F && pt < ticks;
        if (!on) {
            s.blending = false;
        }
        float k = on ? ease(pt / ticks) : 1.0F;
        float[] f = s.from;
        float[] l = s.last;
        for (int i = 0; i < this.all.length; i++) {
            ModelPart p = this.all[i];
            int o = i * 9;
            if (on) {
                p.x = Mth.lerp(k, f[o], p.x);
                p.y = Mth.lerp(k, f[o + 1], p.y);
                p.z = Mth.lerp(k, f[o + 2], p.z);
                p.xRot = Mth.lerp(k, f[o + 3], p.xRot);
                p.yRot = Mth.lerp(k, f[o + 4], p.yRot);
                p.zRot = Mth.lerp(k, f[o + 5], p.zRot);
                p.xScale = Mth.lerp(k, f[o + 6], p.xScale);
                p.yScale = Mth.lerp(k, f[o + 7], p.yScale);
                p.zScale = Mth.lerp(k, f[o + 8], p.zScale);
            }
            l[o] = p.x;
            l[o + 1] = p.y;
            l[o + 2] = p.z;
            l[o + 3] = p.xRot;
            l[o + 4] = p.yRot;
            l[o + 5] = p.zRot;
            l[o + 6] = p.xScale;
            l[o + 7] = p.yScale;
            l[o + 8] = p.zScale;
        }
        s.lastAge = age;
    }

    /** Undoes the rotations of `chain` (the target's ancestors, root side first) so that `target` stays level / hangs
     *  straight down in model space (trays, glasses, strands of hair, keys); add any sway afterwards. */
    private static void level(ModelPart target, ModelPart... chain) {
        float m00 = 1.0F, m01 = 0.0F, m02 = 0.0F, m10 = 0.0F, m11 = 1.0F, m12 = 0.0F, m20 = 0.0F, m21 = 0.0F, m22 = 1.0F;
        for (ModelPart p : chain) {
            float cz = Mth.cos(p.zRot), sz = Mth.sin(p.zRot), cy = Mth.cos(p.yRot), sy = Mth.sin(p.yRot);
            float cx = Mth.cos(p.xRot), sx = Mth.sin(p.xRot);
            float r00 = cz * cy, r01 = cz * sy * sx - sz * cx, r02 = cz * sy * cx + sz * sx;
            float r10 = sz * cy, r11 = sz * sy * sx + cz * cx, r12 = sz * sy * cx - cz * sx;
            float r20 = -sy, r21 = cy * sx, r22 = cy * cx;
            float n00 = m00 * r00 + m01 * r10 + m02 * r20, n01 = m00 * r01 + m01 * r11 + m02 * r21, n02 = m00 * r02 + m01 * r12 + m02 * r22;
            float n10 = m10 * r00 + m11 * r10 + m12 * r20, n11 = m10 * r01 + m11 * r11 + m12 * r21, n12 = m10 * r02 + m11 * r12 + m12 * r22;
            float n20 = m20 * r00 + m21 * r10 + m22 * r20, n21 = m20 * r01 + m21 * r11 + m22 * r21, n22 = m20 * r02 + m21 * r12 + m22 * r22;
            m00 = n00; m01 = n01; m02 = n02; m10 = n10; m11 = n11; m12 = n12; m20 = n20; m21 = n21; m22 = n22;
        }
        // local rotation = transpose(M), decomposed as Rz * Ry * Rx
        target.yRot = (float) Math.asin(Mth.clamp(-m02, -1.0F, 1.0F));
        target.xRot = (float) Math.atan2(m12, m22);
        target.zRot = (float) Math.atan2(m01, m00);
    }

    /** A value that follows its target with a lag (exponential, `speed` per tick), remembered per entity. */
    private static float follow(State s, int slot, float target, float speed, float t) {
        float last = s.ft[slot];
        if (last < 0.0F || t < last || t - last > 40.0F) {
            s.fv[slot] = target;
        } else {
            float k = 1.0F - (float) Math.exp(-speed * (t - last));
            s.fv[slot] = s.fv[slot] + (target - s.fv[slot]) * k;
        }
        s.ft[slot] = t;
        return s.fv[slot];
    }
