    @Override
    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        // hidden while the entity is invisible (the eyes layer draws this model too, so it hides as well)
        this.root.visible = !entity.isInvisible();
        if (!this.root.visible) {
            return;
        }
        float partial = ageInTicks - (float) Mth.floor(ageInTicks);
        int pose = entity.pose();
        float pt = Math.max(0.0F, entity.poseTime(partial));
        float glitch = Mth.clamp(entity.glitch(partial), 0.0F, 1.0F);
        final float poseTicks = pt;
        State mem = this.state(entity, pose, ageInTicks);
        int prev = mem.prev;
        float blend = 8.0F;
        float t = ageInTicks;
        if (glitch > 0.0F) {
            float held = stutter(ageInTicks, glitch);
            float lost = ageInTicks - held;
            pt = Math.max(0.0F, pt - lost);
            limbSwing = limbSwing - lost * limbSwingAmount;
            t = held;
        }
        float yaw = netHeadYaw * 0.017453292F;
        float pitch = headPitch * 0.017453292F;

        float breath = Mth.sin(t * 0.08F);
        float wheeze = Math.max(0.0F, Mth.sin(t * 0.08F)) * Math.max(0.0F, Mth.sin(t * 0.43F));
        float jit = glitch * noise(t * 1.6F);
        float jit2 = glitch * noise(t * 2.2F + 30.0F);
        float look = Mth.clamp(yaw, -1.2F, 1.2F);
        float lookP = Mth.clamp(pitch, -0.5F, 0.6F);
        // embers: the flare card flickers on now and then; always on while he hunts
        this.flare.visible = noise(t * 0.35F + 3.0F) > 0.55F;
        this.mouth.visible = false;
        this.jaw.visible = false;
        // the toque sags a little to one side
        this.toquePuff.zRot = 0.06F;
        this.toquePuff.xRot = -0.04F;

        if (pose == CHOP || pose == LOOK) {
            // facing the board: the left hand holds the food, the right chops a 10-tick rhythm
            float cyc = (t % 10.0F) / 10.0F;
            float raise = cyc < 0.62F ? easeOut(cyc / 0.62F) : 1.0F - easeIn((cyc - 0.62F) / 0.11F);
            if (cyc >= 0.73F) {
                raise = -0.06F * Mth.sin((cyc - 0.73F) / 0.27F * 3.14159F);
            }
            if (pose == LOOK) {
                raise = 1.0F;                       // frozen at the top of the swing
            }
            this.body.xRot = 0.22F + raise * 0.04F;
            this.body.yRot = -0.08F * raise;
            this.neck.xRot = 0.25F;
            this.head.xRot = 0.3F;
            this.leftArm.xRot = -0.744F;
            this.leftArm.zRot = 0.281F;
            this.leftArm.yRot = 0.175F;
            this.leftForearm.xRot = -0.384F;
            this.leftHand.xRot = -0.545F;
            this.rightArm.xRot = Mth.lerp(raise, -0.378F, -2.250F);
            this.rightArm.zRot = Mth.lerp(raise, 0.090F, 0.126F);
            this.rightArm.yRot = Mth.lerp(raise, -0.392F, -0.125F);
            this.rightForearm.xRot = Mth.lerp(raise, -1.620F, -2.102F);
            this.rightHand.xRot = Mth.lerp(raise, 1.600F, 1.379F);
            if (pose == LOOK) {
                // the body stays dead still; only the head comes round, slowly, much too far, over the shoulder
                float side = yaw < -0.05F ? -1.0F : 1.0F;
                float turn = ease(pt / 34.0F);
                float stp = jerky(pt / 34.0F, 5.0F);
                float tt = Mth.lerp(0.35F, turn, stp);
                this.neck.yRot = side * 0.4F * tt;
                this.head.yRot = side * 2.4F * tt;
                this.head.xRot = 0.3F - 0.45F * tt;
                this.neck.xRot = 0.25F - 0.25F * tt;
                this.head.zRot = side * 0.12F * tt + jit * 0.3F;
                this.flare.visible = pt > 26.0F && noise(t * 0.8F) > -0.2F;
                blend = 5.0F;
            }
        } else if (pose == STOVE) {
            // leaning in over the flames: the left hand works a pan, the cleaver hangs, the face down to the fire
            float sw = Mth.sin(t * 0.18F);
            this.body.xRot = 0.42F + breath * 0.015F;
            this.neck.xRot = 0.2F;
            this.head.xRot = 0.35F + Mth.sin(t * 0.05F) * 0.05F;
            this.head.yRot = 0.15F;
            this.leftArm.xRot = -1.05F + sw * 0.08F;
            this.leftArm.zRot = -0.12F;
            this.leftForearm.xRot = -0.65F;
            this.leftHand.xRot = -0.2F + sw * 0.15F;
            this.rightArm.xRot = -0.45F;
            this.rightArm.zRot = 0.12F;
            this.rightForearm.xRot = -0.55F;
            this.flare.visible = noise(t * 0.5F) > 0.2F;
        } else if (pose == PLATE) {
            // at the pass, facing the dining room: head bowed over the plate, small precise movements; the bell at 100
            float a1 = Mth.sin(t * 0.21F);
            float a2 = Mth.sin(t * 0.13F + 1.0F);
            float bell = span(pt, 96.0F, 99.0F) * (1.0F - span(pt, 101.0F, 106.0F));
            this.body.xRot = 0.2F;
            this.neck.xRot = 0.18F;
            this.head.xRot = 0.32F + lookP * 0.2F;
            this.head.yRot = a2 * 0.05F;
            this.leftArm.xRot = -0.992F + a1 * 0.05F - bell * 0.25F;
            this.leftArm.zRot = 0.524F;
            this.leftArm.yRot = 0.182F;
            this.leftForearm.xRot = -0.027F + a2 * 0.08F;
            this.leftHand.xRot = -0.391F + a1 * 0.1F + bell * 0.5F;
            this.rightArm.xRot = -0.457F;
            this.rightArm.zRot = -0.524F;
            this.rightArm.yRot = -0.061F;
            this.rightForearm.xRot = -1.263F;
            this.rightHand.xRot = 1.500F;
        } else if (pose == WALK) {
            float a = Math.min(1.0F, limbSwingAmount * 1.4F);
            float c = limbSwing * 0.7F;
            float s = Mth.sin(c);
            this.rightLeg.xRot = s * 0.5F * a;
            this.leftLeg.xRot = -s * 0.5F * a;
            this.rightShin.xRot = Math.max(0.0F, Mth.sin(c - 1.1F)) * 0.6F * a;
            this.leftShin.xRot = Math.max(0.0F, -Mth.sin(c - 1.1F)) * 0.6F * a;
            this.body.y = 10.5F + Math.abs(Mth.cos(c)) * 0.5F * a;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.body.zRot = s * 0.05F * a;
            this.body.yRot = -s * 0.07F * a;
            this.body.xRot = 0.12F;
            this.rightArm.xRot = -s * 0.3F * a;
            this.leftArm.xRot = s * 0.35F * a;
            this.rightArm.zRot = 0.08F;
            this.leftArm.zRot = -0.08F;
            this.rightForearm.xRot = -0.35F;
            this.leftForearm.xRot = -0.2F;
            this.neck.xRot = 0.15F;
            this.head.xRot = 0.15F + lookP * 0.4F;
            this.head.yRot = look * 0.5F;
        } else if (pose == CHASE) {
            // charging, the cleaver raised high, roaring
            float a = Math.min(1.0F, limbSwingAmount * 1.2F);
            float c = limbSwing * 0.85F;
            float s = Mth.sin(c);
            this.rightLeg.xRot = s * 0.8F * a - 0.1F;
            this.leftLeg.xRot = -s * 0.8F * a - 0.1F;
            this.rightShin.xRot = Math.max(0.0F, Mth.sin(c - 1.0F)) * 1.0F * a + 0.1F;
            this.leftShin.xRot = Math.max(0.0F, -Mth.sin(c - 1.0F)) * 1.0F * a + 0.1F;
            this.body.y = 11.0F + Math.abs(Mth.cos(c)) * 0.9F * a;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.body.xRot = 0.35F;
            this.body.yRot = -s * 0.1F * a;
            this.rightArm.xRot = -2.75F + jit * 0.3F;
            this.rightArm.zRot = -0.15F;
            this.rightForearm.xRot = -1.1F + Mth.sin(t * 0.5F) * 0.15F;
            this.rightHand.xRot = -0.6F;
            this.leftArm.xRot = -0.9F + s * 0.5F * a;
            this.leftArm.zRot = -0.2F;
            this.leftForearm.xRot = -0.9F;
            this.leftHand.xRot = -0.3F;
            this.neck.xRot = -0.15F;
            this.head.xRot = -0.25F + lookP * 0.5F;
            this.head.yRot = look * 0.6F;
            float o = 0.75F + Mth.sin(t * 0.37F) * 0.2F;
            this.mouth.visible = true;
            this.jaw.visible = true;
            this.mouth.yScale = o;
            this.jaw.y = this.jaw.y + 2.0F * o;
            this.flare.visible = true;
            blend = 4.0F;
        } else {
            // IDLE: wheezing, the shoulders heaving, the cleaver hanging heavy
            this.body.xRot = 0.1F + breath * 0.02F + wheeze * 0.03F;
            this.body.y = 10.5F - wheeze * 0.25F;
            this.neck.xRot = 0.2F + wheeze * 0.05F;
            this.head.xRot = 0.25F + Mth.sin(t * 0.031F) * 0.06F;
            this.head.zRot = Mth.sin(t * 0.017F) * 0.08F + twitch(t, 71.0F, 9.0F) * 0.25F;
            this.head.yRot = look * 0.4F;
            this.rightArm.xRot = 0.05F;
            this.rightArm.zRot = 0.1F + wheeze * 0.04F;
            this.leftArm.zRot = -0.1F - wheeze * 0.04F;
            this.rightForearm.xRot = -0.3F;
            this.leftForearm.xRot = -0.25F;
        }
        this.head.zRot = this.head.zRot + jit * 0.3F;
        this.head.xRot = this.head.xRot + jit2 * 0.2F;
        this.rightArm.zRot = this.rightArm.zRot + jit2 * 0.15F;
        this.blend(mem, poseTicks, blend, ageInTicks);
        // the apron hangs from the waist and swings a little with the legs
        this.apron.xRot = -this.body.xRot * 0.85F + (this.leftLeg.xRot + this.rightLeg.xRot) * -0.25F
            + Math.min(this.leftLeg.xRot, this.rightLeg.xRot) * 0.35F;
    }

    /** Smoothstep 0..1. */
    private static float ease(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * (3.0F - 2.0F * c);
    }

    /** Fast in, slow out (0..1). */
    private static float easeOut(float x) {
        float c = 1.0F - Mth.clamp(x, 0.0F, 1.0F);
        return 1.0F - c * c * c;
    }

    /** Slow in, fast out (0..1). */
    private static float easeIn(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * c;
    }

    /** 0 before a, rises to 1 at b (smooth). */
    private static float span(float x, float a, float b) {
        return ease((x - a) / (b - a));
    }

    /** Pseudo random 0..1 for an integer-valued x (bounded argument: Mth.sin is a lookup table). */
    private static float hash(float x) {
        float k = x - 1024.0F * (float) Mth.floor(x / 1024.0F);
        float s = Mth.sin(k * 12.9898F + 4.1414F) * 43758.547F;
        return s - (float) Mth.floor(s);
    }

    /** Smooth value noise -1..1. */
    private static float noise(float x) {
        float i = (float) Mth.floor(x);
        float f = x - i;
        float u = f * f * (3.0F - 2.0F * f);
        return Mth.lerp(u, hash(i), hash(i + 1.0F)) * 2.0F - 1.0F;
    }

    /** Missing frames: time holds still for most of every 3-tick window, then jumps to catch up (g = 0..1). */
    private static float stutter(float x, float g) {
        float p = 3.0F;
        float i = (float) Mth.floor(x / p);
        float f = x / p - i;
        float hold = Mth.clamp(g, 0.0F, 1.0F) * (0.55F + 0.4F * hash(i + 17.0F));
        float s = f < hold ? 0.0F : (f - hold) / (1.0F - hold);
        return (i + s) * p;
    }

    /** 1 -> 0 over 3 ticks once every period ticks (phase shifted): sudden twitches. t must be >= 0. */
    private static float twitch(float t, float period, float phase) {
        float m = (t + phase) % period;
        return m < 3.0F ? 1.0F - m / 3.0F : 0.0F;
    }

    /** Stepped progress: holds still, then lurches to the next step (jerky motion), x in 0..1. */
    private static float jerky(float x, float steps) {
        float c = Mth.clamp(x, 0.0F, 1.0F) * steps;
        float i = (float) Mth.floor(c);
        float f = c - i;
        float s = f < 0.55F ? 0.0F : ease((f - 0.55F) / 0.45F);
        return Math.min(1.0F, (i + s) / steps);
    }

    /** Damped spring response 0..1 with overshoot (x in ticks since the step). */
    private static float spring(float x, float freq, float damp) {
        if (x <= 0.0F) {
            return 0.0F;
        }
        return 1.0F - (float) Math.exp(-damp * x) * Mth.cos(freq * x);
    }
    /** Per-entity animation memory: the previous pose, the values to blend from, smoothed values. */
    private static final class State {
        int pose = -1;
        int prev = -1;
        boolean blending;
        float lastAge = -1000.0F;
        float[] from;
        float[] last;
        final float[] fv = new float[8];
        final float[] ft = new float[] {-1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F};
    }

    private State state(Entity entity, int pose, float age) {
        State s = this.states.get(entity);
        if (s == null) {
            s = new State();
            s.from = new float[this.all.length * 9];
            s.last = new float[this.all.length * 9];
            s.pose = pose;
            this.states.put(entity, s);
        } else if (s.pose != pose) {
            System.arraycopy(s.last, 0, s.from, 0, s.last.length);
            // blend only from a frame that was actually seen a moment ago
            s.blending = age - s.lastAge < 10.0F;
            s.prev = s.pose;
            s.pose = pose;
        }
        return s;
    }

    /** Eases every part from the values shown when the pose changed to the new pose over `ticks`. */
    private void blend(State s, float pt, float ticks, float age) {
        boolean on = s.blending && ticks > 0.0F && pt < ticks;
        if (!on) {
            s.blending = false;
        }
        float k = on ? ease(pt / ticks) : 1.0F;
        float[] f = s.from;
        float[] l = s.last;
        for (int i = 0; i < this.all.length; i++) {
            ModelPart p = this.all[i];
            int o = i * 9;
            if (on) {
                p.x = Mth.lerp(k, f[o], p.x);
                p.y = Mth.lerp(k, f[o + 1], p.y);
                p.z = Mth.lerp(k, f[o + 2], p.z);
                p.xRot = Mth.lerp(k, f[o + 3], p.xRot);
                p.yRot = Mth.lerp(k, f[o + 4], p.yRot);
                p.zRot = Mth.lerp(k, f[o + 5], p.zRot);
                p.xScale = Mth.lerp(k, f[o + 6], p.xScale);
                p.yScale = Mth.lerp(k, f[o + 7], p.yScale);
                p.zScale = Mth.lerp(k, f[o + 8], p.zScale);
            }
            l[o] = p.x;
            l[o + 1] = p.y;
            l[o + 2] = p.z;
            l[o + 3] = p.xRot;
            l[o + 4] = p.yRot;
            l[o + 5] = p.zRot;
            l[o + 6] = p.xScale;
            l[o + 7] = p.yScale;
            l[o + 8] = p.zScale;
        }
        s.lastAge = age;
    }

    /** Undoes the rotations of `chain` (the target's ancestors, root side first) so that `target` stays level / hangs
     *  straight down in model space (trays, glasses, strands of hair, keys); add any sway afterwards. */
    private static void level(ModelPart target, ModelPart... chain) {
        float m00 = 1.0F, m01 = 0.0F, m02 = 0.0F, m10 = 0.0F, m11 = 1.0F, m12 = 0.0F, m20 = 0.0F, m21 = 0.0F, m22 = 1.0F;
        for (ModelPart p : chain) {
            float cz = Mth.cos(p.zRot), sz = Mth.sin(p.zRot), cy = Mth.cos(p.yRot), sy = Mth.sin(p.yRot);
            float cx = Mth.cos(p.xRot), sx = Mth.sin(p.xRot);
            float r00 = cz * cy, r01 = cz * sy * sx - sz * cx, r02 = cz * sy * cx + sz * sx;
            float r10 = sz * cy, r11 = sz * sy * sx + cz * cx, r12 = sz * sy * cx - cz * sx;
            float r20 = -sy, r21 = cy * sx, r22 = cy * cx;
            float n00 = m00 * r00 + m01 * r10 + m02 * r20, n01 = m00 * r01 + m01 * r11 + m02 * r21, n02 = m00 * r02 + m01 * r12 + m02 * r22;
            float n10 = m10 * r00 + m11 * r10 + m12 * r20, n11 = m10 * r01 + m11 * r11 + m12 * r21, n12 = m10 * r02 + m11 * r12 + m12 * r22;
            float n20 = m20 * r00 + m21 * r10 + m22 * r20, n21 = m20 * r01 + m21 * r11 + m22 * r21, n22 = m20 * r02 + m21 * r12 + m22 * r22;
            m00 = n00; m01 = n01; m02 = n02; m10 = n10; m11 = n11; m12 = n12; m20 = n20; m21 = n21; m22 = n22;
        }
        // local rotation = transpose(M), decomposed as Rz * Ry * Rx
        target.yRot = (float) Math.asin(Mth.clamp(-m02, -1.0F, 1.0F));
        target.xRot = (float) Math.atan2(m12, m22);
        target.zRot = (float) Math.atan2(m01, m00);
    }

    /** A value that follows its target with a lag (exponential, `speed` per tick), remembered per entity. */
    private static float follow(State s, int slot, float target, float speed, float t) {
        float last = s.ft[slot];
        if (last < 0.0F || t < last || t - last > 40.0F) {
            s.fv[slot] = target;
        } else {
            float k = 1.0F - (float) Math.exp(-speed * (t - last));
            s.fv[slot] = s.fv[slot] + (target - s.fv[slot]) * k;
        }
        s.ft[slot] = t;
        return s.fv[slot];
    }
