    @Override
    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        // resetPose restores only positions and rotations: scales and visibility are reset here
        for (ModelPart p : this.all) {
            p.xScale = 1.0F;
            p.yScale = 1.0F;
            p.zScale = 1.0F;
            p.visible = true;
            p.skipDraw = false;
        }
        // hidden while the entity is invisible (the eyes layer draws this model too, so it hides as well)
        this.root.visible = !entity.isInvisible();
        if (!this.root.visible) {
            return;
        }
        float partial = ageInTicks - (float) Mth.floor(ageInTicks);
        int pose = entity.pose();
        float pt = Math.max(0.0F, entity.poseTime(partial));
        float glitch = Mth.clamp(entity.glitch(partial), 0.0F, 1.0F);
        final float poseTicks = pt;
        State mem = this.state(entity, pose, ageInTicks);
        int prev = mem.prev;
        float blend = 8.0F;
        float t = ageInTicks;
        if (glitch > 0.0F) {
            float held = stutter(ageInTicks, glitch);
            float lost = ageInTicks - held;
            pt = Math.max(0.0F, pt - lost);
            limbSwing = limbSwing - lost * limbSwingAmount;
            t = held;
        }
        float yaw = netHeadYaw * 0.017453292F;
        float pitch = headPitch * 0.017453292F;

        float breath = Mth.sin(t * 0.045F);
        float jit = glitch * noise(t * 1.8F);
        float jit2 = glitch * noise(t * 2.4F + 90.0F);
        // his head follows you a moment late
        float hy = follow(mem, 0, Mth.clamp(yaw, -1.2F, 1.2F), 0.07F, t);
        float hp = Mth.clamp(pitch, -0.5F, 0.5F);
        this.glare.visible = false;
        this.mouth.visible = false;
        float keySwing = 0.0F;
        if (pose == SIT) {
            // at the desk: seat 7.5 px up, leaning to the monitors; the mouse hand twitches, the left types in bursts
            this.body.y = 15.4F;
            this.rightLeg.y = 15.4F;
            this.leftLeg.y = 15.4F;
            this.rightLeg.xRot = -1.42F;
            this.leftLeg.xRot = -1.42F;
            this.rightLeg.yRot = 0.1F;
            this.leftLeg.yRot = -0.12F;
            this.rightShin.xRot = 1.35F;
            this.leftShin.xRot = 1.5F;
            this.body.xRot = 0.32F + breath * 0.01F;
            float mx = noise(t * 0.4F) * 0.05F + twitch(t, 37.0F, 0.0F) * 0.04F;
            float typing = Math.max(0.0F, noise(t * 0.07F)) * Mth.sin(t * 2.3F);
            this.rightArm.xRot = -0.374F + mx;
            this.rightArm.zRot = -0.420F;
            this.rightArm.yRot = -0.139F + mx;
            this.rightForearm.xRot = -1.665F;
            this.rightHand.xRot = 0.172F;
            this.leftArm.xRot = -0.315F;
            this.leftArm.zRot = 0.521F;
            this.leftArm.yRot = 0.311F;
            this.leftForearm.xRot = -1.550F + typing * 0.06F;
            this.leftHand.xRot = 0.102F + typing * 0.15F;
            this.neck.xRot = 0.1F;
            this.head.xRot = -0.2F + Mth.sin(t * 0.013F) * 0.04F;
            this.head.yRot = Mth.sin(t * 0.011F) * 0.35F + noise(t * 0.03F) * 0.12F;
            this.glare.visible = true;
        } else if (pose == WALK || pose == STAND || pose == LOOK) {
            // slouched, the head jutting forward; stiff steps when walking
            float a = pose == WALK ? Math.min(1.0F, limbSwingAmount * 1.4F) : 0.0F;
            float c = limbSwing * 0.7F;
            float s = Mth.sin(c);
            this.rightLeg.xRot = s * 0.42F * a;
            this.leftLeg.xRot = -s * 0.42F * a;
            this.rightShin.xRot = Math.max(0.0F, Mth.sin(c - 1.2F)) * 0.25F * a;
            this.leftShin.xRot = Math.max(0.0F, -Mth.sin(c - 1.2F)) * 0.25F * a;
            this.body.y = 10.5F + Math.abs(Mth.cos(c)) * 0.3F * a;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.body.xRot = 0.16F + breath * 0.008F;
            this.rightArm.xRot = -s * 0.14F * a + 0.05F;
            this.leftArm.xRot = s * 0.14F * a + 0.05F;
            this.rightArm.zRot = 0.07F;
            this.leftArm.zRot = -0.07F;
            this.rightForearm.xRot = -0.15F;
            this.leftForearm.xRot = -0.15F;
            this.neck.xRot = 0.35F;
            this.head.xRot = -0.25F + hp * 0.5F;
            this.head.yRot = hy;
            keySwing = s * 0.35F * a;
            if (pose == LOOK) {
                // scanning: the head sweeps slowly left, holds, sweeps right; the body lags behind; the glasses flash
                float sweep = Mth.sin(pt * 0.045F);
                float sc = Mth.clamp(sweep * 1.6F, -1.0F, 1.0F);
                this.head.yRot = sc * 1.05F;
                this.neck.yRot = sc * 0.2F;
                this.body.yRot = Mth.sin(pt * 0.045F - 0.9F) * 0.22F;
                this.head.xRot = -0.2F + Mth.sin(pt * 0.09F) * 0.05F;
                this.glare.visible = Math.abs(sc) < 0.25F;
            }
            if (pose == STAND) {
                this.head.zRot = Mth.sin(t * 0.017F) * 0.05F;
            }
        } else if (pose == BOW) {
            // a deep bow held too long, the head hanging loose, hands flat on his thighs
            float down = easeOut(pt / 16.0F);
            this.body.xRot = 1.3F * down + breath * 0.01F;
            this.neck.xRot = 0.35F * down;
            this.head.xRot = 0.45F * down;
            this.head.zRot = 0.05F * down;
            this.rightArm.xRot = -1.05F * down;
            this.leftArm.xRot = -1.05F * down;
            this.rightArm.zRot = 0.04F;
            this.leftArm.zRot = -0.04F;
            this.rightForearm.xRot = -0.1F;
            this.leftForearm.xRot = -0.1F;
        } else if (pose == CHASE) {
            // a fast, stiff power walk: arms pumping at right angles, long straight-legged strides; he never runs
            float a = Math.min(1.0F, limbSwingAmount * 1.2F);
            float c = limbSwing * 0.85F;
            float s = Mth.sin(c);
            this.rightLeg.xRot = s * 0.7F * a;
            this.leftLeg.xRot = -s * 0.7F * a;
            this.rightShin.xRot = Math.max(0.0F, Mth.sin(c - 1.4F)) * 0.2F * a;
            this.leftShin.xRot = Math.max(0.0F, -Mth.sin(c - 1.4F)) * 0.2F * a;
            this.body.y = 10.5F + Math.abs(Mth.cos(c)) * 0.35F * a;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.body.xRot = 0.12F;
            this.body.yRot = -s * 0.08F * a;
            this.rightArm.xRot = -s * 0.8F * a - 0.1F;
            this.leftArm.xRot = s * 0.8F * a - 0.1F;
            this.rightArm.zRot = 0.1F;
            this.leftArm.zRot = -0.1F;
            this.rightForearm.xRot = -1.45F;
            this.leftForearm.xRot = -1.45F;
            this.neck.xRot = 0.3F;
            this.head.xRot = -0.3F + hp * 0.6F;
            this.head.yRot = Mth.clamp(yaw, -1.0F, 1.0F) * 0.8F;
            this.glare.visible = true;
            keySwing = s * 0.8F * a;
            blend = 4.0F;
        } else {
            // REACH: both hands slowly out toward you, the head tilting, "o-kyaku-sama..."
            float go = easeOut(pt / 20.0F);
            this.body.xRot = 0.22F * go;
            this.rightArm.xRot = -1.35F * go;
            this.leftArm.xRot = -1.42F * go;
            this.rightArm.zRot = 0.12F * go;
            this.leftArm.zRot = -0.12F * go;
            this.rightForearm.xRot = -0.2F * go;
            this.leftForearm.xRot = -0.15F * go;
            this.rightHand.xRot = -0.3F * go;
            this.leftHand.xRot = -0.25F * go;
            this.neck.xRot = 0.25F;
            this.head.xRot = -0.15F + hp * 0.5F;
            this.head.yRot = hy;
            this.head.zRot = 0.3F * go + Mth.sin(t * 0.05F) * 0.04F;
            this.mouth.visible = go > 0.5F;
            this.glare.visible = Mth.sin(t * 0.3F) > 0.3F;
        }
        this.head.zRot = this.head.zRot + jit * 0.35F;
        this.head.yRot = this.head.yRot + jit2 * 0.3F;
        this.keys.zRot = keySwing;
        this.blend(mem, poseTicks, blend, ageInTicks);
        // the loosened tie and the keys hang with gravity, swinging a little behind his movements
        level(this.tie, this.body);
        this.tie.xRot = this.tie.xRot - 0.12F + Mth.sin(t * 0.21F) * 0.02F;
        level(this.keysRing, this.body, this.keys);
        this.keysRing.zRot = this.keysRing.zRot + this.keys.zRot * 0.6F;
    }

    /** Smoothstep 0..1. */
    private static float ease(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * (3.0F - 2.0F * c);
    }

    /** Fast in, slow out (0..1). */
    private static float easeOut(float x) {
        float c = 1.0F - Mth.clamp(x, 0.0F, 1.0F);
        return 1.0F - c * c * c;
    }

    /** Slow in, fast out (0..1). */
    private static float easeIn(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * c;
    }

    /** 0 before a, rises to 1 at b (smooth). */
    private static float span(float x, float a, float b) {
        return ease((x - a) / (b - a));
    }

    /** Pseudo random 0..1 for an integer-valued x (bounded argument: Mth.sin is a lookup table). */
    private static float hash(float x) {
        float k = x - 1024.0F * (float) Mth.floor(x / 1024.0F);
        float s = Mth.sin(k * 12.9898F + 4.1414F) * 43758.547F;
        return s - (float) Mth.floor(s);
    }

    /** Smooth value noise -1..1. */
    private static float noise(float x) {
        float i = (float) Mth.floor(x);
        float f = x - i;
        float u = f * f * (3.0F - 2.0F * f);
        return Mth.lerp(u, hash(i), hash(i + 1.0F)) * 2.0F - 1.0F;
    }

    /** Missing frames: time holds still for most of every 3-tick window, then jumps to catch up (g = 0..1). */
    private static float stutter(float x, float g) {
        float p = 3.0F;
        float i = (float) Mth.floor(x / p);
        float f = x / p - i;
        float hold = Mth.clamp(g, 0.0F, 1.0F) * (0.55F + 0.4F * hash(i + 17.0F));
        float s = f < hold ? 0.0F : (f - hold) / (1.0F - hold);
        return (i + s) * p;
    }

    /** 1 -> 0 over 3 ticks once every period ticks (phase shifted): sudden twitches. t must be >= 0. */
    private static float twitch(float t, float period, float phase) {
        float m = (t + phase) % period;
        return m < 3.0F ? 1.0F - m / 3.0F : 0.0F;
    }

    /** Stepped progress: holds still, then lurches to the next step (jerky motion), x in 0..1. */
    private static float jerky(float x, float steps) {
        float c = Mth.clamp(x, 0.0F, 1.0F) * steps;
        float i = (float) Mth.floor(c);
        float f = c - i;
        float s = f < 0.55F ? 0.0F : ease((f - 0.55F) / 0.45F);
        return Math.min(1.0F, (i + s) / steps);
    }

    /** Damped spring response 0..1 with overshoot (x in ticks since the step). */
    private static float spring(float x, float freq, float damp) {
        if (x <= 0.0F) {
            return 0.0F;
        }
        return 1.0F - (float) Math.exp(-damp * x) * Mth.cos(freq * x);
    }
    /** Per-entity animation memory: the previous pose, the values to blend from, smoothed values. */
    private static final class State {
        int pose = -1;
        int prev = -1;
        boolean blending;
        float lastAge = -1000.0F;
        float[] from;
        float[] last;
        final float[] fv = new float[8];
        final float[] ft = new float[] {-1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F};
    }

    private State state(Entity entity, int pose, float age) {
        State s = this.states.get(entity);
        if (s == null) {
            s = new State();
            s.from = new float[this.all.length * 9];
            s.last = new float[this.all.length * 9];
            s.pose = pose;
            this.states.put(entity, s);
        } else if (s.pose != pose) {
            System.arraycopy(s.last, 0, s.from, 0, s.last.length);
            // blend only from a frame that was actually seen a moment ago
            s.blending = age - s.lastAge < 10.0F;
            s.prev = s.pose;
            s.pose = pose;
        }
        return s;
    }

    /** Eases every part from the values shown when the pose changed to the new pose over `ticks`. */
    private void blend(State s, float pt, float ticks, float age) {
        boolean on = s.blending && ticks > 0.0F && pt < ticks;
        if (!on) {
            s.blending = false;
        }
        float k = on ? ease(pt / ticks) : 1.0F;
        float[] f = s.from;
        float[] l = s.last;
        for (int i = 0; i < this.all.length; i++) {
            ModelPart p = this.all[i];
            int o = i * 9;
            if (on) {
                p.x = Mth.lerp(k, f[o], p.x);
                p.y = Mth.lerp(k, f[o + 1], p.y);
                p.z = Mth.lerp(k, f[o + 2], p.z);
                p.xRot = Mth.lerp(k, f[o + 3], p.xRot);
                p.yRot = Mth.lerp(k, f[o + 4], p.yRot);
                p.zRot = Mth.lerp(k, f[o + 5], p.zRot);
                p.xScale = Mth.lerp(k, f[o + 6], p.xScale);
                p.yScale = Mth.lerp(k, f[o + 7], p.yScale);
                p.zScale = Mth.lerp(k, f[o + 8], p.zScale);
            }
            l[o] = p.x;
            l[o + 1] = p.y;
            l[o + 2] = p.z;
            l[o + 3] = p.xRot;
            l[o + 4] = p.yRot;
            l[o + 5] = p.zRot;
            l[o + 6] = p.xScale;
            l[o + 7] = p.yScale;
            l[o + 8] = p.zScale;
        }
        s.lastAge = age;
    }

    /** Undoes the rotations of `chain` (the target's ancestors, root side first) so that `target` stays level / hangs
     *  straight down in model space (trays, glasses, strands of hair, keys); add any sway afterwards. */
    private static void level(ModelPart target, ModelPart... chain) {
        float m00 = 1.0F, m01 = 0.0F, m02 = 0.0F, m10 = 0.0F, m11 = 1.0F, m12 = 0.0F, m20 = 0.0F, m21 = 0.0F, m22 = 1.0F;
        for (ModelPart p : chain) {
            float cz = Mth.cos(p.zRot), sz = Mth.sin(p.zRot), cy = Mth.cos(p.yRot), sy = Mth.sin(p.yRot);
            float cx = Mth.cos(p.xRot), sx = Mth.sin(p.xRot);
            float r00 = cz * cy, r01 = cz * sy * sx - sz * cx, r02 = cz * sy * cx + sz * sx;
            float r10 = sz * cy, r11 = sz * sy * sx + cz * cx, r12 = sz * sy * cx - cz * sx;
            float r20 = -sy, r21 = cy * sx, r22 = cy * cx;
            float n00 = m00 * r00 + m01 * r10 + m02 * r20, n01 = m00 * r01 + m01 * r11 + m02 * r21, n02 = m00 * r02 + m01 * r12 + m02 * r22;
            float n10 = m10 * r00 + m11 * r10 + m12 * r20, n11 = m10 * r01 + m11 * r11 + m12 * r21, n12 = m10 * r02 + m11 * r12 + m12 * r22;
            float n20 = m20 * r00 + m21 * r10 + m22 * r20, n21 = m20 * r01 + m21 * r11 + m22 * r21, n22 = m20 * r02 + m21 * r12 + m22 * r22;
            m00 = n00; m01 = n01; m02 = n02; m10 = n10; m11 = n11; m12 = n12; m20 = n20; m21 = n21; m22 = n22;
        }
        // local rotation = transpose(M), decomposed as Rz * Ry * Rx
        target.yRot = (float) Math.asin(Mth.clamp(-m02, -1.0F, 1.0F));
        target.xRot = (float) Math.atan2(m12, m22);
        target.zRot = (float) Math.atan2(m01, m00);
    }

    /** A value that follows its target with a lag (exponential, `speed` per tick), remembered per entity. */
    private static float follow(State s, int slot, float target, float speed, float t) {
        float last = s.ft[slot];
        if (last < 0.0F || t < last || t - last > 40.0F) {
            s.fv[slot] = target;
        } else {
            float k = 1.0F - (float) Math.exp(-speed * (t - last));
            s.fv[slot] = s.fv[slot] + (target - s.fv[slot]) * k;
        }
        s.ft[slot] = t;
        return s.fv[slot];
    }
