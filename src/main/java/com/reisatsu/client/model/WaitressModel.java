    @Override
    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        // hidden while the entity is invisible (the eyes layer draws this model too, so it hides as well)
        this.root.visible = !entity.isInvisible();
        if (!this.root.visible) {
            return;
        }
        float partial = ageInTicks - (float) Mth.floor(ageInTicks);
        int pose = entity.pose();
        float pt = Math.max(0.0F, entity.poseTime(partial));
        float glitch = Mth.clamp(entity.glitch(partial), 0.0F, 1.0F);
        final float poseTicks = pt;
        State mem = this.state(entity, pose, ageInTicks);
        int prev = mem.prev;
        float blend = 8.0F;
        float t = ageInTicks;
        if (glitch > 0.0F) {
            float held = stutter(ageInTicks, glitch);
            float lost = ageInTicks - held;
            pt = Math.max(0.0F, pt - lost);
            limbSwing = limbSwing - lost * limbSwingAmount;
            t = held;
        }
        float yaw = netHeadYaw * 0.017453292F;
        float pitch = headPitch * 0.017453292F;

        float breath = Mth.sin(t * 0.055F);
        float look = Mth.clamp(yaw, -1.1F, 1.1F);
        float lookP = Mth.clamp(pitch, -0.5F, 0.6F);
        // the head never straightens: a 30 degree tilt with a slow drift; every few seconds it ticks upright for an instant
        float tilt = 0.52F + Mth.sin(t * 0.021F) * 0.04F - twitch(t, 97.0F, 13.0F) * 0.22F;
        float jit = glitch * noise(t * 1.7F);
        float jit2 = glitch * noise(t * 2.3F + 40.0F);
        this.tray.visible = true;
        this.glass.visible = true;
        this.heldGlass.visible = false;
        this.mouth.visible = false;
        this.jaw.visible = false;
        this.mouth.yScale = 0.01F;
        this.glare.visible = false;

        if (pose == WALK) {
            float a = Math.min(1.0F, limbSwingAmount * 1.5F);
            float c = limbSwing * 1.05F;
            float s = Mth.sin(c);
            // short quick regular steps; the body glides: no bob, no sway at all
            this.rightLeg.xRot = s * 0.42F * a;
            this.leftLeg.xRot = -s * 0.42F * a;
            this.rightShin.xRot = Math.max(0.0F, Mth.sin(c - 1.2F)) * 0.55F * a;
            this.leftShin.xRot = Math.max(0.0F, -Mth.sin(c - 1.2F)) * 0.55F * a;
            this.body.xRot = 0.03F;
            this.skirt.xRot = -0.03F + s * 0.03F * a;
            this.rightArm.xRot = s * 0.07F * a + 0.03F;
            this.rightArm.zRot = 0.05F;
            this.rightForearm.xRot = -0.15F;
            // the tray on the flat left palm beside her head
            this.leftArm.xRot = -0.25F;
            this.leftArm.zRot = -0.8F;
            this.leftForearm.zRot = -2.3F;
            this.leftForearm.xRot = -0.1F;
            this.head.zRot = tilt * 0.8F + jit * 0.4F;
            this.head.yRot = look * 0.8F;
            this.head.xRot = lookP * 0.6F + 0.06F;
        } else if (pose == SERVE) {
            // bends, takes the glass off the tray with the right hand and sets it on the table (released at pt 24)
            float bend = span(pt, 0.0F, 10.0F);
            float k1 = span(pt, 4.0F, 12.0F);
            float k2 = span(pt, 13.0F, 23.0F);
            float k3 = span(pt, 25.0F, 35.0F);
            this.body.xRot = 0.5F * bend + breath * 0.008F;
            this.skirt.xRot = -0.42F * bend;
            this.neck.xRot = 0.12F * bend;
            this.head.xRot = 0.3F * bend + lookP * 0.3F;
            this.head.zRot = tilt * 0.9F + jit * 0.4F;
            this.head.yRot = look * 0.35F;
            // tray held low at her left side, out of the way of her face
            this.leftArm.xRot = 0.787F * bend;
            this.leftArm.yRot = -0.199F * bend;
            this.leftArm.zRot = -0.289F * bend;
            this.leftForearm.xRot = -2.027F * bend - 0.1F * (1.0F - bend);
            // right hand: rest -> the glass on the tray -> down to the table -> back to the side
            float rx = Mth.lerp(k1, 0.0F, -0.925F);
            float rz = Mth.lerp(k1, 0.05F, 0.157F);
            float ry = Mth.lerp(k1, 0.0F, -1.2F);
            float rf = Mth.lerp(k1, -0.15F, -1.855F);
            rx = Mth.lerp(k2, rx, -0.452F);
            rz = Mth.lerp(k2, rz, -0.274F);
            ry = Mth.lerp(k2, ry, -0.315F);
            rf = Mth.lerp(k2, rf, -1.156F);
            this.rightArm.xRot = Mth.lerp(k3, rx, -0.2F);
            this.rightArm.zRot = Mth.lerp(k3, rz, 0.06F);
            this.rightArm.yRot = Mth.lerp(k3, ry, 0.0F);
            this.rightForearm.xRot = Mth.lerp(k3, rf, -0.3F);
            this.heldGlass.visible = pt >= 12.0F && pt < 24.0F;
            this.glass.visible = pt < 12.0F;
        } else if (pose == BOW) {
            // a 90 degree bow, held; the tray stays level by her left knee; loose strands fall forward;
            // after 34 ticks the head slowly lifts to stare at the door while the body stays folded
            float down = easeOut(pt / 14.0F);
            float lift = span(pt, 34.0F, 72.0F);
            this.body.xRot = 1.5F * down + Mth.sin(pt * 0.05F) * 0.01F;
            this.skirt.xRot = -1.3F * down;
            this.neck.xRot = 0.1F * down - 0.8F * lift;
            this.head.xRot = 0.12F * down - 0.75F * lift;
            this.head.zRot = 0.06F * down + tilt * 0.7F * lift + jit * 0.3F;
            this.head.yRot = look * 0.3F * lift;
            this.rightArm.xRot = 0.348F * down;
            this.rightArm.zRot = -0.448F * down + 0.05F;
            this.rightForearm.xRot = -1.586F * down;
            this.leftArm.xRot = 0.047F * down;
            this.leftArm.zRot = 0.381F * down;
            this.leftForearm.xRot = -1.866F * down;
        } else if (pose == STAND) {
            // waiting: the tray flat before her in both hands, head tilted 30 degrees, tracking you without straightening
            this.body.xRot = 0.02F + breath * 0.008F;
            this.head.zRot = tilt + jit * 0.5F;
            this.head.yRot = look * 0.95F;
            this.head.xRot = lookP * 0.7F + 0.05F;
            this.neck.zRot = tilt * 0.12F;
            this.rightArm.xRot = 0.103F;
            this.rightArm.zRot = -0.183F;
            this.rightArm.yRot = -0.181F;
            this.rightForearm.xRot = -1.445F;
            this.leftArm.xRot = 0.103F;
            this.leftArm.zRot = 0.183F;
            this.leftArm.yRot = 0.181F;
            this.leftForearm.xRot = -1.445F;
            this.tray.x = -2.4F;
        } else if (pose == NOTICE) {
            // the head rolls over sideways to 90 degrees in three jerks, the polite mouth splits open, the hollows light up
            float roll = jerky(pt / 14.0F, 3.0F);
            float open = span(pt, 5.0F, 12.0F);
            this.head.zRot = tilt + (1.6F - tilt) * roll + jit * 0.6F;
            this.head.yRot = look;
            this.head.xRot = lookP * 0.5F;
            this.neck.zRot = 0.25F * roll;
            float o = open * (1.0F + noise(t * 0.9F) * 0.08F);
            this.mouth.visible = open > 0.01F;
            this.jaw.visible = open > 0.01F;
            this.mouth.yScale = Math.max(0.01F, o);
            this.jaw.y = this.jaw.y + 2.0F * o;
            this.glare.visible = pt > 3.0F;
            this.body.xRot = 0.04F;
            this.rightArm.xRot = 0.103F - 0.4F * open;
            this.rightArm.zRot = -0.183F;
            this.rightArm.yRot = -0.181F;
            this.rightForearm.xRot = -1.445F + 1.2F * open;
            this.leftArm.xRot = 0.103F;
            this.leftArm.zRot = 0.183F;
            this.leftArm.yRot = 0.181F;
            this.leftForearm.xRot = -1.445F;
            this.tray.x = -2.4F;
            blend = 2.0F;
        } else {
            // CHASE: fast and stiff, knees barely bending, arms straight out, the head lolled over sideways, mouth open
            float a = Math.min(1.0F, limbSwingAmount * 1.3F);
            float c = limbSwing * 1.35F;
            float s = Mth.sin(c);
            this.tray.visible = false;
            this.glass.visible = false;
            this.rightLeg.xRot = s * 0.75F * a;
            this.leftLeg.xRot = -s * 0.75F * a;
            this.rightShin.xRot = Math.max(0.0F, Mth.sin(c - 1.4F)) * 0.25F * a;
            this.leftShin.xRot = Math.max(0.0F, -Mth.sin(c - 1.4F)) * 0.25F * a;
            this.body.xRot = 0.16F;
            this.skirt.xRot = -0.12F + s * 0.05F * a;
            this.rightArm.xRot = -1.45F + s * 0.05F * a + jit2 * 0.3F;
            this.leftArm.xRot = -1.45F - s * 0.05F * a - jit2 * 0.3F;
            this.rightArm.zRot = 0.08F;
            this.leftArm.zRot = -0.08F;
            this.rightForearm.xRot = -0.08F;
            this.leftForearm.xRot = -0.08F;
            this.head.zRot = 1.35F + Mth.sin(t * 0.13F) * 0.06F + jit;
            this.head.yRot = look * 0.6F;
            this.head.xRot = lookP * 0.4F - 0.08F;
            float o = 0.9F + Mth.sin(t * 0.4F) * 0.06F;
            this.mouth.visible = true;
            this.jaw.visible = true;
            this.mouth.yScale = o;
            this.jaw.y = this.jaw.y + 2.0F * o;
            this.glare.visible = true;
            blend = 4.0F;
        }
        this.neck.zRot = this.neck.zRot + jit2 * 0.25F;
        this.rightArm.zRot = this.rightArm.zRot + jit * 0.2F;
        this.blend(mem, poseTicks, blend, ageInTicks);
        // after the blend: the tray stays level on her palm, the glasses stand upright, loose strands hang down
        level(this.tray, this.body, this.leftArm, this.leftForearm, this.leftHand);
        level(this.heldGlass, this.body, this.rightArm, this.rightForearm, this.rightHand);
        level(this.lockR, this.body, this.neck, this.head);
        level(this.lockL, this.body, this.neck, this.head);
        this.lockR.xRot = this.lockR.xRot + Mth.sin(t * 0.07F) * 0.05F;
        this.lockL.xRot = this.lockL.xRot + Mth.sin(t * 0.07F + 1.1F) * 0.05F;
    }

    /** Smoothstep 0..1. */
    private static float ease(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * (3.0F - 2.0F * c);
    }

    /** Fast in, slow out (0..1). */
    private static float easeOut(float x) {
        float c = 1.0F - Mth.clamp(x, 0.0F, 1.0F);
        return 1.0F - c * c * c;
    }

    /** Slow in, fast out (0..1). */
    private static float easeIn(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * c;
    }

    /** 0 before a, rises to 1 at b (smooth). */
    private static float span(float x, float a, float b) {
        return ease((x - a) / (b - a));
    }

    /** Pseudo random 0..1 for an integer-valued x (bounded argument: Mth.sin is a lookup table). */
    private static float hash(float x) {
        float k = x - 1024.0F * (float) Mth.floor(x / 1024.0F);
        float s = Mth.sin(k * 12.9898F + 4.1414F) * 43758.547F;
        return s - (float) Mth.floor(s);
    }

    /** Smooth value noise -1..1. */
    private static float noise(float x) {
        float i = (float) Mth.floor(x);
        float f = x - i;
        float u = f * f * (3.0F - 2.0F * f);
        return Mth.lerp(u, hash(i), hash(i + 1.0F)) * 2.0F - 1.0F;
    }

    /** Missing frames: time holds still for most of every 3-tick window, then jumps to catch up (g = 0..1). */
    private static float stutter(float x, float g) {
        float p = 3.0F;
        float i = (float) Mth.floor(x / p);
        float f = x / p - i;
        float hold = Mth.clamp(g, 0.0F, 1.0F) * (0.55F + 0.4F * hash(i + 17.0F));
        float s = f < hold ? 0.0F : (f - hold) / (1.0F - hold);
        return (i + s) * p;
    }

    /** 1 -> 0 over 3 ticks once every period ticks (phase shifted): sudden twitches. t must be >= 0. */
    private static float twitch(float t, float period, float phase) {
        float m = (t + phase) % period;
        return m < 3.0F ? 1.0F - m / 3.0F : 0.0F;
    }

    /** Stepped progress: holds still, then lurches to the next step (jerky motion), x in 0..1. */
    private static float jerky(float x, float steps) {
        float c = Mth.clamp(x, 0.0F, 1.0F) * steps;
        float i = (float) Mth.floor(c);
        float f = c - i;
        float s = f < 0.55F ? 0.0F : ease((f - 0.55F) / 0.45F);
        return Math.min(1.0F, (i + s) / steps);
    }

    /** Damped spring response 0..1 with overshoot (x in ticks since the step). */
    private static float spring(float x, float freq, float damp) {
        if (x <= 0.0F) {
            return 0.0F;
        }
        return 1.0F - (float) Math.exp(-damp * x) * Mth.cos(freq * x);
    }
    /** Per-entity animation memory: the previous pose, the values to blend from, smoothed values. */
    private static final class State {
        int pose = -1;
        int prev = -1;
        boolean blending;
        float lastAge = -1000.0F;
        float[] from;
        float[] last;
        final float[] fv = new float[8];
        final float[] ft = new float[] {-1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F};
    }

    private State state(Entity entity, int pose, float age) {
        State s = this.states.get(entity);
        if (s == null) {
            s = new State();
            s.from = new float[this.all.length * 9];
            s.last = new float[this.all.length * 9];
            s.pose = pose;
            this.states.put(entity, s);
        } else if (s.pose != pose) {
            System.arraycopy(s.last, 0, s.from, 0, s.last.length);
            // blend only from a frame that was actually seen a moment ago
            s.blending = age - s.lastAge < 10.0F;
            s.prev = s.pose;
            s.pose = pose;
        }
        return s;
    }

    /** Eases every part from the values shown when the pose changed to the new pose over `ticks`. */
    private void blend(State s, float pt, float ticks, float age) {
        boolean on = s.blending && ticks > 0.0F && pt < ticks;
        if (!on) {
            s.blending = false;
        }
        float k = on ? ease(pt / ticks) : 1.0F;
        float[] f = s.from;
        float[] l = s.last;
        for (int i = 0; i < this.all.length; i++) {
            ModelPart p = this.all[i];
            int o = i * 9;
            if (on) {
                p.x = Mth.lerp(k, f[o], p.x);
                p.y = Mth.lerp(k, f[o + 1], p.y);
                p.z = Mth.lerp(k, f[o + 2], p.z);
                p.xRot = Mth.lerp(k, f[o + 3], p.xRot);
                p.yRot = Mth.lerp(k, f[o + 4], p.yRot);
                p.zRot = Mth.lerp(k, f[o + 5], p.zRot);
                p.xScale = Mth.lerp(k, f[o + 6], p.xScale);
                p.yScale = Mth.lerp(k, f[o + 7], p.yScale);
                p.zScale = Mth.lerp(k, f[o + 8], p.zScale);
            }
            l[o] = p.x;
            l[o + 1] = p.y;
            l[o + 2] = p.z;
            l[o + 3] = p.xRot;
            l[o + 4] = p.yRot;
            l[o + 5] = p.zRot;
            l[o + 6] = p.xScale;
            l[o + 7] = p.yScale;
            l[o + 8] = p.zScale;
        }
        s.lastAge = age;
    }

    /** Undoes the rotations of `chain` (the target's ancestors, root side first) so that `target` stays level / hangs
     *  straight down in model space (trays, glasses, strands of hair, keys); add any sway afterwards. */
    private static void level(ModelPart target, ModelPart... chain) {
        float m00 = 1.0F, m01 = 0.0F, m02 = 0.0F, m10 = 0.0F, m11 = 1.0F, m12 = 0.0F, m20 = 0.0F, m21 = 0.0F, m22 = 1.0F;
        for (ModelPart p : chain) {
            float cz = Mth.cos(p.zRot), sz = Mth.sin(p.zRot), cy = Mth.cos(p.yRot), sy = Mth.sin(p.yRot);
            float cx = Mth.cos(p.xRot), sx = Mth.sin(p.xRot);
            float r00 = cz * cy, r01 = cz * sy * sx - sz * cx, r02 = cz * sy * cx + sz * sx;
            float r10 = sz * cy, r11 = sz * sy * sx + cz * cx, r12 = sz * sy * cx - cz * sx;
            float r20 = -sy, r21 = cy * sx, r22 = cy * cx;
            float n00 = m00 * r00 + m01 * r10 + m02 * r20, n01 = m00 * r01 + m01 * r11 + m02 * r21, n02 = m00 * r02 + m01 * r12 + m02 * r22;
            float n10 = m10 * r00 + m11 * r10 + m12 * r20, n11 = m10 * r01 + m11 * r11 + m12 * r21, n12 = m10 * r02 + m11 * r12 + m12 * r22;
            float n20 = m20 * r00 + m21 * r10 + m22 * r20, n21 = m20 * r01 + m21 * r11 + m22 * r21, n22 = m20 * r02 + m21 * r12 + m22 * r22;
            m00 = n00; m01 = n01; m02 = n02; m10 = n10; m11 = n11; m12 = n12; m20 = n20; m21 = n21; m22 = n22;
        }
        // local rotation = transpose(M), decomposed as Rz * Ry * Rx
        target.yRot = (float) Math.asin(Mth.clamp(-m02, -1.0F, 1.0F));
        target.xRot = (float) Math.atan2(m12, m22);
        target.zRot = (float) Math.atan2(m01, m00);
    }

    /** A value that follows its target with a lag (exponential, `speed` per tick), remembered per entity. */
    private static float follow(State s, int slot, float target, float speed, float t) {
        float last = s.ft[slot];
        if (last < 0.0F || t < last || t - last > 40.0F) {
            s.fv[slot] = target;
        } else {
            float k = 1.0F - (float) Math.exp(-speed * (t - last));
            s.fv[slot] = s.fv[slot] + (target - s.fv[slot]) * k;
        }
        s.ft[slot] = t;
        return s.fv[slot];
    }
