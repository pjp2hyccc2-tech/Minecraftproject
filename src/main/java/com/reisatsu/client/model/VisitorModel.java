    @Override
    public void setupAnim(T entity, float limbSwing, float limbSwingAmount, float ageInTicks, float netHeadYaw, float headPitch) {
        this.root().getAllParts().forEach(ModelPart::resetPose);
        // resetPose restores only positions and rotations: scales and visibility are reset here
        for (ModelPart p : this.all) {
            p.xScale = 1.0F;
            p.yScale = 1.0F;
            p.zScale = 1.0F;
            p.visible = true;
            p.skipDraw = false;
        }
        // hidden while the entity is invisible (the eyes layer draws this model too, so it hides as well)
        this.root.visible = !entity.isInvisible();
        if (!this.root.visible) {
            return;
        }
        float partial = ageInTicks - (float) Mth.floor(ageInTicks);
        int pose = entity.pose();
        float pt = Math.max(0.0F, entity.poseTime(partial));
        float glitch = Mth.clamp(entity.glitch(partial), 0.0F, 1.0F);
        final float poseTicks = pt;
        State mem = this.state(entity, pose, ageInTicks);
        int prev = mem.prev;
        float blend = 8.0F;
        float t = ageInTicks;
        if (glitch > 0.0F) {
            float held = stutter(ageInTicks, glitch);
            float lost = ageInTicks - held;
            pt = Math.max(0.0F, pt - lost);
            limbSwing = limbSwing - lost * limbSwingAmount;
            t = held;
        }
        float yaw = netHeadYaw * 0.017453292F;
        float pitch = headPitch * 0.017453292F;

        float breath = Mth.sin(t * 0.09F);
        float jit = glitch * noise(t * 1.9F);
        float jit2 = glitch * noise(t * 2.7F + 50.0F);
        this.cracks.visible = false;
        boolean seated = pose == SIT || pose == PRESS || (pose == NOTICE && (prev == SIT || prev == PRESS));
        // the broken right arm: forearm bent the wrong way at the elbow and twisted, the glove limp
        this.rightForearm.xRot = 0.62F;
        this.rightForearm.yRot = 1.3F;
        this.rightHand.xRot = 0.45F;
        this.rightHand.zRot = 0.2F;
        this.leftHand.xRot = -0.1F;

        if (seated) {
            // on the booth bench: hips 7 px above the feet, thighs forward, feet on the floor
            this.body.y = 15.75F;
            this.rightLeg.y = 15.75F;
            this.leftLeg.y = 15.75F;
            this.rightLeg.xRot = -1.45F;
            this.leftLeg.xRot = -1.45F;
            this.rightLeg.yRot = 0.08F;
            this.leftLeg.yRot = -0.08F;
            this.rightShin.xRot = 1.42F;
            this.leftShin.xRot = 1.42F;
            this.body.xRot = 0.28F + breath * 0.012F;
            // the left hand flat on the table; the broken arm lying on it palm-up, twisted
            this.leftArm.xRot = -0.543F;
            this.leftArm.zRot = 0.718F;
            this.leftArm.yRot = 0.195F;
            this.leftForearm.xRot = -1.371F;
            this.leftHand.xRot = 0.13F;
            this.rightArm.xRot = -1.905F;
            this.rightArm.zRot = -0.983F;
            this.rightArm.yRot = -0.189F;
            this.rightForearm.xRot = -1.537F;
            this.rightForearm.yRot = 3.0F;
            this.rightHand.xRot = 1.451F;
            this.rightHand.zRot = 0.0F;
            this.neck.xRot = 0.2F;
            this.helmet.xRot = 0.26F + breath * 0.02F;
            this.helmet.zRot = 0.06F;
            if (pose == PRESS) {
                // lift the hand, reach the call button, press (tick 14), hold, back flat by 26
                float up = span(pt, 0.0F, 7.0F) * (1.0F - span(pt, 18.0F, 26.0F));
                float press = span(pt, 9.0F, 13.0F) * (1.0F - span(pt, 15.0F, 18.0F));
                this.leftArm.xRot = Mth.lerp(up, -0.543F, -1.11F) + press * 0.06F;
                this.leftArm.zRot = Mth.lerp(up, 0.718F, -0.665F);
                this.leftArm.yRot = Mth.lerp(up, 0.195F, 0.145F);
                this.leftForearm.xRot = Mth.lerp(up, -1.371F, -1.644F) + press * 0.12F;
                this.leftHand.xRot = Mth.lerp(up, 0.13F, 1.519F) + press * 0.25F;
                this.helmet.yRot = 0.25F * up;
            }
            if (pose == NOTICE) {
                // the helmet snaps round at you with an overshoot; the hands slam flat
                float sn = spring(pt, 0.9F, 0.35F);
                this.helmet.yRot = Mth.clamp(yaw, -1.9F, 1.9F) * sn;
                this.helmet.xRot = Mth.lerp(Math.min(1.0F, sn), 0.26F, Mth.clamp(pitch, -0.6F, 0.6F) - 0.05F);
                this.neck.xRot = 0.2F * (1.0F - Math.min(1.0F, sn));
                this.body.xRot = 0.28F - 0.2F * Math.min(1.0F, sn);
                this.cracks.visible = pt > 2.0F;
                blend = 1.5F;
            }
        } else if (pose == WALK) {
            // slow limp: the right leg stays stiff and swings short; the body drops onto it and lurches
            float a = Math.min(1.0F, limbSwingAmount * 1.6F);
            float c = limbSwing * 0.62F;
            float s = Mth.sin(c);
            float onBad = Math.max(0.0F, -Mth.cos(c));
            this.rightLeg.xRot = s * 0.26F * a;
            this.rightShin.xRot = 0.05F;
            this.leftLeg.xRot = -s * 0.5F * a;
            this.leftShin.xRot = Math.max(0.0F, Mth.sin(c + 0.7F)) * 0.8F * a;
            this.body.y = 10.0F + onBad * 0.7F * a;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.body.zRot = (onBad - 0.4F) * 0.09F * a;
            this.body.xRot = 0.16F + onBad * 0.05F * a;
            this.body.yRot = s * 0.06F * a;
            // the dead arm swings late like a pendulum and flops at the broken elbow
            this.rightArm.xRot = Mth.sin(c - 1.3F) * 0.32F * a + 0.05F;
            this.rightArm.zRot = 0.06F + onBad * 0.08F;
            this.rightForearm.xRot = 0.62F + Mth.sin(c - 2.1F) * 0.28F * a;
            this.rightHand.xRot = 0.45F + Mth.sin(c - 2.6F) * 0.3F * a;
            this.leftArm.xRot = -s * 0.22F * a;
            this.leftArm.zRot = -0.06F;
            this.leftForearm.xRot = -0.25F;
            this.neck.xRot = 0.15F;
            this.helmet.xRot = 0.22F + Mth.sin(c * 2.0F - 0.6F) * 0.04F * a;
            this.helmet.zRot = -(onBad - 0.4F) * 0.07F * a;
            this.helmet.yRot = Mth.clamp(yaw, -0.6F, 0.6F) * 0.3F;
        } else if (pose == STAND) {
            // waiting by the door: helmet down, swaying slightly, perfectly patient
            this.body.xRot = 0.12F + breath * 0.01F;
            this.body.zRot = Mth.sin(t * 0.023F) * 0.025F;
            this.neck.xRot = 0.15F;
            this.helmet.xRot = 0.24F + breath * 0.02F;
            this.helmet.zRot = 0.08F + Mth.sin(t * 0.017F) * 0.03F;
            this.rightArm.xRot = 0.05F + Mth.sin(t * 0.023F - 1.0F) * 0.03F;
            this.rightArm.zRot = 0.07F;
            this.leftArm.xRot = -0.05F;
            this.leftArm.zRot = -0.07F;
            this.leftForearm.xRot = -0.2F;
        } else if (pose == NOTICE) {
            // standing: the helmet snaps toward you with an overshoot and the visor cracks wider
            float sn = spring(pt, 0.9F, 0.35F);
            this.helmet.yRot = Mth.clamp(yaw, -1.9F, 1.9F) * sn;
            this.helmet.xRot = Mth.lerp(Math.min(1.0F, sn), 0.24F, Mth.clamp(pitch, -0.6F, 0.6F));
            this.neck.xRot = 0.15F * (1.0F - Math.min(1.0F, sn));
            this.body.xRot = 0.05F;
            this.rightArm.zRot = 0.1F;
            this.leftArm.xRot = -0.35F * Math.min(1.0F, sn);
            this.leftArm.zRot = -0.25F;
            this.leftForearm.xRot = -0.6F;
            this.leftHand.xRot = -0.6F;
            this.cracks.visible = pt > 2.0F;
            blend = 1.5F;
        } else {
            // LUNGE: a lurching run straight at you; the good arm grabs, the broken one flails behind
            float a = Math.min(1.0F, limbSwingAmount * 1.2F);
            float c = limbSwing * 0.9F;
            float s = Mth.sin(c);
            this.body.xRot = 0.48F + Mth.sin(c * 2.0F) * 0.04F;
            this.body.y = 10.6F + Math.abs(Mth.cos(c)) * 0.6F * a;
            this.rightLeg.y = this.body.y;
            this.leftLeg.y = this.body.y;
            this.rightLeg.xRot = s * 0.55F * a - 0.25F;
            this.rightShin.xRot = 0.15F;
            this.leftLeg.xRot = -s * 0.85F * a - 0.25F;
            this.leftShin.xRot = Math.max(0.0F, Mth.sin(c + 0.8F)) * 1.1F * a + 0.1F;
            this.leftArm.xRot = -1.75F + s * 0.12F * a + jit * 0.3F;
            this.leftArm.zRot = -0.15F;
            this.leftForearm.xRot = -0.25F;
            this.leftHand.xRot = -0.5F;
            this.rightArm.xRot = 0.6F + Mth.sin(c * 1.5F + 1.0F) * 0.7F * a;
            this.rightArm.zRot = 0.3F + Mth.sin(c * 1.1F) * 0.2F * a;
            this.rightForearm.xRot = 0.62F + Mth.sin(c * 1.5F) * 0.6F * a;
            this.neck.xRot = -0.25F;
            this.helmet.xRot = -0.25F + Mth.clamp(pitch, -0.5F, 0.5F) * 0.5F;
            this.helmet.yRot = Mth.clamp(yaw, -0.8F, 0.8F) * 0.6F;
            this.cracks.visible = true;
            blend = 4.0F;
        }
        this.helmet.zRot = this.helmet.zRot + jit * 0.35F;
        this.helmet.xRot = this.helmet.xRot + jit2 * 0.2F;
        this.rightForearm.xRot = this.rightForearm.xRot + jit2 * 0.6F;
        this.blend(mem, poseTicks, blend, ageInTicks);
        // drops: the falling parts are levelled so they fall straight down from the gloves and the chin bar
        level(this.dripL, this.body, this.leftArm, this.leftForearm, this.leftHand);
        level(this.dripR, this.body, this.rightArm, this.rightForearm, this.rightHand);
        level(this.dripH, this.body, this.neck, this.helmet);
        float dl = (t + 7.0F) % 23.0F;
        float dr = (t + 15.0F) % 31.0F;
        float dh = (t + 3.0F) % 41.0F;
        this.dripLFall.visible = dl < 9.0F;
        this.dripRFall.visible = dr < 9.0F;
        this.dripHFall.visible = dh < 9.0F;
        this.dripLFall.y = dl * dl * 0.16F;
        this.dripRFall.y = dr * dr * 0.16F;
        this.dripHFall.y = dh * dh * 0.16F;
        // the visor fogs with each breath, from the chin up, and clears
        float fb = (t + 20.0F) % 70.0F;
        float fogk = fb < 30.0F ? span(fb, 0.0F, 8.0F) * (1.0F - span(fb, 14.0F, 30.0F)) : 0.0F;
        this.fog.visible = fogk > 0.02F && !this.cracks.visible;
        this.fog.yScale = Math.max(0.02F, fogk);
    }

    /** Smoothstep 0..1. */
    private static float ease(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * (3.0F - 2.0F * c);
    }

    /** Fast in, slow out (0..1). */
    private static float easeOut(float x) {
        float c = 1.0F - Mth.clamp(x, 0.0F, 1.0F);
        return 1.0F - c * c * c;
    }

    /** Slow in, fast out (0..1). */
    private static float easeIn(float x) {
        float c = Mth.clamp(x, 0.0F, 1.0F);
        return c * c * c;
    }

    /** 0 before a, rises to 1 at b (smooth). */
    private static float span(float x, float a, float b) {
        return ease((x - a) / (b - a));
    }

    /** Pseudo random 0..1 for an integer-valued x (bounded argument: Mth.sin is a lookup table). */
    private static float hash(float x) {
        float k = x - 1024.0F * (float) Mth.floor(x / 1024.0F);
        float s = Mth.sin(k * 12.9898F + 4.1414F) * 43758.547F;
        return s - (float) Mth.floor(s);
    }

    /** Smooth value noise -1..1. */
    private static float noise(float x) {
        float i = (float) Mth.floor(x);
        float f = x - i;
        float u = f * f * (3.0F - 2.0F * f);
        return Mth.lerp(u, hash(i), hash(i + 1.0F)) * 2.0F - 1.0F;
    }

    /** Missing frames: time holds still for most of every 3-tick window, then jumps to catch up (g = 0..1). */
    private static float stutter(float x, float g) {
        float p = 3.0F;
        float i = (float) Mth.floor(x / p);
        float f = x / p - i;
        float hold = Mth.clamp(g, 0.0F, 1.0F) * (0.55F + 0.4F * hash(i + 17.0F));
        float s = f < hold ? 0.0F : (f - hold) / (1.0F - hold);
        return (i + s) * p;
    }

    /** 1 -> 0 over 3 ticks once every period ticks (phase shifted): sudden twitches. t must be >= 0. */
    private static float twitch(float t, float period, float phase) {
        float m = (t + phase) % period;
        return m < 3.0F ? 1.0F - m / 3.0F : 0.0F;
    }

    /** Stepped progress: holds still, then lurches to the next step (jerky motion), x in 0..1. */
    private static float jerky(float x, float steps) {
        float c = Mth.clamp(x, 0.0F, 1.0F) * steps;
        float i = (float) Mth.floor(c);
        float f = c - i;
        float s = f < 0.55F ? 0.0F : ease((f - 0.55F) / 0.45F);
        return Math.min(1.0F, (i + s) / steps);
    }

    /** Damped spring response 0..1 with overshoot (x in ticks since the step). */
    private static float spring(float x, float freq, float damp) {
        if (x <= 0.0F) {
            return 0.0F;
        }
        return 1.0F - (float) Math.exp(-damp * x) * Mth.cos(freq * x);
    }
    /** Per-entity animation memory: the previous pose, the values to blend from, smoothed values. */
    private static final class State {
        int pose = -1;
        int prev = -1;
        boolean blending;
        float lastAge = -1000.0F;
        float[] from;
        float[] last;
        final float[] fv = new float[8];
        final float[] ft = new float[] {-1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F, -1.0F};
    }

    private State state(Entity entity, int pose, float age) {
        State s = this.states.get(entity);
        if (s == null) {
            s = new State();
            s.from = new float[this.all.length * 9];
            s.last = new float[this.all.length * 9];
            s.pose = pose;
            this.states.put(entity, s);
        } else if (s.pose != pose) {
            System.arraycopy(s.last, 0, s.from, 0, s.last.length);
            // blend only from a frame that was actually seen a moment ago
            s.blending = age - s.lastAge < 10.0F;
            s.prev = s.pose;
            s.pose = pose;
        }
        return s;
    }

    /** Eases every part from the values shown when the pose changed to the new pose over `ticks`. */
    private void blend(State s, float pt, float ticks, float age) {
        boolean on = s.blending && ticks > 0.0F && pt < ticks;
        if (!on) {
            s.blending = false;
        }
        float k = on ? ease(pt / ticks) : 1.0F;
        float[] f = s.from;
        float[] l = s.last;
        for (int i = 0; i < this.all.length; i++) {
            ModelPart p = this.all[i];
            int o = i * 9;
            if (on) {
                p.x = Mth.lerp(k, f[o], p.x);
                p.y = Mth.lerp(k, f[o + 1], p.y);
                p.z = Mth.lerp(k, f[o + 2], p.z);
                p.xRot = Mth.lerp(k, f[o + 3], p.xRot);
                p.yRot = Mth.lerp(k, f[o + 4], p.yRot);
                p.zRot = Mth.lerp(k, f[o + 5], p.zRot);
                p.xScale = Mth.lerp(k, f[o + 6], p.xScale);
                p.yScale = Mth.lerp(k, f[o + 7], p.yScale);
                p.zScale = Mth.lerp(k, f[o + 8], p.zScale);
            }
            l[o] = p.x;
            l[o + 1] = p.y;
            l[o + 2] = p.z;
            l[o + 3] = p.xRot;
            l[o + 4] = p.yRot;
            l[o + 5] = p.zRot;
            l[o + 6] = p.xScale;
            l[o + 7] = p.yScale;
            l[o + 8] = p.zScale;
        }
        s.lastAge = age;
    }

    /** Undoes the rotations of `chain` (the target's ancestors, root side first) so that `target` stays level / hangs
     *  straight down in model space (trays, glasses, strands of hair, keys); add any sway afterwards. */
    private static void level(ModelPart target, ModelPart... chain) {
        float m00 = 1.0F, m01 = 0.0F, m02 = 0.0F, m10 = 0.0F, m11 = 1.0F, m12 = 0.0F, m20 = 0.0F, m21 = 0.0F, m22 = 1.0F;
        for (ModelPart p : chain) {
            float cz = Mth.cos(p.zRot), sz = Mth.sin(p.zRot), cy = Mth.cos(p.yRot), sy = Mth.sin(p.yRot);
            float cx = Mth.cos(p.xRot), sx = Mth.sin(p.xRot);
            float r00 = cz * cy, r01 = cz * sy * sx - sz * cx, r02 = cz * sy * cx + sz * sx;
            float r10 = sz * cy, r11 = sz * sy * sx + cz * cx, r12 = sz * sy * cx - cz * sx;
            float r20 = -sy, r21 = cy * sx, r22 = cy * cx;
            float n00 = m00 * r00 + m01 * r10 + m02 * r20, n01 = m00 * r01 + m01 * r11 + m02 * r21, n02 = m00 * r02 + m01 * r12 + m02 * r22;
            float n10 = m10 * r00 + m11 * r10 + m12 * r20, n11 = m10 * r01 + m11 * r11 + m12 * r21, n12 = m10 * r02 + m11 * r12 + m12 * r22;
            float n20 = m20 * r00 + m21 * r10 + m22 * r20, n21 = m20 * r01 + m21 * r11 + m22 * r21, n22 = m20 * r02 + m21 * r12 + m22 * r22;
            m00 = n00; m01 = n01; m02 = n02; m10 = n10; m11 = n11; m12 = n12; m20 = n20; m21 = n21; m22 = n22;
        }
        // local rotation = transpose(M), decomposed as Rz * Ry * Rx
        target.yRot = (float) Math.asin(Mth.clamp(-m02, -1.0F, 1.0F));
        target.xRot = (float) Math.atan2(m12, m22);
        target.zRot = (float) Math.atan2(m01, m00);
    }

    /** A value that follows its target with a lag (exponential, `speed` per tick), remembered per entity. */
    private static float follow(State s, int slot, float target, float speed, float t) {
        float last = s.ft[slot];
        if (last < 0.0F || t < last || t - last > 40.0F) {
            s.fv[slot] = target;
        } else {
            float k = 1.0F - (float) Math.exp(-speed * (t - last));
            s.fv[slot] = s.fv[slot] + (target - s.fv[slot]) * k;
        }
        s.ft[slot] = t;
        return s.fv[slot];
    }
