            this.body.xRot = 0.85F + sob * 0.05F;
            this.body.y = 10.5F + sob * 0.25F;
            this.skirt.xRot = -0.7F;
            this.neck.xRot = 0.25F + sob * 0.08F;
            this.head.xRot = 0.35F + sob * 0.12F;
            this.rightArm.xRot = -0.841F;
            this.rightArm.zRot = -0.075F + sob * 0.06F;
            this.rightArm.yRot = -0.618F;
            this.rightForearm.xRot = -1.815F;
            this.rightHand.xRot = 0.058F;
            this.leftArm.xRot = -0.841F;
            this.leftArm.zRot = 0.075F - sob * 0.06F;
            this.leftArm.yRot = 0.618F;
            this.leftForearm.xRot = -1.815F;
