package com.eternalrealm.world.forge;

import com.eternalrealm.core.ModInfo;
import com.eternalrealm.world.forge.feature.AreaSurfaceFeature;
import com.eternalrealm.world.forge.feature.AstoriaTreeFeature;
import com.eternalrealm.world.forge.feature.BoulderFeature;
import com.eternalrealm.world.forge.feature.CrystalClusterFeature;
import com.eternalrealm.world.forge.feature.DarkTowerFeature;
import com.eternalrealm.world.forge.feature.FallenPillarFeature;
import com.eternalrealm.world.forge.feature.FarmPlotFeature;
import com.eternalrealm.world.forge.feature.FloatingIslandFeature;
import com.eternalrealm.world.forge.feature.MagmaVentFeature;
import com.eternalrealm.world.forge.feature.MushroomRingFeature;
import com.eternalrealm.world.forge.feature.PoolFeature;
import com.eternalrealm.world.forge.feature.RockSpireFeature;
import com.eternalrealm.world.forge.feature.RuinFeature;
import com.eternalrealm.world.forge.feature.VariantConfig;
import com.eternalrealm.world.forge.feature.VoidCrackFeature;
import com.eternalrealm.world.gen.WorldgenIds;
import com.mojang.serialization.Codec;
import net.minecraft.core.registries.Registries;
import net.minecraft.world.level.biome.BiomeSource;
import net.minecraft.world.level.levelgen.feature.Feature;
import net.minecraft.world.level.levelgen.feature.configurations.NoneFeatureConfiguration;
import net.minecraftforge.eventbus.api.IEventBus;
import net.minecraftforge.registries.DeferredRegister;
import net.minecraftforge.registries.RegistryObject;

/**
 * Registers the アストリア biome source and features. The dimension itself, its biomes and the configured/placed
 * features are data (data/eternalrealm/dimension, worldgen/...; generated by tools/gen-worldgen-data.py).
 */
public final class AstoriaWorldgen {
    private static final DeferredRegister<Codec<? extends BiomeSource>> BIOME_SOURCES =
            DeferredRegister.create(Registries.BIOME_SOURCE, ModInfo.MOD_ID);
    private static final DeferredRegister<Feature<?>> FEATURES = DeferredRegister.create(Registries.FEATURE, ModInfo.MOD_ID);

    public static final RegistryObject<Codec<? extends BiomeSource>> BIOME_SOURCE =
            BIOME_SOURCES.register(WorldgenIds.BIOME_SOURCE, () -> AstoriaBiomeSource.CODEC);

    public static final RegistryObject<Feature<NoneFeatureConfiguration>> AREA_SURFACE = FEATURES.register(
            WorldgenIds.AREA_SURFACE, () -> new AreaSurfaceFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> DARK_TOWER = FEATURES.register(
            WorldgenIds.DARK_TOWER, () -> new DarkTowerFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> ROCK_SPIRE = FEATURES.register(
            WorldgenIds.ROCK_SPIRE, () -> new RockSpireFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> BOULDER = FEATURES.register(
            WorldgenIds.BOULDER, () -> new BoulderFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> CRYSTAL_CLUSTER = FEATURES.register(
            WorldgenIds.CRYSTAL_CLUSTER, () -> new CrystalClusterFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> FALLEN_PILLAR = FEATURES.register(
            WorldgenIds.FALLEN_PILLAR, () -> new FallenPillarFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> RUIN = FEATURES.register(
            WorldgenIds.RUIN, () -> new RuinFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> TREE = FEATURES.register(
            WorldgenIds.TREE, () -> new AstoriaTreeFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> POOL = FEATURES.register(
            WorldgenIds.POOL, () -> new PoolFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> MAGMA_VENT = FEATURES.register(
            WorldgenIds.MAGMA_VENT, () -> new MagmaVentFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<VariantConfig>> FLOATING_ISLAND = FEATURES.register(
            WorldgenIds.FLOATING_ISLAND, () -> new FloatingIslandFeature(VariantConfig.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> VOID_CRACK = FEATURES.register(
            WorldgenIds.VOID_CRACK, () -> new VoidCrackFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> FARM_PLOT = FEATURES.register(
            WorldgenIds.FARM_PLOT, () -> new FarmPlotFeature(NoneFeatureConfiguration.CODEC));
    public static final RegistryObject<Feature<NoneFeatureConfiguration>> MUSHROOM_RING = FEATURES.register(
            WorldgenIds.MUSHROOM_RING, () -> new MushroomRingFeature(NoneFeatureConfiguration.CODEC));

    private AstoriaWorldgen() {
    }

    public static void register(IEventBus modBus) {
        BIOME_SOURCES.register(modBus);
        FEATURES.register(modBus);
    }
}
