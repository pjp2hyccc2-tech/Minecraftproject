    public static final RegistryObject<SoundEvent> WEAPON_SWING_ONE_HANDED_SWORD = sound("weapon.swing.one_handed_sword");
    public static final RegistryObject<SoundEvent> WEAPON_SWING_TWO_HANDED_SWORD = sound("weapon.swing.two_handed_sword");
    public static final RegistryObject<SoundEvent> WEAPON_SWING_DUAL_BLADES = sound("weapon.swing.dual_blades");
    public static final RegistryObject<SoundEvent> WEAPON_SWING_SPEAR = sound("weapon.swing.spear");
