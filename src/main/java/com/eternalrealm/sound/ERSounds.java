    public static final RegistryObject<SoundEvent> COMBAT_GUARD = sound("combat.guard");
    public static final RegistryObject<SoundEvent> COMBAT_PARRY = sound("combat.parry");
    public static final RegistryObject<SoundEvent> COMBAT_DODGE = sound("combat.dodge");

