    public static final RegistryObject<SoundEvent> MUSIC_AREA_1 = sound("music.area_1");
    /** エルダーフォレスト. */
    public static final RegistryObject<SoundEvent> MUSIC_AREA_2 = sound("music.area_2");
    /** サンドリア砂漠. */
    public static final RegistryObject<SoundEvent> MUSIC_AREA_3 = sound("music.area_3");
    /** ノルディア雪原. */
    public static final RegistryObject<SoundEvent> MUSIC_AREA_4 = sound("music.area_4");
    /** ドラゴニア火山. */
    public static final RegistryObject<SoundEvent> MUSIC_AREA_5 = sound("music.area_5");
