    public static final RegistryObject<SoundEvent> MUSIC_AREA_6 = sound("music.area_6");
    /** 終焉の塔. */
    public static final RegistryObject<SoundEvent> MUSIC_AREA_7 = sound("music.area_7");
    public static final RegistryObject<SoundEvent> MUSIC_DUNGEON = sound("music.dungeon");
    public static final RegistryObject<SoundEvent> MUSIC_BOSS = sound("music.boss");
