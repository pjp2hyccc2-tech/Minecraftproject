    public static final RegistryObject<SoundEvent> JINGLE_LEVEL_UP = sound("jingle.level_up");
    public static final RegistryObject<SoundEvent> JINGLE_QUEST_COMPLETE = sound("jingle.quest_complete");
    public static final RegistryObject<SoundEvent> JINGLE_DISCOVERY = sound("jingle.discovery");

    // ---- Skills: casts and impacts per element (PLAYERS) ----
