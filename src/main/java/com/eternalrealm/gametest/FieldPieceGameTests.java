package com.eternalrealm.gametest;

import com.eternalrealm.core.ModInfo;
import com.eternalrealm.world.field.FieldPieceData;
import com.eternalrealm.world.forge.AstoriaDimension;
import com.eternalrealm.world.forge.FieldPieces;
import net.minecraft.commands.arguments.blocks.BlockStateParser;
import net.minecraft.core.BlockPos;
import net.minecraft.core.registries.BuiltInRegistries;
import net.minecraft.gametest.framework.GameTest;
import net.minecraft.gametest.framework.GameTestAssertException;
import net.minecraft.gametest.framework.GameTestHelper;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraftforge.gametest.GameTestHolder;
import net.minecraftforge.gametest.PrefixGameTestTemplate;

import java.util.ArrayList;
import java.util.Comparator;
import java.util.List;

/**
 * The field set pieces inside a real server: the data loads with every palette entry known to the registry (except
 * the blocks other branches add, which are skipped), and the chunks around the capital generate with the pieces
 * standing exactly where the export put them (their probe blocks), untouched by the decoration that ran afterwards.
 */
@GameTestHolder(ModInfo.MOD_ID)
@PrefixGameTestTemplate(false)
public final class FieldPieceGameTests {
    private static final String EMPTY = "empty";
    /** Pieces whose chunks are generated by the test (the nearest to the capital). */
    private static final int PIECES = 6;

    private FieldPieceGameTests() {
    }

    @GameTest(template = EMPTY, timeoutTicks = 2400)
    public static void fieldPiecesStandWhereTheyWereBuilt(GameTestHelper helper) {
        ServerLevel astoria = helper.getLevel().getServer().getLevel(AstoriaDimension.LEVEL);
        check(astoria != null, "the dimension " + AstoriaDimension.LEVEL.location() + " is not loaded");
        FieldPieceData data = FieldPieces.load(astoria.getServer()).data();
        check(data.pieces().size() >= 11, "expected the field set pieces, got " + data.pieces().size());
        check(data.waystones().size() >= 11, "expected 11 waystone shrines, got " + data.waystones().size());
        List<FieldPieceData.Piece> near = new ArrayList<>(data.pieces());
        near.removeIf(piece -> piece.probes().isEmpty());
        near.sort(Comparator.comparingDouble(piece -> {
            int[] box = piece.box();
            double x = (box[0] + box[3]) / 2.0;
            double z = (box[2] + box[5]) / 2.0;
            return x * x + z * z;
        }));
        int checked = 0;
        StringBuilder report = new StringBuilder();
        for (FieldPieceData.Piece piece : near.subList(0, Math.min(PIECES, near.size()))) {
            for (FieldPieceData.Probe probe : piece.probes()) {
                BlockPos pos = new BlockPos(probe.x(), probe.y(), probe.z());
                astoria.getChunk(pos.getX() >> 4, pos.getZ() >> 4);
                BlockState expected = parse(probe.state());
                BlockState actual = astoria.getBlockState(pos);
                if (expected != actual) {
                    report.append("\n  ").append(piece.id()).append(" @").append(pos.toShortString()).append(": expected ")
                            .append(expected).append(", found ").append(actual);
                }
                check(FieldPieces.covers(pos.getX(), pos.getZ()), piece.id() + " does not cover its probe column " + pos);
                checked++;
            }
        }
        check(checked > 0, "no probes to check");
        check(report.length() == 0, "field set pieces differ from their export:" + report);
        helper.succeed();
    }

    private static BlockState parse(String state) {
        try {
            return BlockStateParser.parseForBlock(BuiltInRegistries.BLOCK.asLookup(), state, false).blockState();
        } catch (Exception e) {
            throw new GameTestAssertException("probe state " + state + " does not parse: " + e.getMessage());
        }
    }

    private static void check(boolean condition, String message) {
        if (!condition) {
            throw new GameTestAssertException(message);
        }
    }
}
