/** The fixed habitats and minor waystones (generated by {@link FieldSitesGenerator}) on the real terrain. */
public class HabitatsTest {
    @Test
    public void everyNormalMonsterOfEveryFieldHasAHomeInThatField() {
        for (int field = 1; field <= FieldLayout.FIELD_COUNT; field++) {
            MonsterTable table = Monsters.tableFor(Areas.require(field));
            Set<String> homes = new HashSet<>();
            for (Habitats.Habitat habitat : Habitats.ofField(field)) {
                homes.add(habitat.monster());
            }
            for (MonsterTable.Entry entry : table.entries()) {
                assertTrue(entry.template().id() + " has no habitat in field " + field,
                        homes.contains(entry.template().id()));
            }
            for (String monster : homes) {
                assertTrue(monster + " does not belong to field " + field, table.entries().stream()
                        .anyMatch(e -> e.template().id().equals(monster)));
            }
        }
        // the common kinds (weight 25+) have a second home far from the first
        for (Habitats.Habitat habitat : Habitats.all()) {
            if (habitat.id().endsWith("_2")) {
                Habitats.Habitat first = Habitats.byId(habitat.id().substring(0, habitat.id().length() - 2)).orElseThrow();
                assertTrue(habitat.id(), Math.hypot(first.x() - habitat.x(), first.z() - habitat.z()) >= 220.0);
            }
        }
    }

    @Test
    public void habitatsLieOnWalkableLandClearOfEverythingAndOfEachOther() {
        Set<String> ids = new HashSet<>();
        List<Habitats.Habitat> all = Habitats.all();
        for (Habitats.Habitat habitat : all) {
            assertTrue("duplicate " + habitat.id(), ids.add(habitat.id()));
            MonsterTemplate template = Monsters.require(habitat.monster());
            assertEquals(habitat.id(), MonsterRole.NORMAL, template.role());
            assertEquals(habitat.id(), habitat.field(), FieldLayout.areaAt(habitat.x(), habitat.z()));
            assertTrue(habitat.id() + " is not on walkable land", FieldSitesGenerator.habitatGround(habitat.field(),
                    habitat.x(), habitat.z(), habitat.radius(), FieldSitesGenerator.slopeLimit(habitat.field())));
            assertTrue(habitat.id() + " is not twice the first area", habitat.radius() >= 40);
            assertTrue(habitat.id() + " is too close to the capital",
                    FieldLayout.capitalDistance(habitat.x(), habitat.z()) >= habitat.radius() + 40.0);
            for (FieldThreats.Lord lord : FieldThreats.lords()) {
                assertTrue(habitat.id() + " reaches into the territory of " + lord.id(),
                        Math.hypot(habitat.x() - lord.x(), habitat.z() - lord.z()) >= lord.territory() + habitat.radius() + 16.0);
            }
            for (FieldThreats.Calamity calamity : FieldThreats.calamities()) {
                assertTrue(habitat.id() + " is in the lair of the calamity of field " + calamity.field(),
                        Math.hypot(habitat.x() - calamity.x(), habitat.z() - calamity.z())
                                >= FieldThreats.LAIR_RADIUS + habitat.radius() + 30.0);
            }
            for (LandmarkSite site : LandmarkSites.all()) {
                assertTrue(habitat.id() + " is at the entrance of " + site.dungeonId(),
                        Math.hypot(habitat.x() - site.x(), habitat.z() - site.z()) >= site.padRadius() + habitat.radius() + 24.0);
            }
            for (FieldLayout.Waystone stone : FieldLayout.waystones()) {
                assertTrue(habitat.id() + " is at waystone " + stone.id(),
                        Math.hypot(habitat.x() - stone.x(), habitat.z() - stone.z()) >= habitat.radius() + 14.0);
            }
            for (Habitats.Habitat other : all) {
                if (other != habitat) {
                    assertTrue(habitat.id() + " overlaps " + other.id(), Math.hypot(habitat.x() - other.x(),
                            habitat.z() - other.z()) >= habitat.radius() + other.radius() + FieldSitesGenerator.HABITAT_GAP);
                }
            }
        }
    }

    /**
     * Owner, 2026-11-12: 「フィールドの敵スポーン範囲を広くして、湧く数を今の３．５倍にして」: 3.5 times as many monsters,
     * appearing over half as far out again, and never where they must not (another field, another habitat's home
     * ground, the capital, a waystone, a lord's territory, a calamity's lair, a dungeon entrance).
     */
    @Test
    public void threeAndAHalfTimesAsManyMonstersAppearOverAWiderGround() {
        int homeSamples = 0;
        int openSamples = 0;
        for (Habitats.Habitat habitat : Habitats.all()) {
            int base = FieldSitesGenerator.basePopulationOf(Monsters.require(habitat.monster()));
            assertTrue(habitat.id() + ": " + habitat.population(),
                    habitat.population() == FieldSitesGenerator.crowded(base)
                            || habitat.population() == FieldSitesGenerator.crowded(Math.min(16, base * 3 / 2)));
            assertEquals(habitat.id(), Math.round(habitat.radius() * Habitats.SPREAD), habitat.spawnRadius());
            assertTrue(habitat.id(), habitat.spawnRadius() >= 60);
            int n = 600;
            for (int i = 0; i < n; i++) {
                double angle = i * 2.399963;
                double d = habitat.spawnRadius() * Math.sqrt((i + 0.5) / n);
                double x = habitat.x() + 0.5 + Math.cos(angle) * d;
                double z = habitat.z() + 0.5 + Math.sin(angle) * d;
                boolean home = habitat.distanceTo(x, z) <= habitat.radius() - 0.5;
                boolean open = Habitats.spawnable(habitat, x, z);
                if (home) {
                    homeSamples++;
                    assertTrue(habitat.id() + ": its own home ground is closed at " + x + "," + z, open);
                }
                if (!open) {
                    continue;
                }
                openSamples++;
                assertEquals(habitat.id(), habitat.field(), FieldLayout.areaAt(x, z));
                assertTrue(habitat.id(), FieldLayout.capitalDistance(x, z) >= Habitats.CAPITAL_CLEARANCE);
                for (Habitats.Habitat other : Habitats.all()) {
                    assertTrue(habitat.id() + " appears at home in " + other.id(),
                            other == habitat || other.distanceTo(x, z) >= other.radius());
                }
                for (FieldLayout.Waystone stone : FieldLayout.waystones()) {
                    assertTrue(habitat.id() + " appears at " + stone.id(),
                            Math.hypot(x - stone.x(), z - stone.z()) >= Habitats.WAYSTONE_CLEARANCE);
                }
                for (FieldThreats.Lord lord : FieldThreats.lords()) {
                    assertTrue(habitat.id() + " appears in the territory of " + lord.id(),
                            Math.hypot(x - lord.x(), z - lord.z()) >= lord.territory() + Habitats.LORD_CLEARANCE);
                }
                for (FieldThreats.Calamity calamity : FieldThreats.calamities()) {
                    assertTrue(habitat.id() + " appears in a lair", Math.hypot(x - calamity.x(), z - calamity.z())
                            >= FieldThreats.LAIR_RADIUS + Habitats.LAIR_CLEARANCE);
                }
                for (LandmarkSite site : LandmarkSites.all()) {
                    assertTrue(habitat.id() + " appears at the entrance of " + site.dungeonId(),
                            Math.hypot(x - site.x(), z - site.z()) >= site.padRadius() + Habitats.ENTRANCE_CLEARANCE);
                }
            }
            assertFalse(habitat.id() + " appears beyond its spawn radius",
                    Habitats.spawnable(habitat, habitat.x() + habitat.spawnRadius() + 1.0, habitat.z()));
        }
        // the wider ground is real: monsters appear over well more than their home grounds
        assertTrue("open " + openSamples + " / home " + homeSamples, openSamples >= homeSamples * 1.5);
    }

    @Test
    public void weakerMonstersLiveNearerTheFieldsShrine() {
        for (int field = 1; field <= FieldLayout.FIELD_COUNT; field++) {
            FieldLayout.Waystone shrine = FieldSitesGenerator.shrine(field);
            List<Habitats.Habitat> first = Habitats.ofField(field).stream().filter(h -> !h.id().endsWith("_2"))
                    .sorted((a, b) -> Integer.compare(Monsters.require(a.monster()).levels().min(),
                            Monsters.require(b.monster()).levels().min())).toList();
            int quarter = first.size() / 4;
            double weak = 0.0;
            double strong = 0.0;
            for (int i = 0; i < quarter; i++) {
                weak += first.get(i).distanceTo(shrine.x(), shrine.z());
                strong += first.get(first.size() - 1 - i).distanceTo(shrine.x(), shrine.z());
            }
            assertTrue("field " + field + ": the weakest live farther out than the strongest", weak < strong);
        }
    }

    @Test
    public void fiveTimesAsManyWaystonesSpreadOverEveryField() {
        assertEquals(11, FieldLayout.shrines().size());
        assertEquals(44, FieldLayout.minorWaystones().size());
        assertEquals(55, FieldLayout.waystones().size());
        Map<Integer, Integer> perField = new HashMap<>();
        Set<String> ids = new HashSet<>();
        for (FieldLayout.Waystone stone : FieldLayout.minorWaystones()) {
            assertTrue("duplicate " + stone.id(), ids.add(stone.id()));
            assertTrue(FieldLayout.isMinor(stone.id()));
            perField.merge(stone.field(), 1, Integer::sum);
            assertTrue(stone.id() + " has no flat dry ground", FieldSitesGenerator.landCircle(stone.field(), stone.x(),
                    stone.z(), 6, 3));
            for (FieldLayout.Waystone other : FieldLayout.waystones()) {
                if (other != stone) {
                    assertTrue(stone.id() + " is too close to " + other.id(),
                            Math.hypot(stone.x() - other.x(), stone.z() - other.z()) >= 140.0);
                }
            }
            for (Habitats.Habitat habitat : Habitats.all()) {
                assertTrue(stone.id() + " stands in habitat " + habitat.id(),
                        habitat.distanceTo(stone.x(), stone.z()) >= habitat.radius() + 14.0);
            }
            for (FieldThreats.Lord lord : FieldThreats.lords()) {
                assertTrue(stone.id() + " stands in the territory of " + lord.id(),
                        Math.hypot(stone.x() - lord.x(), stone.z() - lord.z()) >= lord.territory() + 6.0);
            }
        }
        for (FieldLayout.Waystone shrine : FieldLayout.shrines()) {
            assertFalse(FieldLayout.isMinor(shrine.id()));
        }
        for (int field = 1; field <= FieldLayout.FIELD_COUNT; field++) {
            assertTrue("field " + field + " has " + perField.get(field), perField.getOrDefault(field, 0) >= 4);
        }
    }
}
