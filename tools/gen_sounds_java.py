#!/usr/bin/env python3
"""Generates com.sounan.registry.ModSounds from the sound events of docs/DESIGN.md §7 plus any extra
events found in assets/sounan/sounds.json (written by tools/audio)."""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
design = open(os.path.join(ROOT, "docs/DESIGN.md"), encoding="utf-8").read()
sec = design.split("## 7. Sounds", 1)[1].split("## 8.", 1)[0]
events = []
for m in re.finditer(r"^\| `([a-z_]+\.[a-z_]+)`(?: / `([a-z_]+\.[a-z_]+)`)?", sec, re.M):
    for g in m.groups():
        if g and g not in events:
            events.append(g)
sj = os.path.join(ROOT, "src/main/resources/assets/sounan/sounds.json")
if os.path.exists(sj):
    for k in json.load(open(sj, encoding="utf-8")):
        if k not in events:
            events.append(k)


def const(e):
    return re.sub(r"[^A-Z0-9]+", "_", e.upper())


lines = [
    "package com.sounan.registry;",
    "",
    "import com.sounan.Sounan;",
    "import net.minecraft.sounds.SoundEvent;",
    "import net.minecraftforge.registries.DeferredRegister;",
    "import net.minecraftforge.registries.ForgeRegistries;",
    "import net.minecraftforge.registries.RegistryObject;",
    "",
    "/** Every sound event of the mod (generated by tools/gen_sounds_java.py; files in assets/sounan/sounds.json). */",
    "public final class ModSounds {",
    "    public static final DeferredRegister<SoundEvent> SOUNDS = DeferredRegister.create(ForgeRegistries.SOUND_EVENTS, Sounan.MODID);",
    "",
]
for e in events:
    lines.append(f'    public static final RegistryObject<SoundEvent> {const(e)} = reg("{e}");')
lines += [
    "",
    "    private ModSounds() {}",
    "",
    "    private static RegistryObject<SoundEvent> reg(String name) {",
    "        return SOUNDS.register(name, () -> SoundEvent.createVariableRangeEvent(Sounan.id(name)));",
    "    }",
    "}",
    "",
]
out = os.path.join(ROOT, "src/main/java/com/sounan/registry/ModSounds.java")
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(len(events), "sound events")
