#!/usr/bin/env python3
"""Generates com.hitori.registry.ModSounds from the sound events of docs/DESIGN.md §8 plus any extra
events found in assets/hitori/sounds.json (written by tools/audio)."""
import json
import os
import re

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
design = open(os.path.join(ROOT, "docs/DESIGN.md"), encoding="utf-8").read()
sec = design.split("## 8. Sounds", 1)[1].split("## 9.", 1)[0]
events = []
for m in re.finditer(r"`([^`]+)`", sec):
    g = m.group(1)
    if re.fullmatch(r"[a-z_]+\.[a-z_0-9]+", g) and not g.endswith((".py", ".ogg", ".json")) and g not in events:
        events.append(g)
sj = os.path.join(ROOT, "src/main/resources/assets/hitori/sounds.json")
if os.path.exists(sj):
    for k in json.load(open(sj, encoding="utf-8")):
        if k not in events:
            events.append(k)


def const(e):
    return re.sub(r"[^A-Z0-9]+", "_", e.upper())


lines = [
    "package com.hitori.registry;",
    "",
    "import com.hitori.Hitori;",
    "import net.minecraft.sounds.SoundEvent;",
    "import net.minecraft.world.level.block.SoundType;",
    "import net.minecraftforge.common.util.ForgeSoundType;",
    "import net.minecraftforge.registries.DeferredRegister;",
    "import net.minecraftforge.registries.ForgeRegistries;",
    "import net.minecraftforge.registries.RegistryObject;",
    "",
    "/** Every sound event of the mod (generated by tools/gen_sounds_java.py; files in assets/hitori/sounds.json). */",
    "public final class ModSounds {",
    "    public static final DeferredRegister<SoundEvent> SOUNDS = DeferredRegister.create(ForgeRegistries.SOUND_EVENTS, Hitori.MODID);",
    "",
]
for e in events:
    lines.append(f'    public static final RegistryObject<SoundEvent> {const(e)} = reg("{e}");')
# floor sound types (optional, for the world's blocks: socked feet on the apartment's floors use the player.step_*
# sounds; break / place / hit stay vanilla)
TYPES = [("TATAMI", "PLAYER_STEP_TATAMI", "WOOL", "tatami mats (tatami, tatami_worn)"),
         ("FLOOR", "PLAYER_STEP_FLOOR", "WOOD", "old varnished floorboards, vinyl, the closet's plywood"),
         ("TILE", "PLAYER_STEP_TILE", "STONE", "bath tiles, the genkan's tiles"),
         ("WET", "PLAYER_STEP_WET", "STONE", "the wet outdoor corridor and street, a wet bathroom floor")]
if all(t[1] in [const(e) for e in events] for t in TYPES):
    lines += [
        "",
        "    // Floor sound types: step and fall use the floor's footstep, break / place / hit come from a vanilla type.",
        "    // Vanilla plays step sounds at 0.15 x the type's volume; 4.0 keeps footsteps well above the quiet room beds.",
    ]
    for name, ev, base, what in TYPES:
        lines.append(f"    /** {what} */")
        lines.append(f"    public static final ForgeSoundType SOUND_TYPE_{name} = floor({ev}, SoundType.{base});")
    lines += [
        "",
        "    private static ForgeSoundType floor(RegistryObject<SoundEvent> step, SoundType base) {",
        "        return new ForgeSoundType(4.0f, 1.0f, base::getBreakSound, step, base::getPlaceSound, base::getHitSound, step);",
        "    }",
    ]
lines += [
    "",
    "    private ModSounds() {}",
    "",
    "    private static RegistryObject<SoundEvent> reg(String name) {",
    "        return SOUNDS.register(name, () -> SoundEvent.createVariableRangeEvent(Hitori.id(name)));",
    "    }",
    "}",
    "",
]
out = os.path.join(ROOT, "src/main/java/com/hitori/registry/ModSounds.java")
open(out, "w", encoding="utf-8").write("\n".join(lines))
print(len(events), "sound events")
