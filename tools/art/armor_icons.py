VARIANTS = [1, 2, 3, 4, 5, 6, 7, "knight", "assassin", "mage", "ranger", "priest", "spellblade"]
SLOTS = {"helmet": HELMET, "chestplate": CHEST, "leggings": LEGS, "boots": BOOT}


def icon(slot: str, variant):
    mats = THEMES[variant]
    rows = SLOTS[slot][variant]
    if slot != "boots":
        return render(rows, mats, local="BSEGRF")
    # a pair: back boot (up-right) then front boot (down-left)
    full = [r + "........" for r in rows]
    pad = ["." * 16] * 16
    back = [list(r) for r in pad]
    front = [list(r) for r in pad]
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            if ch != ".":
                back[y + 1][x + 6] = ch
                front[y + 5][x + 1] = ch
    b = render(["".join(r) for r in back], mats, local="BSEGRF")
    f = render(["".join(r) for r in front], mats, local="BSEGRF")
    # darken the back boot slightly so the pair reads as two objects
    import numpy as np
    b.a[:, :, :3] = (b.a[:, :, :3].astype(int) * 0.86).astype("uint8")
    b.paste(f)
    return b


def name(slot: str, variant) -> str:
    return f"{slot}_{variant}" if isinstance(variant, int) else f"{slot}_job_{variant}"


def all_icons():
    for slot in SLOTS:
        for v in VARIANTS:
            yield name(slot, v), icon(slot, v)


