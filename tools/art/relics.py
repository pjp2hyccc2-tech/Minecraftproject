def docs_table(relics) -> str:
    """The relic list of docs/modules/armory.md (between the markers)."""
    lines = ["", "| 出どころ | 必要Lv | 武器 | 防具セット | アクセサリー | お守り |", "|---|---|---|---|---|---|"]
    for r in relics:
        names = r.names()
        weapon = names[f"design.eternalrealm.{r.weapon_id}"][0]
        armor = names[f"armor_set.eternalrealm.{r.set_id}"][0]
        accessory = names[f"design.eternalrealm.{r.accessory_id}"][0]
        charm = names[f"design.eternalrealm.{r.charm_id}"][0]
        lines.append(f"| `{r.key}` {KIND_JA[r.kind]}・{r.motif[0]} | {r.relic_level} "
                     f"| {weapon}（{TYPE_JA[r.wtype]}・{ELEMENT_JA[r.element]}） "
                     f"| {armor}（{STYLE_JA[r.style]}） "
                     f"| {accessory}（{r.acc[1]}・{r.acc[2]}・{ACC_FOCUS_JA[r.acc[3]]}） "
                     f"| {charm}（{CHARM_FOCUS_JA[r.charm[1]]}） |")
    lines.append("")
    return "\n".join(lines)


def docs_with_table(text: str, table: str) -> str:
    begin = text.index(DOCS_BEGIN) + len(DOCS_BEGIN)
    end = text.index(DOCS_END)
    return text[:begin] + "\n" + table + "\n" + text[end:]


def write_text(path: str, text: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def write_json_entries(path: str, data: dict) -> None:
    write_text(path, "{\n" + ",\n".join(f"  {json.dumps(k, ensure_ascii=False)}: {json.dumps(v, ensure_ascii=False)}"
                                        for k, v in data.items()) + "\n}\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--no-art", action="store_true")
    args = ap.parse_args()
    relics = relics_data.load()
    problems = relics_data.check(relics)
    if problems:
        for p in problems:
            print("ERROR", p)
        return 1
    with open(DOCS, encoding="utf-8") as f:
        docs = f.read()
    wanted_docs = docs_with_table(docs, docs_table(relics))
    if args.check:
        if docs != wanted_docs:
            print("ERROR docs/modules/armory.md: the relic table is out of date (run tools/art/relics.py)")
            return 1
        import relic_art
        missing = relic_art.check(relics, ASSETS)
        for m in missing:
            print("missing", m)
        return 1 if missing else 0
    write_text(JAVA, java(relics))
    texts = i18n(relics)
    write_json_entries(I18N, texts)
    write_text(DOCS, wanted_docs)
    print(f"relics: {len(relics)} sources, {len(texts)} texts")
    if not args.no_art:
        import relic_art
        relic_art.generate(relics, ASSETS)
    return 0


if __name__ == "__main__":
    sys.exit(main())
