#!/usr/bin/env python3
"""金枠の遺宝 (relics): writes the Java table, the texts and the art of every relic from tools/art/relics_data.py.

    python3 tools/art/relics.py            # RelicTable.java, docs/i18n/relics.json, the docs table, textures, models,
                                           # preview
    python3 tools/art/relics.py --check    # only checks the data, the docs table and that every relic has its art

Art: the weapons are drawn by named_weapons.py from their sprite specs, the armor sets by armor_icons / armor_worn in
their materials and emblem (as the named sets of named_armor.py), the accessories and charms by trinket_icons.py. The
relic weapons and armor pieces sit on their tier items (CustomModelData 3500+, 4500+), the trinkets on the trinket base
items (<tier>_accessory, <tier>_charm, 5000+).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

import relics_data  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
JAVA = os.path.join(ROOT, "src/main/java/com/eternalrealm/item/RelicTable.java")
I18N = os.path.join(ROOT, "docs/i18n/relics.json")
DOCS = os.path.join(ROOT, "docs/modules/armory.md")
DOCS_BEGIN = "<!-- RELIC TABLE BEGIN (tools/art/relics.py) -->"
DOCS_END = "<!-- RELIC TABLE END -->"
ASSETS = os.path.join(ROOT, "src/main/resources/assets/eternalrealm")
NS = "eternalrealm"
TIER_IDS = ["iron", "steel", "sandstone", "frost", "flame", "celestial", "abyss"]
PIECE_NOUNS = ["helmet", "chestplate", "leggings", "boots"]


def java(relics) -> str:
    rows = []
    for r in relics:
        rows.append(f'            row("{r.key}", "{r.kind}", "{r.target}", {r.field}, {r.level}, '
                    f'"{relics_data.JAVA_TYPES[r.wtype]}", "{r.feel}", "{r.element}", "{r.style}", "{r.acc[0]}", '
                    f'"{r.acc[1]}", "{r.acc[2]}", "{r.acc[3]}", "{r.charm[0]}", "{r.charm[1]}")')
    body = ",\n".join(rows)
    return f'''package com.eternalrealm.item;

import java.util.List;

/**
 * GENERATED by tools/art/relics.py from tools/art/relics_data.py (do not edit): the relic sources (金枠の遺宝) and
 * the shape of their relics. {{@link Relics}} makes the designs and their numbers from these rows; the row index fixes
 * the model numbers (weapon 3500 + i, armor 4500 + 4i, accessory 5000 + 2i, charm 5001 + 2i).
 */
final class RelicTable {{
    /**
     * One source: its key, kind and target, its field and level, the weapon (type, feel, element), the armor style,
     * the accessory (kind, main stat, second stat, focus) and the charm (kind, focus).
     */
    record Row(String key, String kind, String target, int field, int level, String weaponType, String feel,
               String element, String style, String accessory, String accessoryMain, String accessorySecond,
               String accessoryFocus, String charm, String charmFocus) {{
    }}

    static final List<Row> ROWS = List.of(
{body});

    private RelicTable() {{
    }}

    private static Row row(String key, String kind, String target, int field, int level, String weaponType,
                           String feel, String element, String style, String accessory, String accessoryMain,
                           String accessorySecond, String accessoryFocus, String charm, String charmFocus) {{
        return new Row(key, kind, target, field, level, weaponType, feel, element, style, accessory, accessoryMain,
                accessorySecond, accessoryFocus, charm, charmFocus);
    }}
}}
'''


def i18n(relics) -> dict:
    out = {}
    for r in relics:
        for key, (ja, en) in r.names().items():
            out[key] = {"ja": ja, "en": en}
    return out


KIND_JA = {"BOSS": "ダンジョンのボス", "CALAMITY": "災厄", "LORD": "ヌシ", "WANDERER": "放浪する大物"}
TYPE_JA = {"SWORD": "片手剣", "GREAT": "両手剣", "TWIN": "双剣", "SPEAR": "槍", "STAFF": "杖", "BOW": "弓"}
ELEMENT_JA = {"FIRE": "炎", "FROST": "氷", "THUNDER": "雷", "VENOM": "毒", "HOLY": "聖", "SHADOW": "闇", "BLOOD": "血",
              "EARTH": "地"}
