#!/usr/bin/env python3
"""Validate the art against docs/DESIGN.md section 5 (and 4 for the monsters).

Parses the block tables (nature, buildings, doors, props), the item list, the GUI list and the monster ids, then
checks that every expected PNG exists with the right size and RGBA mode, cutout textures have binary alpha, eyes
layers are black wherever transparent (they are drawn additively), the prop block models / 3D item models named in
section 5 exist and reference existing textures, and that nothing unexpected sits in the texture folders.
"""
import json
import os
import re
import sys
sys.dont_write_bytecode = True

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import ROOT, TEX_ROOT, MODEL_ROOT  # noqa: E402

DESIGN = os.path.join(ROOT, 'docs', 'DESIGN.md')
NOT_OURS = {'gui/trail_map'}             # generated by tools/terrain
ALLOWED_EXTRA_PREFIX = ('item/held/',)   # skins of the 3D held models


def section(text, start, stop):
    i = text.index(start)
    j = text.index(stop, i + len(start)) if stop else len(text)
    return text[i:j]


def expected():
    text = open(DESIGN, encoding='utf-8').read()
    s5 = section(text, '## 5. Registry ids', '## 6.')
    exp = {}
    blocks = section(s5, '### Blocks', '### Items')
    props, prop_models = [], set()
    in_doors = in_props = False
    for line in blocks.splitlines():
        if line.startswith('Doors'):
            in_doors = True
        if line.startswith('Props'):
            in_doors, in_props = False, True
        if not line.startswith('|') or '---' in line:
            continue
        cols = [c.strip() for c in line.strip('|').split('|')]
        if cols[0] in ('id', ''):
            continue
        ids = re.findall(r'`([a-z0-9_]+)`', cols[0])
        if in_doors:
            for d in ids:
                exp[f'block/{d}_bottom'] = (16, 16)
                exp[f'block/{d}_top'] = (16, 16)
                exp[f'item/{d}'] = (16, 16)
            continue
        if len(cols) < 2:
            continue
        if 'MEIKON textures' in cols[1]:
            # copied MEIKON textures: names of the actual files
            for n in ('tatami_old_top', 'tatami_old_side', 'old_planks', 'rotten_planks', 'dark_beam_side', 'dark_beam_top',
                      'plaster_wall', 'shoji_torn', 'futon_top', 'futon_side', 'stone_lantern', 'blood_stain', 'footprints',
                      'hair_strands', 'shimenawa'):
                exp[f'block/{n}'] = (16, 16)
            continue
        for t in re.findall(r'`([a-z0-9_]+)`', cols[1]):
            exp[f'block/{t}'] = (16, 16)
        if len(cols) >= 3:
            for m in re.findall(r'model `([a-z0-9_]+)`|`([a-z0-9_]+)`\)', cols[2]):
                for g in m:
                    if g:
                        prop_models.add(g)
        if in_props:
            props += ids
    items = section(s5, '### Items', '### Entities')
    item_line, held_line = items.split('3D held models')[0], items.split('3D held models')[1]
    for n in re.findall(r'`([a-z0-9_]+)`', item_line):
        exp[f'item/{n}'] = (16, 16)
    held = re.findall(r'`([a-z0-9_]+)`', held_line.split('\n\n')[0])
    held = [h for h in held if not h.startswith('forge')]
    gui = section(s5, '### GUI', None)
    for m in re.finditer(r'`([a-z0-9_/.]+)`\s*(\d+)\s*[×x]\s*(\d+)|`([a-z0-9_/.]+)`\s*(\d+)²', gui):
        if m.group(1):
            exp[f'gui/{m.group(1)}'] = (int(m.group(2)), int(m.group(3)))
        else:
            exp[f'gui/{m.group(4)}'] = (int(m.group(5)), int(m.group(5)))
    m = re.search(r'`jumpscare_nozoki`.*?256²', gui, re.S)
    for n in re.findall(r'`(jumpscare_[a-z]+)`', gui):
        exp[f'gui/{n}'] = (256, 256)
    m = re.search(r'`phone/wallpaper_0\.\.2`\s*(\d+)×(\d+)', gui)
    if m:
        exp.pop('gui/phone/wallpaper_0..2', None)
        for i in range(3):
            exp[f'gui/phone/wallpaper_{i}'] = (int(m.group(1)), int(m.group(2)))
    for n in ('vignette', 'grain', 'paper', 'hands'):
        exp.setdefault(f'gui/{n}', None)
    for k in list(exp):
        if k in NOT_OURS:
            exp.pop(k)
    s4 = section(text, '## 4. Monsters', '## 5.')
    monsters = re.findall(r'^\| `([a-z]+)` \|', s4, re.M)
    for mid in monsters:
        exp[f'entity/{mid}'] = None
        exp[f'entity/{mid}_eyes'] = None
    return exp, props, prop_models, held, monsters


def model_textures(m):
    out = set()
    for v in m.get('textures', {}).values():
        if not v.startswith('#'):
            out.add(v)
    return out


def check_model(path, problems, label):
    if not os.path.isfile(path):
        problems.append(f'MISSING  {label}')
        return None
    m = json.load(open(path, encoding='utf-8'))
    body = m.get('base', m)
    texs = model_textures(body)
    for p in m.get('perspectives', {}).values():
        texs |= model_textures(p)
    for t in texs:
        ns, rel = t.split(':', 1) if ':' in t else ('minecraft', t)
        if ns != 'reisatsu':
            continue
        if not os.path.isfile(os.path.join(TEX_ROOT, rel + '.png')):
            problems.append(f'TEXREF   {label} -> {t} does not exist')
    for el in body.get('elements', []):
        for face, fd in el['faces'].items():
            ref = fd['texture']
            if ref.startswith('#') and ref[1:] not in body.get('textures', {}):
                problems.append(f'TEXREF   {label} element face {face} uses undefined {ref}')
        for c in el['from'] + el['to']:
            if not -16 <= c <= 32:
                problems.append(f'BOUNDS   {label} element coordinate {c} outside -16..32')
        rot = el.get('rotation')
        if rot and rot['angle'] not in (-45, -22.5, 0, 22.5, 45):
            problems.append(f'ROTATION {label} angle {rot["angle"]} not allowed')
    if 'particle' not in body.get('textures', {}):
        problems.append(f'PARTICLE {label} has no particle texture')
    return m


def main():
    exp, props, prop_models, held, monsters = expected()
    try:
        from common import REGISTRY
        if not REGISTRY:
            import gen_textures  # noqa: F401  (registers everything)
        cutouts = {n for n, s in REGISTRY.items() if s['cutout']}
    except Exception as e:  # pragma: no cover
        print('warning: generators not importable:', e)
        cutouts = set()
    problems = []
    for rel, size in sorted(exp.items()):
        path = os.path.join(TEX_ROOT, rel + '.png')
        if not os.path.isfile(path):
            problems.append(f'MISSING  {rel}.png')
            continue
        im = Image.open(path)
        if im.mode != 'RGBA':
            problems.append(f'MODE     {rel}.png is {im.mode}, expected RGBA')
        if size and im.size != size:
            problems.append(f'SIZE     {rel}.png is {im.size[0]}x{im.size[1]}, expected {size[0]}x{size[1]}')
        a = np.asarray(im.convert('RGBA'))
        if rel in cutouts:
            bad = np.setdiff1d(np.unique(a[..., 3]), [0, 255])
            if bad.size:
                problems.append(f'ALPHA    {rel}.png (cutout) has partial alpha {bad[:6]}')
        if rel.endswith('_eyes'):
            leak = (a[..., 3] == 0) & (a[..., :3].max(-1) > 0)
            if leak.any():
                problems.append(f'EYES     {rel}.png has colour under {int(leak.sum())} transparent pixels (additive layer)')
        if rel.startswith('gui/jumpscare') and (a[..., 3] < 255).any():
            problems.append(f'OPAQUE   {rel}.png must be opaque')
    fr = os.path.join(TEX_ROOT, 'gui/phone/frame.png')
    if os.path.isfile(fr):
        a = np.asarray(Image.open(fr).convert('RGBA'))
        if a[24:296, 8:152, 3].max() != 0:
            problems.append('FRAME    gui/phone/frame.png screen area x 8..151, y 24..295 is not fully transparent')
    for cat in ('block', 'item', 'gui', 'entity'):
        d = os.path.join(TEX_ROOT, cat)
        for dirpath, _, files in os.walk(d):
            for f in sorted(files):
                if not f.endswith('.png'):
                    continue
                rel = os.path.relpath(os.path.join(dirpath, f), TEX_ROOT)[:-4].replace(os.sep, '/')
                if rel not in exp and not rel.startswith(ALLOWED_EXTRA_PREFIX) and rel not in NOT_OURS:
                    problems.append(f'EXTRA    {rel}.png is not listed in DESIGN.md')
    # prop block models (+ variants) and 3D item models
    variants = {'lost_bag_open', 'hokora_offered', 'rope_anchor_roped', 'tunnel_lamp_lit', 'key_hook_empty'}
    for name in sorted(set(props) | variants | {'blue_tarp', 'fallen_leaves'}):
        check_model(os.path.join(MODEL_ROOT, 'block', name + '.json'), problems, f'models/block/{name}.json')
    for name in held:
        m = check_model(os.path.join(MODEL_ROOT, 'item', name + '.json'), problems, f'models/item/{name}.json')
        if m and m.get('loader') != 'forge:separate_transforms':
            problems.append(f'LOADER   models/item/{name}.json is not forge:separate_transforms')
    # monster models
    for mid in monsters:
        java = os.path.join(ROOT, 'src', 'main', 'java', 'com', 'reisatsu', 'client', 'model', mid.capitalize() + 'Model.java')
        if not os.path.isfile(java):
            problems.append(f'MISSING  client/model/{mid.capitalize()}Model.java')
    print(f'checked {len(exp)} textures ({sum(r.startswith("block/") for r in exp)} block, {sum(r.startswith("item/") for r in exp)} item, '
          f'{sum(r.startswith("gui/") for r in exp)} gui, {sum(r.startswith("entity/") for r in exp)} entity), '
          f'{len(set(props) | variants) + 2} prop models, {len(held)} held models, {len(monsters)} monster models')
    if problems:
        print('\n'.join(problems))
        print(f'FAILED: {len(problems)} problem(s)')
        return False
    print('OK: all textures present, sized, RGBA; cutouts binary; eyes layers clean; models consistent')
    return True


if __name__ == '__main__':
    sys.exit(0 if main() else 1)
