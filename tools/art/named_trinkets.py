#!/usr/bin/env python3
"""名品の装身具 (named trinkets of the lords and dungeons, com.eternalrealm.item.NamedTrinkets): writes the Java table,
the names and lore, the icons, the models and the base item overrides of the 48 trinkets in named_trinkets_data.py,
and tools/art/named_trinkets_preview.png.

    python3 tools/art/named_trinkets.py            # NamedTrinketTable.java, docs/i18n/named_trinkets.json, art
    python3 tools/art/named_trinkets.py --check    # only checks that every trinket has its art and the table is current

They sit on the trinket base items of their level's tier (<tier>_accessory, <tier>_charm) at CustomModelData 5400 + i
(i: the row's index); armory_art.patch_tier_models writes the overrides (armory_art.design_overrides asks overrides()).
"""
from __future__ import annotations

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
if HERE not in sys.path:
    sys.path.insert(0, HERE)

from PIL import Image, ImageDraw  # noqa: E402

import named_trinkets_data  # noqa: E402
import palette as P  # noqa: E402
import trinket_icons  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
ASSETS = os.path.join(ROOT, "src/main/resources/assets/eternalrealm")
JAVA = os.path.join(ROOT, "src/main/java/com/eternalrealm/item/NamedTrinketTable.java")
I18N = os.path.join(ROOT, "docs/i18n/named_trinkets.json")
NS = "eternalrealm"
MODELS = 5400
TIER_IDS = ["iron", "steel", "sandstone", "frost", "flame", "celestial", "abyss"]
TIER_LEVELS = [1, 8, 15, 22, 30, 37, 44]

KIND_NOUNS = {
    "BROOCH": ("ブローチ", "Brooch"), "CIRCLET": ("額冠", "Circlet"), "ANKLET": ("足環", "Anklet"),
    "MEDAL": ("勲章", "Medal"), "MIRROR": ("護り鏡", "Ward Mirror"), "FEATHER": ("守り羽", "Ward Feather"),
    "BEADS": ("数珠", "Prayer Beads"), "DOLL": ("身代わり人形", "Ward Doll"),
}


def tier_of(level: int) -> int:
    tier = 1
    for i, lv in enumerate(TIER_LEVELS):
        if level >= lv:
            tier = i + 1
    return tier


def is_charm(row) -> bool:
    return row.kind in named_trinkets_data.CHARMS


def java(rows) -> str:
    lines = []
    for r in rows:
        lines.append(f'            row("{r.id}", "{r.source}", "{r.origin}", {r.field}, {r.level}, "{r.kind}", '
                     f'"{r.main}", "{r.second}", "{r.effect}")')
    body = ",\n".join(lines)
    return f'''package com.eternalrealm.item;

import java.util.List;

/**
 * GENERATED by tools/art/named_trinkets.py from tools/art/named_trinkets_data.py (do not edit): the named trinkets of
 * the lords and the dungeons (名品の装身具). {{@link NamedTrinkets}} makes the designs and their numbers from these rows;
 * the row index fixes the model number (5400 + i).
 */
final class NamedTrinketTable {{
    /** One trinket: id, source (LORD / DUNGEON) and its id, field, level, kind, two stats and the effect. */
    record Row(String id, String source, String origin, int field, int level, String kind, String main, String second,
               String effect) {{
    }}

    static final List<Row> ROWS = List.of(
{body});

    private NamedTrinketTable() {{
    }}

    private static Row row(String id, String source, String origin, int field, int level, String kind, String main,
                           String second, String effect) {{
        return new Row(id, source, origin, field, level, kind, main, second, effect);
    }}
}}
'''


def i18n(rows):
    data = {}
    for r in rows:
        data[f"design.{NS}.{r.id}"] = {"ja": r.ja, "en": r.en}
        data[f"design.{NS}.{r.id}.lore"] = {"ja": r.ja_lore, "en": r.en_lore}
    for kind, (ja, en) in KIND_NOUNS.items():
        data[f"trinket_kind.{NS}.{kind.lower()}"] = {"ja": ja, "en": en}
    data[f"dungeon.{NS}.final"] = {"ja": "終焉の玉座", "en": "Throne of the End"}
    return data


def ramp(name):
    return getattr(P, name)


def icon(row):
    metal, gem, cloth = (ramp(name) for name in row.look)
    return trinket_icons.icon(row.kind, metal, gem, cloth)


def overrides():
    """item path -> [(model number, model id)] of the named trinkets (for armory_art.design_overrides)."""
    out = {}
    for i, r in enumerate(named_trinkets_data.load()):
        item = f"{TIER_IDS[tier_of(r.level) - 1]}_{'charm' if is_charm(r) else 'accessory'}"
        out.setdefault(item, []).append((MODELS + i, f"{NS}:item/trinket/{r.id}"))
    return out


def write_json(path, data):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(data, ensure_ascii=False, indent=2))
        f.write("\n")


def generate(assets=ASSETS):
    import armory_art
    rows = named_trinkets_data.load()
    with open(JAVA, "w", encoding="utf-8", newline="\n") as f:
        f.write(java(rows))
    write_json(I18N, i18n(rows))
    tiles = {}
    for r in rows:
        img = icon(r)
        armory_art.save_png(img, os.path.join(assets, "textures", "item", "trinket", f"{r.id}.png"))
        armory_art.write_json(os.path.join(assets, "models", "item", "trinket", f"{r.id}.json"),
                              {"parent": "minecraft:item/generated",
                               "textures": {"layer0": f"{NS}:item/trinket/{r.id}"}})
        tiles[r.id] = img
    patched = armory_art.patch_tier_models(assets)
    print(f"named trinkets: {len(rows)} icons and models, {len(i18n(rows))} texts; {patched} item models patched")
    preview(rows, tiles)


def preview(rows, tiles):
    bg = (30, 26, 34, 255)
    cell = 16 * 3
    per_row = 8
    width = 12 + per_row * (cell + 110) + 8
    lines = (len(rows) + per_row - 1) // per_row
    height = 28 + lines * (cell + 22) + 8
    img = Image.new("RGBA", (width, height), bg)
    d = ImageDraw.Draw(img)
    d.text((8, 6), "Named trinkets: 30 lords, 8 dungeons and the final raid (accessory gold frame, charm blue)",
           fill=(232, 198, 106, 255))
    for i, r in enumerate(rows):
        col, line = i % per_row, i // per_row
        x = 10 + col * (cell + 110)
        y = 26 + line * (cell + 22)
        im = Image.fromarray(tiles[r.id].a, "RGBA").resize((cell, cell), Image.NEAREST)
        d.rectangle((x - 2, y - 2, x + cell + 1, y + cell + 1),
                    outline=(120, 200, 220, 255) if is_charm(r) else (232, 198, 106, 255))
        img.alpha_composite(im, (x, y))
        d.text((x + cell + 6, y + 4), r.origin, fill=(230, 220, 190, 255))
        d.text((x + cell + 6, y + 18), f"Lv{r.level} {r.main}/{r.second}", fill=(170, 160, 150, 255))
        d.text((x + cell + 6, y + 32), r.effect.lower(), fill=(140, 200, 220, 255))
    out = os.path.join(HERE, "named_trinkets_preview.png")
    img.save(out, optimize=True)
    print(f"preview: {os.path.relpath(out, ROOT)} {img.size}")


def check(assets=ASSETS):
    rows = named_trinkets_data.load()
    problems = []
    for r in rows:
        for path in (f"textures/item/trinket/{r.id}.png", f"models/item/trinket/{r.id}.json"):
            if not os.path.isfile(os.path.join(assets, path)):
                problems.append("missing " + path)
    if not os.path.isfile(JAVA) or open(JAVA, encoding="utf-8").read() != java(rows):
        problems.append("NamedTrinketTable.java is out of date")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        problems = check()
        if problems:
            print(*problems[:20], sep="\n")
            sys.exit(1)
        print(f"named trinkets: all {len(named_trinkets_data.ROWS)} have their art, the table is current")
        return
    generate()


if __name__ == "__main__":
    main()
