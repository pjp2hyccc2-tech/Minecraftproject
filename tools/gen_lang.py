def build(base, lines, intro, subs):
    out = dict(base)
    for cat, arr in lines.items():
        for i, s in enumerate(arr):
            out[f'line.satsujinki.{cat}.{i}'] = s
    for typ, arr in intro.items():
        for i, s in enumerate(arr):
            out[f'line.satsujinki.intro.{typ}.{i}'] = s
    for k, v in subs.items():
        out[f'subtitles.satsujinki.{k}'] = v
    return out


def main():
    os.makedirs(OUT, exist_ok=True)
    ja = build(JA, LINES_JA, INTRO_JA, SUBS_JA)
    en = build(EN, LINES_EN, INTRO_EN, SUBS_EN)
    missing = set(ja) ^ set(en)
    if missing:
        raise SystemExit('lang key mismatch: ' + ', '.join(sorted(missing)))
    for name, data in (('ja_jp', ja), ('en_us', en)):
        with open(os.path.join(OUT, name + '.json'), 'w', encoding='utf-8') as f:
            json.dump(data, f, ensure_ascii=False, indent=2, sort_keys=True)
    counts = {k: len(v) for k, v in LINES_JA.items()}
    print('lang done', len(ja), 'keys; line counts', counts)


if __name__ == '__main__':
    main()
