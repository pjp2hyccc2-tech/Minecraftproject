#!/usr/bin/env python3
"""Generates the thin per-program stub files of the HuntCraft shader pack.

Iris/Oculus treat every dimension folder as a completely separate program set, so each
folder needs its own gbuffers_*/deferred/composite/final files.  The real code lives in
shaders/program/*.glsl and shaders/lib/*.glsl; the stubs only #define the dimension and
the program variant and #include the shared source.

Usage:  python3 tools/shader/build_pack.py            (from the repo root)
        python3 tools/shader/build_pack.py --zip out.zip   (also writes a zip of the pack)
"""
import os
import sys
import zipfile

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "main", "shaderpack")
SHADERS = os.path.normpath(os.path.join(ROOT, "shaders"))

VERSION = "#version 330 compatibility"

# program name -> (shared source, extra defines)
PROGRAMS = {
    "shadow": ("program/shadow.glsl", []),
    "gbuffers_basic": ("program/gbuffers.glsl", ["PROG_BASIC"]),
    "gbuffers_textured": ("program/gbuffers.glsl", ["PROG_TEXTURED"]),
    "gbuffers_textured_lit": ("program/gbuffers.glsl", ["PROG_TEXTURED"]),
    "gbuffers_skybasic": ("program/gbuffers_sky.glsl", ["PROG_SKYBASIC"]),
    "gbuffers_skytextured": ("program/gbuffers_sky.glsl", ["PROG_SKYTEXTURED"]),
    "gbuffers_clouds": ("program/gbuffers_sky.glsl", ["PROG_CLOUDS"]),
    "gbuffers_weather": ("program/gbuffers_sky.glsl", ["PROG_WEATHER"]),
    "gbuffers_terrain": ("program/gbuffers.glsl", ["PROG_TERRAIN"]),
    "gbuffers_damagedblock": ("program/gbuffers.glsl", ["PROG_TERRAIN", "PROG_DAMAGE"]),
    "gbuffers_block": ("program/gbuffers.glsl", ["PROG_BLOCK"]),
    "gbuffers_block_translucent": ("program/gbuffers.glsl", ["PROG_BLOCK", "FORWARD"]),
    "gbuffers_entities": ("program/gbuffers.glsl", ["PROG_ENTITIES"]),
    "gbuffers_entities_translucent": ("program/gbuffers.glsl", ["PROG_ENTITIES", "FORWARD"]),
    "gbuffers_spidereyes": ("program/gbuffers.glsl", ["PROG_SPIDEREYES"]),
    "gbuffers_armor_glint": ("program/gbuffers.glsl", ["PROG_GLINT"]),
    "gbuffers_beaconbeam": ("program/gbuffers.glsl", ["PROG_BEACON"]),
    "gbuffers_hand": ("program/gbuffers.glsl", ["PROG_HAND"]),
    "gbuffers_hand_water": ("program/gbuffers.glsl", ["PROG_HAND", "FORWARD"]),
    "gbuffers_water": ("program/gbuffers_water.glsl", []),
    "deferred": ("program/deferred.glsl", []),
    "composite": ("program/composite.glsl", []),
    "composite1": ("program/bloom.glsl", ["BLOOM_EXTRACT"]),
    "composite2": ("program/bloom.glsl", ["BLOOM_BLUR_H"]),
    "composite3": ("program/bloom.glsl", ["BLOOM_BLUR_V"]),
    "final": ("program/final.glsl", []),
}

# folder -> (dimension define, has shadow pass)
FOLDERS = {
    "": ("DIM_OVERWORLD", True),
    "huntcraft_village": ("DIM_VILLAGE", True),
    "huntcraft_hills": ("DIM_HILLS", True),
    "huntcraft_frost": ("DIM_FROST", True),
    "huntcraft_ember": ("DIM_EMBER", True),
    "world-1": ("DIM_NETHER", False),
    "world1": ("DIM_END", False),
}

HEADER = "// generated by tools/shader/build_pack.py - do not edit, edit shaders/program/*.glsl\n"


def stub(stage, dim, defines, source):
    lines = [VERSION, HEADER.rstrip(), "#define " + stage, "#define " + dim]
    lines += ["#define " + d for d in defines]
    lines.append('#include "/%s"' % source)
    return "\n".join(lines) + "\n"


def generate():
    written = []
    for folder, (dim, has_shadow) in FOLDERS.items():
        out_dir = os.path.join(SHADERS, folder) if folder else SHADERS
        os.makedirs(out_dir, exist_ok=True)
        # remove stale generated stubs
        for f in os.listdir(out_dir):
            p = os.path.join(out_dir, f)
            if os.path.isfile(p) and (f.endswith(".vsh") or f.endswith(".fsh")):
                with open(p, encoding="utf-8") as fh:
                    if HEADER.strip() in fh.read():
                        os.remove(p)
        for prog, (source, defines) in PROGRAMS.items():
            if prog == "shadow" and not has_shadow:
                continue
            for ext, stage in (("vsh", "VERTEX_SHADER"), ("fsh", "FRAGMENT_SHADER")):
                p = os.path.join(out_dir, prog + "." + ext)
                with open(p, "w", encoding="utf-8", newline="\n") as fh:
                    fh.write(stub(stage, dim, defines, source))
                written.append(os.path.relpath(p, ROOT))
    return written


def make_zip(path):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _dirs, files in os.walk(ROOT):
            for f in sorted(files):
                full = os.path.join(base, f)
                z.write(full, os.path.relpath(full, ROOT))


if __name__ == "__main__":
    files = generate()
    print("generated %d stub files under %s" % (len(files), SHADERS))
    if "--zip" in sys.argv:
        out = sys.argv[sys.argv.index("--zip") + 1]
        make_zip(out)
        print("wrote", out)
