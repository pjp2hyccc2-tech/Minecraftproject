#!/usr/bin/env python3
"""Generates the thin per-program stub files of the SounanShaders pack.

Iris/Oculus treat every dimension folder as a separate program set, so each folder needs its
own gbuffers_* / deferred / composite* / final stubs. The real code lives in
shaders/program/*.glsl and shaders/lib/*.glsl; a stub only #defines the dimension and the
program variant and #includes the shared source.

  (root)            every dimension not listed below (overworld, mod dimensions ...)
  sounan_kaerazu/   sounan:kaerazu   -> #define SOUNAN_MOUNTAIN (the mountain: fear / danger / camera)
  world-1/          the Nether       -> #define DIM_NETHER (no shadow pass)
  world1/           the End          -> #define DIM_END    (no shadow pass)

Usage:  python3 tools/shader/build_pack.py              regenerate the stubs
        python3 tools/shader/build_pack.py --check      exit 1 if a stub is missing / stale
        python3 tools/shader/build_pack.py --zip X.zip  also write the pack as a zip
"""
import os
import sys
import zipfile

PACK = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "src", "main", "shaderpack"))
SHADERS = os.path.join(PACK, "shaders")

VERSION = "#version 330 compatibility"
HEADER = "// generated by tools/shader/build_pack.py - do not edit; edit shaders/program/*.glsl"

# program -> (shared source, variant defines)
PROGRAMS = {
    "shadow": ("program/shadow.glsl", []),
    "gbuffers_basic": ("program/gbuffers.glsl", ["PROG_BASIC"]),
    "gbuffers_textured": ("program/gbuffers.glsl", ["PROG_TEXTURED"]),
    "gbuffers_textured_lit": ("program/gbuffers.glsl", ["PROG_TEXTURED"]),
    "gbuffers_skybasic": ("program/sky.glsl", ["PROG_SKYBASIC"]),
    "gbuffers_skytextured": ("program/sky.glsl", ["PROG_SKYTEXTURED"]),
    "gbuffers_clouds": ("program/gbuffers.glsl", ["PROG_CLOUDS"]),
    "gbuffers_terrain": ("program/gbuffers.glsl", ["PROG_TERRAIN"]),
    "gbuffers_damagedblock": ("program/gbuffers.glsl", ["PROG_DAMAGE"]),
    "gbuffers_block": ("program/gbuffers.glsl", ["PROG_BLOCK"]),
    "gbuffers_block_translucent": ("program/gbuffers.glsl", ["PROG_BLOCK", "TRANSLUCENT"]),
    "gbuffers_beaconbeam": ("program/gbuffers.glsl", ["PROG_BEACON"]),
    "gbuffers_entities": ("program/gbuffers.glsl", ["PROG_ENTITIES"]),
    "gbuffers_entities_translucent": ("program/gbuffers.glsl", ["PROG_ENTITIES", "TRANSLUCENT"]),
    "gbuffers_armor_glint": ("program/gbuffers.glsl", ["PROG_GLINT"]),
    "gbuffers_spidereyes": ("program/gbuffers.glsl", ["PROG_EYES"]),
    "gbuffers_hand": ("program/gbuffers.glsl", ["PROG_HAND"]),
    "gbuffers_hand_water": ("program/gbuffers.glsl", ["PROG_HAND", "TRANSLUCENT"]),
    "gbuffers_weather": ("program/gbuffers.glsl", ["PROG_WEATHER"]),
    "gbuffers_water": ("program/gbuffers.glsl", ["PROG_WATER"]),
    "deferred": ("program/deferred.glsl", []),
    "composite": ("program/volumetric.glsl", []),
    "composite1": ("program/atmosphere.glsl", []),
    "composite2": ("program/bloom.glsl", ["BLOOM_H"]),
    "composite3": ("program/bloom.glsl", ["BLOOM_V"]),
    "final": ("program/final.glsl", []),
}

# folder -> (dimension define or None, has a shadow pass)
FOLDERS = {
    "": (None, True),
    "sounan_kaerazu": ("SOUNAN_MOUNTAIN", True),
    "world-1": ("DIM_NETHER", False),
    "world1": ("DIM_END", False),
}


def stub(stage, dim, defines, source):
    lines = [VERSION, HEADER, "#define " + stage]
    if dim:
        lines.append("#define " + dim)
    lines += ["#define " + d for d in defines]
    lines.append('#include "/%s"' % source)
    return "\n".join(lines) + "\n"


def expected_files():
    """relative path (to shaders/) -> content"""
    out = {}
    for folder, (dim, has_shadow) in FOLDERS.items():
        for prog, (source, defines) in PROGRAMS.items():
            if prog == "shadow" and not has_shadow:
                continue
            for ext, stage in (("vsh", "VERTEX_SHADER"), ("fsh", "FRAGMENT_SHADER")):
                rel = os.path.join(folder, prog + "." + ext) if folder else prog + "." + ext
                out[rel] = stub(stage, dim, defines, source)
    return out


def generated_on_disk():
    found = []
    for folder in FOLDERS:
        d = os.path.join(SHADERS, folder) if folder else SHADERS
        if not os.path.isdir(d):
            continue
        for f in sorted(os.listdir(d)):
            p = os.path.join(d, f)
            if os.path.isfile(p) and f.endswith((".vsh", ".fsh")):
                with open(p, encoding="utf-8") as fh:
                    if HEADER in fh.read():
                        found.append(os.path.relpath(p, SHADERS))
    return found


def check():
    exp = expected_files()
    bad = []
    for rel, content in exp.items():
        p = os.path.join(SHADERS, rel)
        if not os.path.isfile(p):
            bad.append("missing " + rel)
            continue
        with open(p, encoding="utf-8") as fh:
            if fh.read() != content:
                bad.append("stale   " + rel)
    for rel in generated_on_disk():
        if rel not in exp:
            bad.append("orphan  " + rel)
    return bad


def generate():
    exp = expected_files()
    for rel in generated_on_disk():
        if rel not in exp:
            os.remove(os.path.join(SHADERS, rel))
    for rel, content in exp.items():
        p = os.path.join(SHADERS, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        with open(p, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
    return len(exp)


def make_zip(path):
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as z:
        for base, _dirs, files in os.walk(PACK):
            for f in sorted(files):
                full = os.path.join(base, f)
                z.write(full, os.path.relpath(full, PACK))


if __name__ == "__main__":
    if "--check" in sys.argv:
        problems = check()
        for p in problems:
            print(p)
        print("stubs: %s" % ("OK" if not problems else "%d problem(s)" % len(problems)))
        sys.exit(1 if problems else 0)
    n = generate()
    print("generated %d stub files under %s" % (n, SHADERS))
    if "--zip" in sys.argv:
        out = sys.argv[sys.argv.index("--zip") + 1]
        make_zip(out)
        print("wrote", out)
