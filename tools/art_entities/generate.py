BG = (46, 52, 64, 255)


def to_img(arr):
    return Image.fromarray(arr, 'RGBA')


def compose_rows(rows, pad=6, bg=BG, label_h=12):
    width = max(sum(im.width for im, _ in row) + pad * (len(row) + 1) for row in rows)
    height = sum(max(im.height for im, _ in row) + label_h + pad for row in rows) + pad
    sheet = Image.new('RGBA', (width, height), bg)
    draw = ImageDraw.Draw(sheet)
    y = pad
    for row in rows:
        x = pad
        rh = max(im.height for im, _ in row)
        for im, label in row:
            sheet.alpha_composite(im, (x, y + label_h + rh - im.height))
            draw.text((x, y), label, fill=(230, 230, 230, 255))
            x += im.width + pad
        y += rh + label_h + pad
    return sheet


def preview_rig(rig, painted, ppu, frames=5, scale_preview=False):
    rows = []
    row = []
    for v in rig.variants:
        tex = painted[v.id].img
        im = to_img(ermodel.render(rig, v, tex, ppu=ppu, yaw=32, pitch=10))
        back = to_img(ermodel.render(rig, v, tex, ppu=ppu * 0.6, yaw=200, pitch=10))
        row.append((im, v.id))
        row.append((back, ''))
        if len(row) >= 8:
            rows.append(row)
            row = []
    if row:
        rows.append(row)
    return rows


def anim_sheet(rig, painted, ppu, frames=6):
    rows = []
    seen = set()
    for v in rig.variants:
        names = [rig.slot_anim(v, s).name for s in rig.slots]
        new = [n for n in names if n not in seen]
        if not new and v is not rig.variants[0]:
            continue
        for n in names:
            if n in seen:
                continue
            seen.add(n)
            an = rig.anims[n]
            row = []
            for k in range(frames):
                t = an.length * k / (frames - 1) if not an.loop else an.length * k / frames
                pose = ermodel.evaluate([(an, t)])
                im = to_img(ermodel.render(rig, v, painted[v.id].img, pose=pose, ppu=ppu, yaw=35, pitch=10,
                                           size=(int(ppu * 34), int(ppu * 44)) if rig.name == 'humanoid' else None,
                                           center=None))
                row.append((im, '%s %s t=%.2f' % (v.id, n, t) if k == 0 else 't=%.2f' % t))
            rows.append(row)
    return rows


def write_fx():
    """Boss shield swirl (scrolled by the energy swirl render type, so it must tile): hexagonal cells."""
    size = 64
    img = np.zeros((size, size, 4), np.uint8)
    for y in range(size):
        for x in range(size):
            # distance to the nearest hex cell edge, tiling every 16 x 14 pixels
            cx = (x % 16) - 8
            cy = (y % 14) - 7
            if (y // 14) % 2:
                cx = ((x + 8) % 16) - 8
            d = max(abs(cx) * 0.866 + abs(cy) * 0.5, abs(cy))
            edge = max(0.0, 1.0 - abs(d - 6.0) / 1.6)
            sparkle = 1.0 if (x * 7 + y * 13) % 53 == 0 else 0.0
            v = min(1.0, 0.18 + 0.82 * edge + sparkle)
            img[y, x] = (int(140 * v + 40), int(200 * v + 30), int(255 * v), 255)
    d = os.path.join(TEX_DIR, 'fx')
    os.makedirs(d, exist_ok=True)
    Image.fromarray(img, 'RGBA').save(os.path.join(d, 'boss_shield.png'), optimize=True)


def main(argv):
    names = [a for a in argv if not a.startswith('--')]
    rigs = load_rigs(names or None)
    for rig in rigs:
        ermodel.pack(rig)
        painted = paint_rig(rig)
        write_textures(rig, painted)
        write_java(rig)
        rig.painted = painted
        print('%-10s %3d parts %3d boxes tex %dx%d, %d variants, %d animations' % (
            rig.name, len(rig.parts), len(rig.cubes), rig.tex_w, rig.tex_h, len(rig.variants), len(rig.anims)))
    if not names:
        write_timings(rigs)
        uv_table(rigs)
        write_fx()
    if '--no-preview' in argv:
        return
    all_rows = []
    for rig in rigs:
        ppu = rig.__dict__.get('preview_ppu', 4.0)
        all_rows.extend(preview_rig(rig, rig.painted, ppu))
        sheet = compose_rows(anim_sheet(rig, rig.painted, ppu * 0.75))
        sheet.save(os.path.join(HERE, 'preview_%s.png' % rig.name))
    if not names:
        compose_rows(all_rows).save(os.path.join(HERE, 'preview.png'))
    else:
        compose_rows(all_rows).save(os.path.join(HERE, 'preview_%s_variants.png' % '_'.join(names)))


if __name__ == '__main__':
    main(sys.argv[1:])
