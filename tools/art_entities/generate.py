#!/usr/bin/env python3
"""ETERNAL REALM entity art pipeline (deterministic; needs Pillow and numpy).

Single source of truth for the enemy and boss models: geometry, UV layout, keyframe animations and textures.
Run from anywhere:  python3 tools/art_entities/generate.py [--no-preview]

Writes
  src/main/resources/assets/eternalrealm/textures/entity/<rig>/<variant>.png  (+ <variant>_glow.png)
  src/main/java/com/eternalrealm/client/entity/model/gen/<Rig>Geometry.java / <Rig>Animations.java
  src/main/java/com/eternalrealm/entity/AnimationTimings.java   (animation lengths/impact times for the server)
  tools/art_entities/preview.png (all variants) and tools/art_entities/preview_<rig>.png (animation strips)

UV map: every box gets its own rectangle from the skyline packer in ermodel.pack(); the table is printed with
--uv and kept in tools/art_entities/uv_map.txt so texture edits can be matched to boxes.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np  # noqa: E402
from PIL import Image, ImageDraw  # noqa: E402

import ermodel  # noqa: E402
import erpaint  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
TEX_DIR = os.path.join(ROOT, 'src', 'main', 'resources', 'assets', 'eternalrealm', 'textures', 'entity')
GEN_PKG = 'com.eternalrealm.client.entity.model.gen'
GEN_DIR = os.path.join(ROOT, 'src', 'main', 'java', *GEN_PKG.split('.'))
TIMINGS = os.path.join(ROOT, 'src', 'main', 'java', 'com', 'eternalrealm', 'entity', 'RigData.java')


def load_rigs(names=None):
    import rig_humanoid
    mods = [rig_humanoid]
    for extra in ('rig_beast', 'rig_golem', 'rig_flyer', 'rig_king', 'rig_treant', 'rig_colossus', 'rig_queen',
                  'rig_dragon'):
        try:
            mods.append(__import__(extra))
        except ImportError:
            pass
    rigs = [m.rig() for m in mods]
    if names:
        rigs = [r for r in rigs if r.name in names]
    return rigs


def paint_rig(rig):
    out = {}
    for v in rig.variants:
        def vis(part, v=v):
            return ermodel.visible_chain(rig, v, part)
        p = erpaint.Painter(rig, v, vis)
        p.paint_all()
        if v.paint:
            v.paint(p)
        out[v.id] = p
    return out


def write_textures(rig, painted):
    d = os.path.join(TEX_DIR, rig.name)
    os.makedirs(d, exist_ok=True)
    for vid, p in painted.items():
        Image.fromarray(p.img, 'RGBA').save(os.path.join(d, vid + '.png'), optimize=True)
        glow_path = os.path.join(d, vid + '_glow.png')
        if rig_variant(rig, vid).glow:
            g = p.glow.copy()
            g[..., 3] = np.where(g[..., :3].any(axis=2), 255, 0)
            Image.fromarray(g, 'RGBA').save(glow_path, optimize=True)
        elif os.path.exists(glow_path):
            os.remove(glow_path)


def rig_variant(rig, vid):
    for v in rig.variants:
        if v.id == vid:
            return v
    raise KeyError(vid)


def write_java(rig):
    os.makedirs(GEN_DIR, exist_ok=True)
    with open(os.path.join(GEN_DIR, rig.java_name + 'Geometry.java'), 'w') as f:
        f.write(ermodel.java_geometry(rig, GEN_PKG, rig.java_name + 'Geometry'))
    with open(os.path.join(GEN_DIR, rig.java_name + 'Animations.java'), 'w') as f:
        f.write(ermodel.java_animations(rig, GEN_PKG, rig.java_name + 'Animations'))


def write_timings(rigs):
    L = []
    w = L.append
    jf = ermodel.jf
    w('// GENERATED by tools/art_entities/generate.py. Do not edit: change the script and re-run.')
    w('package com.eternalrealm.entity;')
    w('')
    w('import java.util.List;')
    w('')
    w('/**')
    w(' * Data of the entity rigs shared by server and client: variant ids, model scales, and the length and impact')
    w(' * time (seconds) of every animation slot, so the server times hits, movement locks and death removal to what')
    w(' * the client shows. Slot order: enemies follow {@link EnemyAnim}, bosses follow {@link BossAnimation}.')
    w(' */')
    w('public final class RigData {')
    arrays = {}
    cases = []
    for rig in rigs:
        for v in rig.variants:
            lengths = tuple(round(rig.slot_anim(v, s).length, 4) for s in rig.slots)
            impacts = tuple(round(rig.slot_anim(v, s).impact if rig.slot_anim(v, s).impact is not None
                                  else rig.slot_anim(v, s).length * 0.5, 4) for s in rig.slots)
            key = (lengths, impacts)
            if key not in arrays:
                arrays[key] = 'T%d' % len(arrays)
            cases.append(('%s/%s' % (rig.name, v.id), arrays[key], v.extra.get('scale', 1.0)))
    for (lengths, impacts), name in arrays.items():
        w('    private static final float[] %s_LENGTH = {%s};' % (name, ', '.join(jf(x) for x in lengths)))
        w('    private static final float[] %s_IMPACT = {%s};' % (name, ', '.join(jf(x) for x in impacts)))
    w('')
    w('    private RigData() {')
    w('    }')
    w('')
    w('    /** Variant ids of a rig ("humanoid", "beast", ..., "king", ...), empty if unknown. */')
    w('    public static List<String> variants(String rig) {')
    w('        return switch (rig) {')
    for rig in rigs:
        w('            case "%s" -> List.of(%s);' % (rig.name, ', '.join('"%s"' % v.id for v in rig.variants)))
    w('            default -> List.of();')
    w('        };')
    w('    }')
    w('')
    w('    /** Model and hitbox scale of {@code rig/variant} (1 if unknown). */')
    w('    public static float scale(String rig, String variant) {')
    w('        return switch (rig + "/" + variant) {')
    by_scale = {}
    for k, _, s in cases:
        by_scale.setdefault(s, []).append(k)
    for s, keys in by_scale.items():
        if s == 1.0:
            continue
        w('            case %s -> %s;' % (', '.join('"%s"' % k for k in keys), jf(s)))
    w('            default -> 1.0F;')
    w('        };')
    w('    }')
    w('')
    w('    /** Hitbox {width, height} in blocks of a boss look (bosses only; {1, 2} if unknown). */')
    w('    public static float[] hitbox(String rig, String variant) {')
    w('        return switch (rig + "/" + variant) {')
    for rig in rigs:
        for v in rig.variants:
            hb = v.extra.get('hitbox')
            if hb:
                w('            case "%s/%s" -> new float[]{%s, %s};' % (rig.name, v.id, jf(hb[0]), jf(hb[1])))
    w('            default -> new float[]{1.0F, 2.0F};')
    w('        };')
    w('    }')
    w('')
    w('    /** Seconds of the animation in {@code slot} for {@code rig/variant}, or 1 if unknown. */')
    w('    public static float length(String rig, String variant, int slot) {')
    w('        float[] values = lengths(rig + "/" + variant);')
    w('        return values != null && slot >= 0 && slot < values.length ? values[slot] : 1.0F;')
    w('    }')
    w('')
    w('    /** Seconds from the start of the animation in {@code slot} to its hit frame. */')
    w('    public static float impact(String rig, String variant, int slot) {')
    w('        float[] values = impacts(rig + "/" + variant);')
    w('        return values != null && slot >= 0 && slot < values.length ? values[slot] : 0.5F;')
    w('    }')
    for kind in ('LENGTH', 'IMPACT'):
        w('')
        w('    private static float[] %s(String key) {' % ('lengths' if kind == 'LENGTH' else 'impacts'))
        w('        return switch (key) {')
        by_arr = {}
        for k, name, _ in cases:
            by_arr.setdefault(name, []).append(k)
        for name, keys in by_arr.items():
            w('            case %s -> %s_%s;' % (', '.join('"%s"' % k for k in keys), name, kind))
        w('            default -> null;')
        w('        };')
        w('    }')
    w('}')
    os.makedirs(os.path.dirname(TIMINGS), exist_ok=True)
    with open(TIMINGS, 'w') as f:
        f.write('\n'.join(L) + '\n')


def uv_table(rigs):
    lines = ['UV map (rig, part, box index, material, texOffs u v, size w h d, mirror/share)']
    for rig in rigs:
        lines.append('== %s %dx%d' % (rig.name, rig.tex_w, rig.tex_h))
        for p in rig.parts.values():
            for i, c in enumerate(p.cubes):
                lines.append('%-12s %-16s %d %-16s %4d %4d   %2d %2d %2d %s' % (
                    rig.name, p.name, i, c.mat, c.u, c.v, c.w, c.h, c.d,
                    ('mirror ' if c.mirror else '') + ('share=' + c.share if c.share else '')))
    with open(os.path.join(HERE, 'uv_map.txt'), 'w') as f:
        f.write('\n'.join(lines) + '\n')


