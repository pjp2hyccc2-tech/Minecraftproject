#!/usr/bin/env python3
"""ETERNAL REALM hero art pipeline (deterministic; needs Pillow and numpy): the four legendary travellers.

  rig_hero.py    geometry of the hero rig and the animation kit
  hero_anims.py  every animation of the four (idle, walk, run, ready, talk, two attacks, two skills, the ultimate,
                 fallen, joining)
  hero_cast.py   the four looks (parts, palettes, painting)
  hero_paint.py  painting helpers at two texels per unit (faces, hair, cloth, metal, glow)
Run from anywhere:  python3 tools/art_entities/generate_hero.py [--no-preview] [ids: preview only those]
  HERO_ANIM=<anim name> with ids: also a strip of that animation (/tmp/herowork/anim.png)

Writes
  src/main/resources/assets/eternalrealm/textures/entity/hero/<id>.png (+ <id>_glow.png)
  src/main/resources/assets/eternalrealm/textures/gui/portrait/<id>.png  (96x96 busts; the dialogue box draws them
      at 48x48 GUI pixels, so they stay sharp at GUI scale 2)
  src/main/java/com/eternalrealm/client/entity/model/gen/HeroGeometry.java / HeroAnimations.java
  src/main/java/com/eternalrealm/npc/HeroBodies.java  (ids, scales, the length and hit times of every move; pure, for
      the server)
  tools/art_entities/preview_hero.png, preview_hero_anim.png, preview_hero_portraits.png
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

import ermodel  # noqa: E402
import generate  # noqa: E402
import generate_npc  # noqa: E402
import rig_hero  # noqa: E402

ROOT = generate.ROOT
BODIES = os.path.join(ROOT, 'src', 'main', 'java', 'com', 'eternalrealm', 'npc', 'HeroBodies.java')
PORTRAIT = 96
PORTRAIT_PPU = 6.0


def build():
    rig = rig_hero.rig()
    ermodel.pack(rig)
    painted = generate.paint_rig(rig)
    return rig, painted


# ------------------------------------------------------------------------------------------------ portraits

def portrait(rig, v, tex):
    spec = v.extra.get('portrait') or {}
    yaw = spec.get('yaw', -24.0)
    ppu = PORTRAIT_PPU * spec.get('zoom', 1.0)
    dy = spec.get('dy', 0.0)
    hidden = set(spec.get('hide', ())) - v.hide
    v.hide |= hidden
    try:
        pose = None
        if spec.get('pose'):
            pose = ermodel.evaluate([(rig.anims[spec['pose']], spec.get('pose_t', 0.0))])
        model = ermodel.render(rig, v, tex, pose=pose, yaw=yaw, pitch=4.0, ppu=ppu, size=(PORTRAIT, PORTRAIT),
                               center=(0.6, -4.5 + dy))
    finally:
        v.hide -= hidden
    bg = spec.get('bg', ('#5a6a8a', '#161c2a'))
    img = generate_npc.backdrop(bg[0], bg[1], PORTRAIT).astype(np.float64)
    alpha = model[..., 3] > 0
    pad = np.pad(alpha, 1)
    ring = (pad[:-2, 1:-1] | pad[2:, 1:-1] | pad[1:-1, :-2] | pad[1:-1, 2:]) & ~alpha
    img[ring, :3] *= 0.4
    img[alpha, :3] = model[alpha, :3]
    return Image.fromarray(img.astype(np.uint8), 'RGBA')


def write_portraits(rig, painted):
    os.makedirs(generate_npc.PORTRAIT_DIR, exist_ok=True)
    out = {}
    for v in rig.variants:
        im = portrait(rig, v, painted[v.id].img)
        im.save(os.path.join(generate_npc.PORTRAIT_DIR, v.id + '.png'), optimize=True)
        out[v.id] = im
    return out


# ------------------------------------------------------------------------------------------------ java

def write_java(rig):
    generate.write_java(rig)
    for name in ('Geometry', 'Animations'):
        path = os.path.join(generate.GEN_DIR, rig.java_name + name + '.java')
        with open(path) as f:
            text = f.read()
        with open(path, 'w') as f:
            f.write(text.replace('tools/art_entities/generate.py', 'tools/art_entities/generate_hero.py', 1))


def write_bodies(rig):
    jf = ermodel.jf
    L = []
    w = L.append
    ids = [v.id for v in rig.variants]
    w('// GENERATED by tools/art_entities/generate_hero.py. Do not edit: change the script and re-run.')
    w('package com.eternalrealm.npc;')
    w('')
    w('import java.util.List;')
    w('')
    w('/**')
    w(' * The bodies of the four travellers (pure data, shared by server and client): appearance ids, model scales and')
    w(' * the timing of every animation slot: its length and the moments its blows land (seconds), so the server lands')
    w(' * a hit when the body swings it. Textures are {@code textures/entity/hero/<id>.png}, portraits')
    w(' * {@code textures/gui/portrait/<id>.png}.')
    w(' */')
    w('public final class HeroBodies {')
    w('    /** Every appearance id. */')
    w('    public static final List<String> APPEARANCES = List.of(%s);' % ', '.join('"%s"' % i for i in ids))
    w('    /** Animation slots, in the order of the model\'s tables. */')
    w('    public static final List<String> SLOTS = List.of(%s);' % ', '.join('"%s"' % s for s in rig.slots))
    for i, s in enumerate(rig.slots):
        w('    public static final int %s = %d;' % (s.upper(), i))
    w('')
    w('    private HeroBodies() {')
    w('    }')
    w('')
    w('    public static boolean exists(String id) {')
    w('        return APPEARANCES.contains(id);')
    w('    }')
    w('')
    w('    /** Model (and hitbox) scale of an appearance (1 if unknown). */')
    w('    public static float scale(String id) {')
    w('        return switch (id == null ? "" : id) {')
    for v in rig.variants:
        w('            case "%s" -> %s;' % (v.id, jf(float(v.extra.get('scale', 1.0)))))
    w('            default -> 1.0F;')
    w('        };')
    w('    }')
    w('')
    w('    /** Length (seconds) of the animation in {@code slot} for an appearance (0 if unknown). */')
    w('    public static float length(String id, int slot) {')
    w('        float[] lengths = switch (id == null ? "" : id) {')
    for v in rig.variants:
        w('            case "%s" -> new float[]{%s};' % (v.id, ', '.join(jf(rig.slot_anim(v, s).length)
                                                                        for s in rig.slots)))
        pass
    w('            default -> null;')
    w('        };')
    w('        return lengths == null || slot < 0 || slot >= lengths.length ? 0.0F : lengths[slot];')
    w('    }')
    w('')
    w('    /** The moments (seconds from the start) the blows of the animation in {@code slot} land; none if unknown. */')
    w('    public static float[] hits(String id, int slot) {')
    w('        return switch ((id == null ? "" : id) + "/" + slot) {')
    for v in rig.variants:
        for i, s in enumerate(rig.slots):
            an = rig.slot_anim(v, s)
            hits = rig_hero.HITS.get(an.name)
            if hits:
                w('            case "%s/%d" -> new float[]{%s};' % (v.id, i, ', '.join(jf(h) for h in hits)))
    w('            default -> new float[0];')
    w('        };')
    w('    }')
    w('}')
    with open(BODIES, 'w') as f:
        f.write('\n'.join(L) + '\n')


# ------------------------------------------------------------------------------------------------ previews

def views(rig, v, tex, ppu=6.0, pose=None):
    out = []
    for yaw, label in ((0, v.id), (35, ''), (150, ''), (200, '')):
        im = Image.fromarray(ermodel.render(rig, v, tex, pose=pose, yaw=yaw, pitch=8, ppu=ppu,
                                            size=(int(ppu * 30), int(ppu * 58)), center=(0, 3)))
        out.append((im, label))
    return out


def preview(rig, painted, path, ppu=6.0, ids=None):
    rows = []
    for v in rig.variants:
        if ids and v.id not in ids:
            continue
        rows.append(views(rig, v, painted[v.id].img, ppu))
    generate.compose_rows(rows).save(path)


def strip(rig, v, tex, an, ppu=4.0, frames=8, yaw=30):
    row = []
    for k in range(frames):
        t = an.length * k / frames if an.loop else an.length * k / (frames - 1)
        pose = ermodel.evaluate([(an, t)])
        im = Image.fromarray(ermodel.render(rig, v, tex, pose=pose, yaw=yaw, pitch=8, ppu=ppu,
                                            size=(int(ppu * 44), int(ppu * 58)), center=(0, 3)))
        row.append((im, '%s %.2f' % (an.name, t) if k == 0 else '%.2f' % t))
    return row


def anim_sheet(rig, painted, path, ppu=3.0):
    rows = []
    for v in rig.variants:
        for slot in rig.slots:
            an = rig.slot_anim(v, slot)
            rows.append(strip(rig, v, painted[v.id].img, an, ppu, frames=8))
    generate.compose_rows(rows).save(path)


def portrait_sheet(portraits, path):
    row = [(im.resize((PORTRAIT * 2, PORTRAIT * 2), Image.NEAREST), vid) for vid, im in portraits.items()]
    generate.compose_rows([row]).save(path)


def main(argv):
    rig, painted = build()
    ids = [a for a in argv if not a.startswith('--')]
    print('hero: %d parts %d boxes tex %dx%d (x%d), %d looks, %d animations' % (
        len(rig.parts), len(rig.cubes), rig.tex_w, rig.tex_h, rig.texel, len(rig.variants), len(rig.anims)))
    if ids:
        os.makedirs('/tmp/herowork', exist_ok=True)
        ppu = float(os.environ.get('HERO_PPU', '6'))
        preview(rig, painted, '/tmp/herowork/preview_sel.png', ppu=ppu, ids=ids)
        name = os.environ.get('HERO_ANIM')
        if name:
            rows = []
            for vid in ids:
                v = generate.rig_variant(rig, vid)
                for n in name.split(','):
                    an = rig.anims[n] if n in rig.anims else rig.slot_anim(v, n)
                    rows.append(strip(rig, v, painted[vid].img, an, float(os.environ.get('HERO_APPU', '4')),
                                      frames=int(os.environ.get('HERO_FRAMES', '8')),
                                      yaw=float(os.environ.get('HERO_YAW', '30'))))
            generate.compose_rows(rows).save('/tmp/herowork/anim.png')
        if os.environ.get('HERO_PORTRAIT'):
            portrait_sheet({vid: portrait(rig, generate.rig_variant(rig, vid), painted[vid].img) for vid in ids},
                           '/tmp/herowork/portraits.png')
        return
    generate.write_textures(rig, painted)
    write_java(rig)
    write_bodies(rig)
    portraits = write_portraits(rig, painted)
    if '--no-preview' in argv:
        return
    preview(rig, painted, os.path.join(HERE, 'preview_hero.png'))
    portrait_sheet(portraits, os.path.join(HERE, 'preview_hero_portraits.png'))
    anim_sheet(rig, painted, os.path.join(HERE, 'preview_hero_anim.png'))


if __name__ == '__main__':
    main(sys.argv[1:])
